					epfvv.Guid,
					N'P',
					@StageMatchesActivity,
					0,
					1 - @StageMatchesActivity,
					CASE
						WHEN @StageMatchesActivity = 1 THEN N''
						ELSE N'The RIBA stage must be the selected Activity''s stage: ' + ISNULL(@ActivityRibaStageLabel, N'') + N'.'
					END
				FROM SCore.EntityPropertiesForValidationV AS epfvv
				WHERE epfvv.[Schema] = N'SFin'
				  AND epfvv.Hobt = N'InvoiceRequestItems'
				  AND epfvv.Name IN (N'RIBAStageId');
			END;

			

    RETURN;
