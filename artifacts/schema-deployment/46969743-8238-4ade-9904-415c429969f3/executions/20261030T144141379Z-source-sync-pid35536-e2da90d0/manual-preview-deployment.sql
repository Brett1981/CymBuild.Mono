                            ELSE N''
                        END
            FROM SFin.InvoiceRequests AS r
            JOIN Totals AS t
                ON t.ID = r.ID
            LEFT JOIN Reasons AS rs
                ON rs.ID = r.ID;

            SET @CreatedInvoiceRequests =
            (
                SELECT COUNT(1)
                FROM #InsertedRequests
