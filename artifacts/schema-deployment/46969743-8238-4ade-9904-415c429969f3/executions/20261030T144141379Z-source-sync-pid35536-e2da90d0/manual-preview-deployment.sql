		WHERE (a.Guid = @ActivityGuid)
		  AND (a.RowStatus NOT IN (0, 254))
		  AND (rs.ID > 0)
		  AND (rs.RowStatus NOT IN (0, 254));

		IF (@ActivityRibaStageGuid IS NOT NULL)
			BEGIN
