/*
	CYB-580: how much of the agreed fee is left for an invoice request item.

	One calculation shared by every route that creates invoice request items, so the manual route
	(SFin.InvoiceRequestItemsUpsert) and invoice automation
	(SFin.InvoiceAutomation_CreateInvoiceRequests_FromTriggerInstances) cannot drift apart.

	An item on a RIBA stage is checked against that stage. An item with no stage (NULL or the -1
	sentinel) is checked against the job total (StageId -3, "Total (inc. Fee Cap)").
	SJob.Job_FeeDrawdown.Remaining only subtracts posted invoices, so CommittedFee also includes
	invoices still Batched for approval and, when @IncludeOpenRequestItems = 1, Invoice Request
	Items not yet on an invoice (saving a request item reserves fee against other requests;
	creating an invoice is checked only against invoices, so a flagged request cannot block a
	valid one). @ExcludeItemGuid leaves an item's own value out, so re-saving it is not counted
	twice.
*/
CREATE OR ALTER FUNCTION [SFin].[tvf_InvoiceRequestItemFeeCheck]
(
	  @JobId			INT
	, @RIBAStageId		INT
	, @ExcludeItemGuid	UNIQUEIDENTIFIER
	, @IncludeOpenRequestItems	BIT
)
RETURNS TABLE
AS
RETURN
	WITH FeeStage AS
	(
		SELECT
			FeeStageId = CASE WHEN ISNULL(@RIBAStageId, -1) = -1 THEN -3 ELSE @RIBAStageId END
	)
	SELECT
		  fs.FeeStageId
		, FeeStageLabel	= COALESCE(fd.StageLabel, rs.Description)
		, AgreedFee		= CAST(ISNULL(fd.Agreed, 0) AS DECIMAL(19,2))
		, CommittedFee	= CAST(ISNULL(c.Net, 0) AS DECIMAL(19,2))
		, RemainingFee	= CAST(ISNULL(fd.Agreed, 0) - ISNULL(c.Net, 0) AS DECIMAL(19,2))
	FROM FeeStage AS fs
	LEFT JOIN SJob.Job_FeeDrawdown AS fd
		ON fd.JobId = @JobId
	   AND fd.StageId = fs.FeeStageId
	LEFT JOIN SJob.RibaStages AS rs
		ON rs.ID = fs.FeeStageId
	   AND fs.FeeStageId <> -3
	OUTER APPLY
	(
		SELECT
			Net = SUM(committed.Net)
		FROM
		(
			--Invoices and credit notes, posted or still Batched for approval. A rejected batched
			--invoice is archived (RowStatus 200); its request then counts below as not yet invoiced.
			SELECT
				td.Net * CASE WHEN tt.IsNegated = 1 THEN -1 ELSE 1 END AS Net
			FROM SFin.TransactionDetails AS td
			INNER JOIN SFin.Transactions AS t
				ON t.ID = td.TransactionID
			   AND t.JobID = @JobId
			   AND t.RowStatus NOT IN (0,200,254)
			INNER JOIN SFin.TransactionTypes AS tt
				ON tt.ID = t.TransactionTypeID
			   AND tt.RowStatus NOT IN (0,254)
			   AND tt.IsBank = 0
			LEFT JOIN SJob.Activities AS a
				ON a.ID = td.ActivityID
			   AND a.JobID = @JobId
			   AND a.RowStatus NOT IN (0,254)
			LEFT JOIN SFin.InvoiceRequestItems AS tiri
				ON tiri.ID = td.InvoiceRequestItemId
			   AND tiri.RowStatus NOT IN (0,254)
			WHERE td.RowStatus NOT IN (0,254)
			  AND NOT EXISTS
			  (
				  SELECT 1
				  FROM SFin.InvoiceRequestItems AS xiri
				  WHERE xiri.ID = td.InvoiceRequestItemId
					AND xiri.[Guid] = @ExcludeItemGuid
			  )
			  AND
			  (
					 fs.FeeStageId = -3
				  OR td.RIBAStageID = fs.FeeStageId
				  OR a.RibaStageId = fs.FeeStageId
				  OR tiri.RIBAStageId = fs.FeeStageId
			  )

			UNION ALL

			--Invoice Request Items not yet on an invoice.
			SELECT
				oiri.Net
			FROM SFin.InvoiceRequestItems AS oiri
			INNER JOIN SFin.InvoiceRequests AS oir
				ON oir.ID = oiri.InvoiceRequestId
			   AND oir.JobId = @JobId
			   AND oir.RowStatus NOT IN (0,254)
			LEFT JOIN SJob.Activities AS oa
				ON oa.ID = oiri.ActivityId
			   AND oa.RowStatus NOT IN (0,254)
			WHERE @IncludeOpenRequestItems = 1
			  AND oiri.RowStatus NOT IN (0,254)
			  AND oiri.ID > 0
			  AND (@ExcludeItemGuid IS NULL OR oiri.[Guid] <> @ExcludeItemGuid)
			  AND
			  (
					 fs.FeeStageId = -3
				  OR oiri.RIBAStageId = fs.FeeStageId
				  OR oa.RibaStageId = fs.FeeStageId
			  )
			  AND NOT EXISTS
			  (
				  SELECT 1
				  FROM SFin.TransactionDetails AS otd
				  INNER JOIN SFin.Transactions AS ot
					  ON ot.ID = otd.TransactionID
					 AND ot.RowStatus NOT IN (0,200,254)
				  WHERE otd.InvoiceRequestItemId = oiri.ID
					AND otd.RowStatus NOT IN (0,254)
			  )
		) AS committed
	) AS c;
