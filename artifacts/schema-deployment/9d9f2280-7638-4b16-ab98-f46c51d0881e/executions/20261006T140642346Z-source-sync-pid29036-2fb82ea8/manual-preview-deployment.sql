/*
    CYB-574: checks that an applied metadata run actually converged.

    Apply trusts each table's upsert procedure and its natural-key matching. On QA2 several rows
    reported "applied" while nothing changed (a HoBT the upsert could not re-activate, Quote
    properties updated through a stale same-name duplicate, an EntityTypes flag the upsert has
    no parameter for), and that was only noticed three runs later. This re-compares every row the
    apply wrote against its source payload and records each one that still differs as a Warn
    'ApplyDidNotConverge' issue on the run.

    It re-uses Stage's own comparison rather than a second copy of it: the run's staged rows are
    copied into a throwaway verification run, the applied rows get their post-apply target
    payload (same column list as MetadataStage_Run), and MetadataStage_NormaliseDifferences
    classifies them exactly as a fresh Stage would. The verification run is then removed.

    Advisory only: it runs after the apply transaction has committed (Concursus.EF
    MetadataMigrationRepository.ApplyAsync), never rethrows, and logs its own failure.
*/
CREATE OR ALTER PROCEDURE [SMigration].[MetadataApply_VerifyConvergence]
(
    @RunGuid UNIQUEIDENTIFIER
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE
        @VerifyRunGuid UNIQUEIDENTIFIER = NEWID(),
        @TargetDatabaseName SYSNAME,
        @CheckedCount INT = 0,
        @NotConvergedCount INT = 0,
        @RegistryGuid UNIQUEIDENTIFIER,
        @SchemaName SYSNAME,
        @TableName SYSNAME,
        @GuidColumnName SYSNAME,
        @ColumnList NVARCHAR(MAX),
        @Sql NVARCHAR(MAX),
        @DetailsJson NVARCHAR(MAX),
        @StepStatus NVARCHAR(15),
        @ErrorMessage NVARCHAR(4000);

    BEGIN TRY
        SELECT
            @TargetDatabaseName = run.TargetDatabaseName
        FROM SMigration.Metadata_Run AS run
        WHERE run.Guid = @RunGuid
          AND run.RowStatus NOT IN (0,254)
          AND run.AppliedOnUtc IS NOT NULL;

        IF @TargetDatabaseName IS NULL
            RETURN;

        IF OBJECT_ID(N'tempdb..#ConvergenceRows') IS NOT NULL
            DROP TABLE #ConvergenceRows;

        CREATE TABLE #ConvergenceRows
        (
            RegistryGuid UNIQUEIDENTIFIER NOT NULL,
            SourceRowGuid UNIQUEIDENTIFIER NOT NULL,
            TargetRowGuid UNIQUEIDENTIFIER NOT NULL,
            CONSTRAINT PK_ConvergenceRows PRIMARY KEY CLUSTERED (RegistryGuid, SourceRowGuid)
        );

        -- The rows the apply wrote: selected Insert/Update rows that are not ignored. The target
        -- row is the override's, else the naturalised target identity, else the source Guid -
        -- the same order MetadataApply_Run resolves with.
        INSERT INTO #ConvergenceRows
        (
            RegistryGuid,
            SourceRowGuid,
            TargetRowGuid
        )
        SELECT DISTINCT
            sr.RegistryGuid,
            sr.SourceRowGuid,
            COALESCE
            (
                ov.TargetRowGuid,
                TRY_CONVERT(UNIQUEIDENTIFIER, JSON_VALUE(sr.TargetPayloadJson, N'$.' + tr.GuidColumnName)),
                sr.SourceRowGuid
            )
        FROM SMigration.Metadata_StagedRows AS sr
        INNER JOIN SMigration.Metadata_RunSelections AS selection
            ON selection.RunGuid = sr.RunGuid
           AND selection.RegistryGuid = sr.RegistryGuid
           AND selection.SourceRowGuid = sr.SourceRowGuid
           AND selection.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_TableRegistry AS tr
            ON tr.Guid = sr.RegistryGuid
           AND tr.RowStatus NOT IN (0,254)
        LEFT JOIN SMigration.Metadata_IdentityMapOverrides AS ov
            ON ov.DatabaseName = @TargetDatabaseName
           AND ov.RegistryGuid = sr.RegistryGuid
           AND ov.SourceRowGuid = sr.SourceRowGuid
           AND ov.RowStatus NOT IN (0,254)
        WHERE sr.RunGuid = @RunGuid
          AND sr.RowStatus NOT IN (0,254)
          AND sr.DifferenceType IN (N'Insert', N'Update')
          AND NOT EXISTS
          (
              SELECT 1
              FROM SMigration.Metadata_IgnoredRecords AS ignored
              WHERE ignored.DatabaseName = @TargetDatabaseName
                AND ignored.RegistryGuid = sr.RegistryGuid
                AND ignored.SourceRowGuid = sr.SourceRowGuid
                AND ignored.RowStatus NOT IN (0,254)
          );

        SET @CheckedCount = @@ROWCOUNT;

        BEGIN TRANSACTION;

        INSERT INTO SMigration.Metadata_Run
        (
            Guid,
            RowStatus,
            SourceEnvironment,
            TargetEnvironment,
            SourceServerName,
            SourceDatabaseName,
            TargetServerName,
            TargetDatabaseName,
            RunStatus,
            IsValidateOnly,
            CreatedOnUtc,
            CreatedByUserId,
            SummaryJson
        )
        SELECT
            @VerifyRunGuid,
            1,
            run.SourceEnvironment,
            run.TargetEnvironment,
            run.SourceServerName,
            run.SourceDatabaseName,
            run.TargetServerName,
            run.TargetDatabaseName,
            N'ConvergenceCheck',
            1,
            SYSUTCDATETIME(),
            run.CreatedByUserId,
            N'{}'
        FROM SMigration.Metadata_Run AS run
        WHERE run.Guid = @RunGuid;

        -- Every staged row is copied, because the normalisation resolves foreign keys through the
        -- run's staged rows. Only the applied rows are compared; the rest are marked NoChange.
        INSERT INTO SMigration.Metadata_StagedRows
        (
            Guid,
            RowStatus,
            RunGuid,
            RegistryGuid,
            SourceRowGuid,
            SourceRowId,
            SourceRowStatus,
            SourcePayloadJson,
            SourcePayloadHash,
            TargetPayloadJson,
            TargetPayloadHash,
            DifferenceType,
            CreatedOnUtc
        )
        SELECT
            NEWID(),
            1,
            @VerifyRunGuid,
            sr.RegistryGuid,
            sr.SourceRowGuid,
            sr.SourceRowId,
            sr.SourceRowStatus,
            sr.SourcePayloadJson,
            sr.SourcePayloadHash,
            sr.TargetPayloadJson,
            sr.TargetPayloadHash,
            N'NoChange',
            SYSUTCDATETIME()
        FROM SMigration.Metadata_StagedRows AS sr
        WHERE sr.RunGuid = @RunGuid
          AND sr.RowStatus NOT IN (0,254);

        DECLARE registry_cursor CURSOR LOCAL FAST_FORWARD FOR
            SELECT DISTINCT
                tr.Guid,
                tr.SchemaName,
                tr.TableName,
                tr.GuidColumnName
            FROM #ConvergenceRows AS c
            INNER JOIN SMigration.Metadata_TableRegistry AS tr
                ON tr.Guid = c.RegistryGuid
            WHERE OBJECT_ID(QUOTENAME(tr.SchemaName) + N'.' + QUOTENAME(tr.TableName), N'U') IS NOT NULL;

        OPEN registry_cursor;

        FETCH NEXT FROM registry_cursor
        INTO @RegistryGuid, @SchemaName, @TableName, @GuidColumnName;

        WHILE @@FETCH_STATUS = 0
        BEGIN
            -- Same column list as MetadataStage_Run's same-server path.
            SET @ColumnList = NULL;

            SELECT
                @ColumnList =
                    STRING_AGG(CONVERT(NVARCHAR(MAX), QUOTENAME(c.name)), N',')
                    WITHIN GROUP (ORDER BY c.column_id)
            FROM sys.schemas AS s
            INNER JOIN sys.tables AS t
                ON t.schema_id = s.schema_id
            INNER JOIN sys.columns AS c
                ON c.object_id = t.object_id
            WHERE s.name = @SchemaName
              AND t.name = @TableName
              AND c.is_computed = 0
              AND c.system_type_id <> 189;

            IF @ColumnList IS NOT NULL
            BEGIN
                SET @Sql = N'
UPDATE v
SET TargetPayloadJson =
    (
        SELECT ' + @ColumnList + N'
        FROM ' + QUOTENAME(@SchemaName) + N'.' + QUOTENAME(@TableName) + N' AS tj
        WHERE tj.' + QUOTENAME(@GuidColumnName) + N' = c.TargetRowGuid
        FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
    )
FROM SMigration.Metadata_StagedRows AS v
INNER JOIN #ConvergenceRows AS c
    ON c.RegistryGuid = v.RegistryGuid
   AND c.SourceRowGuid = v.SourceRowGuid
WHERE v.RunGuid = @VerifyRunGuid
  AND c.RegistryGuid = @RegistryGuid;';

                EXEC sys.sp_executesql
                    @Sql,
                    N'@VerifyRunGuid UNIQUEIDENTIFIER, @RegistryGuid UNIQUEIDENTIFIER',
                    @VerifyRunGuid = @VerifyRunGuid,
                    @RegistryGuid = @RegistryGuid;
            END;

            FETCH NEXT FROM registry_cursor
            INTO @RegistryGuid, @SchemaName, @TableName, @GuidColumnName;
        END;

        CLOSE registry_cursor;
        DEALLOCATE registry_cursor;

        UPDATE v
        SET TargetPayloadHash = CASE
                WHEN v.TargetPayloadJson IS NULL THEN NULL
                ELSE HASHBYTES('SHA2_256', CONVERT(VARBINARY(MAX), v.TargetPayloadJson))
            END,
            DifferenceType = CASE
                WHEN v.TargetPayloadJson IS NULL THEN N'Insert'
                WHEN v.SourcePayloadHash = HASHBYTES('SHA2_256', CONVERT(VARBINARY(MAX), v.TargetPayloadJson)) THEN N'NoChange'
                ELSE N'Update'
            END
        FROM SMigration.Metadata_StagedRows AS v
        INNER JOIN #ConvergenceRows AS c
            ON c.RegistryGuid = v.RegistryGuid
           AND c.SourceRowGuid = v.SourceRowGuid
        WHERE v.RunGuid = @VerifyRunGuid;

        EXEC SMigration.MetadataStage_NormaliseDifferences
            @RunGuid = @VerifyRunGuid;

        DELETE FROM SMigration.Metadata_ValidationIssues
        WHERE RunGuid = @RunGuid
          AND IssueCode = N'ApplyDidNotConverge';

        INSERT INTO SMigration.Metadata_ValidationIssues
        (
            Guid,
            RowStatus,
            RunGuid,
            RegistryGuid,
            SourceRowGuid,
            Severity,
            IssueCode,
            IssueMessage,
            DetailsJson,
            CreatedOnUtc
        )
        SELECT
            NEWID(),
            1,
            @RunGuid,
            v.RegistryGuid,
            v.SourceRowGuid,
            N'Warn',
            N'ApplyDidNotConverge',
            LEFT(CONCAT
            (
                tr.SchemaName, N'.', tr.TableName, N' row ',
                COALESCE(N'''' + JSON_VALUE(v.SourcePayloadJson, N'$.Name') + N''' ', N''),
                CONVERT(NVARCHAR(36), v.SourceRowGuid),
                CASE WHEN v.TargetPayloadJson IS NULL
                     THEN N' was applied but is still missing from the target.'
                     ELSE CONCAT(N' was applied but still differs from the source (', ISNULL(diff.KeyList, N'foreign key'), N').')
                END
            ), 4000),
            CONCAT
            (
                N'{"targetRowGuid":"', CONVERT(NVARCHAR(36), c.TargetRowGuid),
                N'","columns":"', STRING_ESCAPE(ISNULL(diff.KeyList, N''), 'json'), N'"}'
            ),
            SYSUTCDATETIME()
        FROM SMigration.Metadata_StagedRows AS v
        INNER JOIN #ConvergenceRows AS c
            ON c.RegistryGuid = v.RegistryGuid
           AND c.SourceRowGuid = v.SourceRowGuid
        INNER JOIN SMigration.Metadata_TableRegistry AS tr
            ON tr.Guid = v.RegistryGuid
        OUTER APPLY
        (
            -- Raw differing columns for the message. Foreign-key IDs always differ between
            -- environments, so ID-named columns are left out of the list (the normalisation
            -- above has already compared them by Guid).
            SELECT
                STRING_AGG(CONVERT(NVARCHAR(MAX), k.KeyName), N', ') AS KeyList
            FROM
            (
                SELECT COALESCE(src.[key], tgt.[key]) COLLATE DATABASE_DEFAULT AS KeyName
                FROM OPENJSON(v.SourcePayloadJson) AS src
                FULL OUTER JOIN OPENJSON(v.TargetPayloadJson) AS tgt
                    ON tgt.[key] COLLATE DATABASE_DEFAULT = src.[key] COLLATE DATABASE_DEFAULT
                WHERE ISNULL(src.[value], N'~') <> ISNULL(tgt.[value], N'~')
            ) AS k
            WHERE k.KeyName NOT LIKE N'%ID'
              AND k.KeyName NOT LIKE N'%Id'
        ) AS diff
        WHERE v.RunGuid = @VerifyRunGuid
          AND v.DifferenceType IN (N'Insert', N'Update')
          -- A non-manual query's Statement is regenerated from the target's own object by
          -- SCore.EntityQueryUpsert, so a Statement-only difference there is expected.
          AND NOT
          (
              tr.SchemaName = N'SCore'
              AND tr.TableName = N'EntityQueries'
              AND JSON_VALUE(v.SourcePayloadJson, N'$.IsManualStatement') IN (N'false', N'0')
              AND diff.KeyList = N'Statement'
          );

        SET @NotConvergedCount = @@ROWCOUNT;

        DELETE FROM SMigration.Metadata_StagedRows
        WHERE RunGuid = @VerifyRunGuid;

        DELETE FROM SMigration.Metadata_Run
        WHERE Guid = @VerifyRunGuid;

        COMMIT TRANSACTION;

        SET @DetailsJson = CONCAT(N'{"checkedRows":', @CheckedCount, N',"notConvergedRows":', @NotConvergedCount, N'}');
        SET @StepStatus = CASE WHEN @NotConvergedCount > 0 THEN N'Warning' ELSE N'Succeeded' END;

        EXEC SMigration.MetadataExecutionLog_Add
            @RunGuid = @RunGuid,
            @StepName = N'ApplyConvergenceCheck',
            @StepStatus = @StepStatus,
            @Message = N'Applied rows re-compared with the source after apply.',
            @DetailsJson = @DetailsJson;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @ErrorMessage = LEFT(ERROR_MESSAGE(), 4000);
        SET @DetailsJson = CONCAT(N'{"error":"', STRING_ESCAPE(@ErrorMessage, 'json'), N'"}');

        BEGIN TRY
            EXEC SMigration.MetadataExecutionLog_Add
                @RunGuid = @RunGuid,
                @StepName = N'ApplyConvergenceCheck',
                @StepStatus = N'Failed',
                @Message = N'The post-apply convergence check could not run. The apply itself is unaffected.',
                @DetailsJson = @DetailsJson;
        END TRY
        BEGIN CATCH
        END CATCH;
    END CATCH;
END;
GO

