		-- They must be initialised before the quote loop because a new enquiry
		-- can legitimately have no quotes to duplicate.
		DECLARE	@OldStatus UNIQUEIDENTIFIER = '00000000-0000-0000-0000-000000000000',
				@CreatedByUserGuid UNIQUEIDENTIFIER = '00000000-0000-0000-0000-000000000000',
