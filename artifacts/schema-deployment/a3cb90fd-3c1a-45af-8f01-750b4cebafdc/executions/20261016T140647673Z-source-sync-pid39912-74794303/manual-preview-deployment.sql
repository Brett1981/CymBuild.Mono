        -- HoBT stayed soft-deleted after an Apply that reported success).
        UPDATE hobt
        SET RowStatus = ISNULL(@EH_RowStatus, hobt.RowStatus),
            EntityTypeID = ISNULL(entityType.ID, hobt.EntityTypeID)
        FROM SCore.EntityHobts AS hobt
        LEFT JOIN SCore.EntityTypes AS entityType
            ON entityType.Guid = @EH_EntityTypeGuid
        WHERE hobt.Guid = @EntityHoBTGuidToApply
          AND
          (
              hobt.RowStatus <> ISNULL(@EH_RowStatus, hobt.RowStatus)
              OR hobt.EntityTypeID <> ISNULL(entityType.ID, hobt.EntityTypeID)
          );

        FETCH NEXT FROM EntityHobts_Cursor
