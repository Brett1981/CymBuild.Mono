    FROM #MetadataSourceGuidLookup AS lookup
    WHERE lookup.SchemaName = N'SCore'
      AND lookup.TableName = N'EntityDataTypes'
      AND lookup.SourceRowId = @EQP_SourceEntityDataTypeID;

    SELECT
        @EQP_MappedEntityPropertyGuid = lookup.SourceRowGuid
    FROM #MetadataSourceGuidLookup AS lookup
    WHERE lookup.SchemaName = N'SCore'
      AND lookup.TableName = N'EntityProperties'
      AND lookup.SourceRowId = @EQP_SourceMappedEntityPropertyID;

    /*
        2026-10-12 UAT_Test run C7CA0A7D: a retirement (source RowStatus 254) can reference a
        row that is retired in both environments and so never staged ([SSop].[QuotesUpsert]
        @QuoteJobType -> retired property QuoteJobType). Its ID has no Guid in the lookup and
        the upsert wrote NULL into MappedEntityPropertyID. Retiring only changes RowStatus, so
        keep the target row's own references for any the source cannot resolve.
    */
    IF @EQP_RowStatus IN (0,254)
    BEGIN
        SELECT
            @EQP_EntityQueryGuid = ISNULL(@EQP_EntityQueryGuid, targetQuery.Guid),
            @EQP_EntityDataTypeGuid = ISNULL(@EQP_EntityDataTypeGuid, targetDataType.Guid),
            @EQP_MappedEntityPropertyGuid = ISNULL(@EQP_MappedEntityPropertyGuid, targetProperty.Guid)
        FROM SCore.EntityQueryParameters AS targetParameter
        LEFT JOIN SCore.EntityQueries AS targetQuery
            ON targetQuery.ID = targetParameter.EntityQueryID
        LEFT JOIN SCore.EntityDataTypes AS targetDataType
            ON targetDataType.ID = targetParameter.EntityDataTypeID
        LEFT JOIN SCore.EntityProperties AS targetProperty
            ON targetProperty.ID = targetParameter.MappedEntityPropertyID
        WHERE targetParameter.Guid = ISNULL(@EQP_OverrideTargetGuid, @Guid);
    END;

    -- A manual Identity Map override means "update the record I matched this to," not
    -- "insert my own Guid" - resolve to the override's target before upserting.
    DECLARE @EntityQueryParameterGuid UNIQUEIDENTIFIER = ISNULL(@EQP_OverrideTargetGuid, @Guid);

    IF @EQP_OverrideTargetGuid IS NOT NULL AND @EQP_ColumnSourceSelectionJson IS NOT NULL
    BEGIN
        SET @EQP_TargetRowFound = 0;
        SET @EQP_Target_RowStatus = NULL;
        SET @EQP_Target_Name = NULL;
        SET @EQP_Target_DefaultValue = NULL;
        SET @EQP_Target_IsInput = NULL;
        SET @EQP_Target_IsOutput = NULL;
        SET @EQP_Target_IsReturnColumn = NULL;

        SELECT
            @EQP_Target_RowStatus = targetrow.RowStatus,
            @EQP_Target_Name = targetrow.Name,
            @EQP_Target_DefaultValue = targetrow.DefaultValue,
            @EQP_Target_IsInput = targetrow.IsInput,
            @EQP_Target_IsOutput = targetrow.IsOutput,
            @EQP_Target_IsReturnColumn = targetrow.IsReturnColumn
        FROM SCore.EntityQueryParameters AS targetrow
        WHERE targetrow.Guid = @EQP_OverrideTargetGuid;

        IF @@ROWCOUNT > 0 SET @EQP_TargetRowFound = 1;

        -- Only trust the "keep target value" merge when the override's target row actually
        -- resolved; a stale/unresolved override must fall back to the source value instead
        -- of silently reusing whatever a prior loop iteration left in these variables.
        IF @EQP_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EQP_ColumnSourceSelectionJson) WHERE [value] = N'RowStatus') SET @EQP_RowStatus = @EQP_Target_RowStatus;
        IF @EQP_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EQP_ColumnSourceSelectionJson) WHERE [value] = N'Name') SET @EQP_Name = @EQP_Target_Name;
        IF @EQP_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EQP_ColumnSourceSelectionJson) WHERE [value] = N'DefaultValue') SET @EQP_DefaultValue = @EQP_Target_DefaultValue;
        IF @EQP_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EQP_ColumnSourceSelectionJson) WHERE [value] = N'IsInput') SET @EQP_IsInput = @EQP_Target_IsInput;
        IF @EQP_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EQP_ColumnSourceSelectionJson) WHERE [value] = N'IsOutput') SET @EQP_IsOutput = @EQP_Target_IsOutput;
        IF @EQP_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EQP_ColumnSourceSelectionJson) WHERE [value] = N'IsReturnColumn') SET @EQP_IsReturnColumn = @EQP_Target_IsReturnColumn;
    END;

    /*
        CYB-574: SCore.EntityQueryUpsert regenerates the parameters of a non-manual query
        (IsManualStatement = 0) from the object signature, under NEWID() Guids, when the
        EntityQueries step above inserts or updates it. Inserting the source parameter under its
        own Guid as well left two active rows with the same name on one query (seen on QA2:
        "The variable name '@Guid' has already been declared"). Adopt that target row instead:
        move it onto the source Guid so the upsert below updates it, keeping Guids aligned with
        the source. A target row that is itself a staged source row is never taken.
    */
    IF @EQP_OverrideTargetGuid IS NULL
       AND NOT EXISTS (SELECT 1 FROM SCore.EntityQueryParameters AS existing WHERE existing.Guid = @EntityQueryParameterGuid)
    BEGIN
        SET @EQP_AdoptTargetId = NULL;
        SET @EQP_AdoptOldGuid = NULL;

        SELECT TOP (1)
            @EQP_AdoptTargetId = targetParameter.ID,
            @EQP_AdoptOldGuid = targetParameter.Guid
        FROM SCore.EntityQueryParameters AS targetParameter
        INNER JOIN SCore.EntityQueries AS targetQuery
            ON targetQuery.ID = targetParameter.EntityQueryID
        WHERE targetQuery.Guid = @EQP_EntityQueryGuid
          AND targetParameter.Name = @EQP_Name
          AND targetParameter.RowStatus NOT IN (0,254)
          AND NOT EXISTS
          (
              SELECT 1
              FROM SMigration.Metadata_StagedRows AS stagedParameter
              INNER JOIN SMigration.Metadata_TableRegistry AS stagedTr
                  ON stagedTr.Guid = stagedParameter.RegistryGuid
              WHERE stagedParameter.RunGuid = @RunGuid
                AND stagedParameter.RowStatus NOT IN (0,254)
                AND stagedTr.SchemaName = N'SCore'
                AND stagedTr.TableName = N'EntityQueryParameters'
                AND stagedParameter.SourceRowGuid = targetParameter.Guid
          )
        ORDER BY targetParameter.ID;

        IF @EQP_AdoptTargetId IS NOT NULL
        BEGIN
            EXEC SMigration.MetadataDataObject_Ensure
                @Guid = @EntityQueryParameterGuid,
                @SchemeName = N'SCore',
                @ObjectName = N'EntityQueryParameters';

            UPDATE SCore.EntityQueryParameters
            SET Guid = @EntityQueryParameterGuid
            WHERE ID = @EQP_AdoptTargetId;

            UPDATE SCore.DataObjects
            SET RowStatus = 254
            WHERE Guid = @EQP_AdoptOldGuid
              AND RowStatus NOT IN (0,254);

            SET @EQP_AdoptedCount += 1;
        END;
    END;

    EXEC SCore.EntityQueryParameterUpsert
        @Name = @EQP_Name,
        @RowStatus = @EQP_RowStatus,
        @EntityQueryGuid = @EQP_EntityQueryGuid,
        @EntityDataTypeGuid = @EQP_EntityDataTypeGuid,
        @MappedEntityPropertyGuid = @EQP_MappedEntityPropertyGuid,
        @DefaultValue = @EQP_DefaultValue,
        @IsInput = @EQP_IsInput,
        @IsOutput = @EQP_IsOutput,
        @IsReturnColumn = @EQP_IsReturnColumn,
        @Guid = @EntityQueryParameterGuid OUTPUT;

    /*
        CYB-574: the adopt step above only runs when the source Guid is new to the target. An
        Update can instead revive a soft-deleted source row while the generated copy is still
        active (seen on QA2 run 4: 'Invoice Request Items Validate' ended with two '@Guid').
        Once the applied row is active, remove any other active row with the same query and
        name that is not itself a staged source row. Hard delete: EntityQueryUpsert's MERGE
        ignores RowStatus and would revive a soft-deleted copy.
    */
    IF EXISTS
    (
        SELECT 1
        FROM SCore.EntityQueryParameters AS applied
        WHERE applied.Guid = @EntityQueryParameterGuid
          AND applied.RowStatus NOT IN (0,254)
    )
    BEGIN
        DELETE FROM @EQP_RemovedDuplicates;

        DELETE other
        OUTPUT deleted.Guid INTO @EQP_RemovedDuplicates (Guid)
        FROM SCore.EntityQueryParameters AS other
        INNER JOIN SCore.EntityQueryParameters AS applied
            ON applied.Guid = @EntityQueryParameterGuid
           AND applied.EntityQueryID = other.EntityQueryID
           AND applied.Name = other.Name
           AND applied.ID <> other.ID
        WHERE other.RowStatus NOT IN (0,254)
          AND NOT EXISTS
          (
              SELECT 1
              FROM SMigration.Metadata_StagedRows AS stagedParameter
              INNER JOIN SMigration.Metadata_TableRegistry AS stagedTr
                  ON stagedTr.Guid = stagedParameter.RegistryGuid
              WHERE stagedParameter.RunGuid = @RunGuid
                AND stagedParameter.RowStatus NOT IN (0,254)
                AND stagedTr.SchemaName = N'SCore'
                AND stagedTr.TableName = N'EntityQueryParameters'
                AND stagedParameter.SourceRowGuid = other.Guid
          );

        SET @EQP_RemovedDuplicateCount += (SELECT COUNT(1) FROM @EQP_RemovedDuplicates);

        UPDATE dob
        SET RowStatus = 254
        FROM SCore.DataObjects AS dob
        INNER JOIN @EQP_RemovedDuplicates AS removed
            ON removed.Guid = dob.Guid
        WHERE dob.RowStatus NOT IN (0,254);
    END;

    FETCH NEXT FROM EntityQueryParameters_Cursor
    INTO
        @Guid,
        @EQP_RowStatus,
        @EQP_Name,
        @EQP_SourceEntityQueryID,
        @EQP_SourceEntityDataTypeID,
        @EQP_SourceMappedEntityPropertyID,
        @EQP_DefaultValue,
        @EQP_IsInput,
        @EQP_IsOutput,
        @EQP_IsReturnColumn,
        @EQP_OverrideTargetGuid,
        @EQP_ColumnSourceSelectionJson;
END;

CLOSE EntityQueryParameters_Cursor;
DEALLOCATE EntityQueryParameters_Cursor;

DECLARE @EQP_AdoptedDetailsJson NVARCHAR(MAX) = CONCAT(N'{"adoptedGeneratedParameters":', @EQP_AdoptedCount, N',"removedDuplicateParameters":', @EQP_RemovedDuplicateCount, N'}');

EXEC SMigration.MetadataExecutionLog_Add
    @RunGuid = @RunGuid,
    @StepName = N'ApplyEntityQueryParameters',
    @StepStatus = N'Succeeded',
    @Message = N'Entity query parameters applied.',
    @DetailsJson = @EQP_AdoptedDetailsJson;


