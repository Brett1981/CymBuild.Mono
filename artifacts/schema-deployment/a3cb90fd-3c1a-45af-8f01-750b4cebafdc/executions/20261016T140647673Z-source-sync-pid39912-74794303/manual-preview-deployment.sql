            @EH_RowStatus,
            @EH_SchemaName,
            @EH_ObjectName,
            @EH_SourceEntityTypeID,
            @EH_ObjectType,
            @EH_IsMainHoBT,
            @EH_IsReadOnlyOffline,
            @EH_OverrideTargetGuid,
