      AND lookup.TableName = N'LanguageLabels'
      AND lookup.SourceRowId = @GVCD_SourceLanguageLabelID;

    DECLARE @ExistingGridViewColumnDefinitionGuid UNIQUEIDENTIFIER = NULL;

    -- A manual Identity Map override is an explicit, reviewed operator decision and wins over
    -- the natural-key (GridViewDefinition+PrimaryKey/Name) match below.
    -- CYB-574: so does the row's own Guid, even soft-deleted (see the EntityProperties handler).
    IF @GVCD_OverrideTargetGuid IS NULL
       AND NOT EXISTS (SELECT 1 FROM SUserInterface.GridViewColumnDefinitions AS ownRow WHERE ownRow.Guid = @Guid)
    BEGIN
        SELECT TOP (1)
            @ExistingGridViewColumnDefinitionGuid = gvcd.Guid
        FROM SUserInterface.GridViewColumnDefinitions AS gvcd
        INNER JOIN SUserInterface.GridViewDefinitions AS gvd
            ON gvd.ID = gvcd.GridViewDefinitionID
           AND gvd.RowStatus NOT IN (0,254)
        WHERE gvd.Guid = @GVCD_GridViewDefinitionGuid
          AND gvcd.RowStatus NOT IN (0,254)
          AND gvcd.Guid <> @Guid
          AND
          (
              (
                  ISNULL(@GVCD_IsPrimaryKey, 0) = 1
                  AND gvcd.IsPrimaryKey = 1
              )
              OR
              (
                  ISNULL(@GVCD_IsPrimaryKey, 0) = 0
                  AND gvcd.Name = @GVCD_Name
              )
          )
        ORDER BY
            CASE WHEN ISNULL(@GVCD_IsPrimaryKey, 0) = 1 AND gvcd.IsPrimaryKey = 1 THEN 0 ELSE 1 END,
            gvcd.ID;
    END;

    DECLARE @GridViewColumnDefinitionGuid UNIQUEIDENTIFIER = ISNULL(@GVCD_OverrideTargetGuid, ISNULL(@ExistingGridViewColumnDefinitionGuid, @Guid));

    /*
        CYB-574: with the Guid row winning, an active column on the same grid view with the same
        name (or the primary-key column, when this one is the key) that is not an active staged
        source row is a duplicate - typically generated in the target when the grid view was
        re-created. Retire it and clear its IsPrimaryKey: IX_UQ_GridViewColumndefinition_IsPrimaryKey
        is filtered on IsPrimaryKey = 1 only, so a soft-deleted key column still holds the slot.
    */
    IF @GVCD_OverrideTargetGuid IS NULL
       AND @ExistingGridViewColumnDefinitionGuid IS NULL
       AND ISNULL(@GVCD_RowStatus, 1) NOT IN (0,254)
       AND EXISTS (SELECT 1 FROM SUserInterface.GridViewColumnDefinitions AS ownRow WHERE ownRow.Guid = @Guid)
    BEGIN
        UPDATE blocker
        SET RowStatus = CASE WHEN blocker.RowStatus IN (0,254) THEN blocker.RowStatus ELSE 254 END,
            IsPrimaryKey = 0
        FROM SUserInterface.GridViewColumnDefinitions AS blocker
        INNER JOIN SUserInterface.GridViewDefinitions AS blockerGrid
            ON blockerGrid.ID = blocker.GridViewDefinitionID
        WHERE blockerGrid.Guid = @GVCD_GridViewDefinitionGuid
          AND blocker.Guid <> @Guid
          AND
          (
              (blocker.RowStatus NOT IN (0,254) AND blocker.Name = @GVCD_Name)
              OR (ISNULL(@GVCD_IsPrimaryKey, 0) = 1 AND blocker.IsPrimaryKey = 1)
          )
          AND NOT EXISTS
          (
              SELECT 1
              FROM SMigration.Metadata_StagedRows AS stagedColumn
              INNER JOIN SMigration.Metadata_TableRegistry AS stagedTr
                  ON stagedTr.Guid = stagedColumn.RegistryGuid
              WHERE stagedColumn.RunGuid = @RunGuid
                AND stagedColumn.RowStatus NOT IN (0,254)
                AND stagedTr.SchemaName = N'SUserInterface'
                AND stagedTr.TableName = N'GridViewColumnDefinitions'
                AND stagedColumn.SourceRowGuid = blocker.Guid
                AND ISNULL(stagedColumn.SourceRowStatus, 1) NOT IN (0,254)
