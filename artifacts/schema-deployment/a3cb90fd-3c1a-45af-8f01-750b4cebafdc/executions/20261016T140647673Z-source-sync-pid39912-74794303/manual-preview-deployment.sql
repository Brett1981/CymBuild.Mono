                q.Name,
                p.Name
            HAVING COUNT(1) > 1
        ) AS duplicate;

        /*
            CYB-574: a parameter whose mapped property belongs to a different entity type than
            its query AND whose name does not match that property was mapped by a raw ID copied
            from another environment (legacy data-compare scripts), so it points at an unrelated
            property. Both conditions are needed: either alone has legitimate cases.

            2026-10-12 UAT_Test run B245E6D5: a selected Insert/Update of the parameter replaces
            the target mapping with the source one (resolved by Guid), so for those rows the
            source mapping is checked instead (second insert below); the target check covers
            only parameters this run leaves alone.
        */
        INSERT INTO SMigration.Metadata_ValidationIssues
        (
            Guid,
            RowStatus,
            RunGuid,
            RegistryGuid,
            SourceRowGuid,
            Severity,
            IssueCode,
            IssueMessage,
            DetailsJson,
            CreatedOnUtc
        )
        SELECT
            NEWID(),
            1,
            @RunGuid,
            @EntityQueryParametersRegistryGuid,
            p.Guid,
            N'Warn',
            N'QueryParameterMappingMismatch',
            LEFT(CONCAT
            (
                N'Target parameter ', p.Name, N' on query ''', q.Name, N''' maps to property ',
                ep.Name, N' of entity type ''', propertyEntity.Name, N''', not the query''s entity type ''',
                queryEntity.Name, N'''. It was probably mapped by a raw ID from another environment.'
            ), 4000),
            CONCAT(N'{"entityQueryGuid":"', CONVERT(NVARCHAR(36), q.Guid), N'","mappedEntityPropertyGuid":"', CONVERT(NVARCHAR(36), ep.Guid), N'"}'),
            SYSUTCDATETIME()
        FROM SCore.EntityQueryParameters AS p
        INNER JOIN SCore.EntityQueries AS q
            ON q.ID = p.EntityQueryID
           AND q.RowStatus NOT IN (0,254)
        INNER JOIN SCore.EntityProperties AS ep
            ON ep.ID = p.MappedEntityPropertyID
        INNER JOIN SCore.EntityHobts AS h
            ON h.ID = ep.EntityHoBTID
        INNER JOIN SCore.EntityTypes AS propertyEntity
            ON propertyEntity.ID = h.EntityTypeID
        INNER JOIN SCore.EntityTypes AS queryEntity
            ON queryEntity.ID = q.EntityTypeID
        WHERE p.RowStatus NOT IN (0,254)
          AND p.MappedEntityPropertyID > 0
          AND h.EntityTypeID <> q.EntityTypeID
          AND p.Name NOT IN (N'@' + ep.Name, N'@' + ep.Name + N'Guid')
          AND N'@' + ep.Name NOT IN (REPLACE(p.Name, N'Guid', N'ID'), REPLACE(p.Name, N'Guid', N'Id'))
          AND NOT EXISTS
          (
              SELECT 1
              FROM #MetadataSelectedValidationRows AS selected
              WHERE selected.RegistryGuid = @EntityQueryParametersRegistryGuid
                AND selected.SourceRowGuid = p.Guid
          );

        INSERT INTO SMigration.Metadata_ValidationIssues
        (
            Guid,
            RowStatus,
            RunGuid,
            RegistryGuid,
            SourceRowGuid,
            Severity,
            IssueCode,
            IssueMessage,
            DetailsJson,
            CreatedOnUtc
        )
        SELECT
            NEWID(),
            1,
            @RunGuid,
            @EntityQueryParametersRegistryGuid,
            parameterRow.SourceRowGuid,
            N'Warn',
            N'QueryParameterMappingMismatch',
            LEFT(CONCAT
            (
                N'Source parameter ', src.ParameterName, N' on query ''', src.QueryName, N''' maps to property ',
                src.PropertyName, N', which belongs to a different entity type than the query. Fix the mapping in the source before applying.'
            ), 4000),
            CONCAT(N'{"entityQueryGuid":"', CONVERT(NVARCHAR(36), queryRow.SourceRowGuid), N'","mappedEntityPropertyGuid":"', CONVERT(NVARCHAR(36), propertyRow.SourceRowGuid), N'"}'),
            SYSUTCDATETIME()
        FROM #MetadataSelectedValidationRows AS selected
        INNER JOIN SMigration.Metadata_StagedRows AS parameterRow
            ON parameterRow.RunGuid = @RunGuid
           AND parameterRow.RegistryGuid = selected.RegistryGuid
           AND parameterRow.SourceRowGuid = selected.SourceRowGuid
           AND parameterRow.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_TableRegistry AS queryTr
            ON queryTr.SchemaName = N'SCore'
           AND queryTr.TableName = N'EntityQueries'
           AND queryTr.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_StagedRows AS queryRow
            ON queryRow.RunGuid = @RunGuid
           AND queryRow.RegistryGuid = queryTr.Guid
           AND queryRow.SourceRowId = TRY_CONVERT(BIGINT, JSON_VALUE(parameterRow.SourcePayloadJson, N'$.EntityQueryID'))
           AND queryRow.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_TableRegistry AS propertyTr
            ON propertyTr.SchemaName = N'SCore'
           AND propertyTr.TableName = N'EntityProperties'
           AND propertyTr.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_StagedRows AS propertyRow
            ON propertyRow.RunGuid = @RunGuid
           AND propertyRow.RegistryGuid = propertyTr.Guid
           AND propertyRow.SourceRowId = TRY_CONVERT(BIGINT, JSON_VALUE(parameterRow.SourcePayloadJson, N'$.MappedEntityPropertyID'))
           AND propertyRow.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_TableRegistry AS sourceHobtTr
            ON sourceHobtTr.SchemaName = N'SCore'
           AND sourceHobtTr.TableName = N'EntityHobts'
           AND sourceHobtTr.RowStatus NOT IN (0,254)
        INNER JOIN SMigration.Metadata_StagedRows AS sourceHobtRow
            ON sourceHobtRow.RunGuid = @RunGuid
           AND sourceHobtRow.RegistryGuid = sourceHobtTr.Guid
           AND sourceHobtRow.SourceRowId = TRY_CONVERT(BIGINT, JSON_VALUE(propertyRow.SourcePayloadJson, N'$.EntityHoBTID'))
           AND sourceHobtRow.RowStatus NOT IN (0,254)
        CROSS APPLY
        (
            SELECT
                ParameterName = JSON_VALUE(parameterRow.SourcePayloadJson, N'$.Name'),
                QueryName = JSON_VALUE(queryRow.SourcePayloadJson, N'$.Name'),
                PropertyName = JSON_VALUE(propertyRow.SourcePayloadJson, N'$.Name'),
                QueryEntityTypeId = TRY_CONVERT(BIGINT, COALESCE(JSON_VALUE(queryRow.SourcePayloadJson, N'$.EntityTypeID'), JSON_VALUE(queryRow.SourcePayloadJson, N'$.EntityTypeId'))),
                PropertyEntityTypeId = TRY_CONVERT(BIGINT, COALESCE(JSON_VALUE(sourceHobtRow.SourcePayloadJson, N'$.EntityTypeID'), JSON_VALUE(sourceHobtRow.SourcePayloadJson, N'$.EntityTypeId')))
        ) AS src
        WHERE selected.RegistryGuid = @EntityQueryParametersRegistryGuid
          AND ISNULL(TRY_CONVERT(TINYINT, JSON_VALUE(parameterRow.SourcePayloadJson, N'$.RowStatus')), 1) NOT IN (0,254)
          AND TRY_CONVERT(BIGINT, JSON_VALUE(parameterRow.SourcePayloadJson, N'$.MappedEntityPropertyID')) > 0
          AND src.QueryEntityTypeId <> src.PropertyEntityTypeId
          AND src.ParameterName NOT IN (N'@' + src.PropertyName, N'@' + src.PropertyName + N'Guid')
          AND N'@' + src.PropertyName NOT IN (REPLACE(src.ParameterName, N'Guid', N'ID'), REPLACE(src.ParameterName, N'Guid', N'Id'));
    END;

    UPDATE ignored
    SET
        ignored.LastSeenRunGuid = @RunGuid,
        ignored.LastSeenOnUtc = SYSUTCDATETIME()
    FROM SMigration.Metadata_ValidationIssueIgnores AS ignored
    INNER JOIN SMigration.Metadata_ValidationIssues AS issue
        ON issue.RunGuid = @RunGuid
       AND issue.RegistryGuid = ignored.RegistryGuid
       AND issue.SourceRowGuid = ignored.SourceRowGuid
       AND issue.IssueCode = ignored.IssueCode
       AND issue.RowStatus NOT IN (0,254)
    WHERE ignored.DatabaseName = @TargetDatabaseName
      AND ignored.RowStatus NOT IN (0,254);

    SELECT
        @FailCount = SUM(CASE WHEN vi.Severity = N'Fail' THEN 1 ELSE 0 END),
        @WarnCount = SUM(CASE WHEN vi.Severity = N'Warn' THEN 1 ELSE 0 END),
        @InfoCount = SUM(CASE WHEN vi.Severity = N'Info' THEN 1 ELSE 0 END)
    FROM SMigration.Metadata_ValidationIssues AS vi
    WHERE vi.RunGuid = @RunGuid
      AND vi.RowStatus NOT IN (0,254)
      AND NOT EXISTS
      (
          SELECT 1
          FROM SMigration.Metadata_ValidationIssueIgnores AS ignoredIssue
          WHERE ignoredIssue.DatabaseName = @TargetDatabaseName
            AND ignoredIssue.RegistryGuid = vi.RegistryGuid
            AND ignoredIssue.SourceRowGuid = vi.SourceRowGuid
            AND ignoredIssue.IssueCode = vi.IssueCode
            AND ignoredIssue.RowStatus NOT IN (0,254)
      )
      AND
      (
          vi.IssueCode IN (N'RunNotFound', N'NoSelectedRows', N'DuplicateSourceGuid', N'DuplicateTargetGuid', N'DuplicateTargetKey', N'UnresolvedReference', N'SelectedRowParentNotSelected', N'UnselectedActionableRows', N'DuplicateQueryParameterName', N'QueryParameterMappingMismatch', N'QueryCallSignatureMismatch')
          OR EXISTS
          (
              SELECT 1
              FROM #MetadataSelectedValidationRows AS selected
              WHERE selected.RegistryGuid = vi.RegistryGuid
                AND
                (
                    vi.SourceRowGuid IS NULL
                    OR selected.SourceRowGuid = vi.SourceRowGuid
                )
          )
      );

    SET @FailCount = ISNULL(@FailCount, 0);
    SET @WarnCount = ISNULL(@WarnCount, 0);
    SET @InfoCount = ISNULL(@InfoCount, 0);

    UPDATE SMigration.Metadata_Run
    SET
        RunStatus = CASE WHEN @FailCount > 0 THEN N'ValidationFailed' ELSE N'Validated' END,
        ValidatedOnUtc = SYSUTCDATETIME(),
        SummaryJson = CONCAT
        (
            N'{"failCount":',
            CONVERT(NVARCHAR(30), @FailCount),
            N',"warnCount":',
            CONVERT(NVARCHAR(30), @WarnCount),
            N',"infoCount":',
            CONVERT(NVARCHAR(30), @InfoCount),
            N'}'
        )
    WHERE Guid = @RunGuid
      AND RowStatus NOT IN (0,254);
    DECLARE @_StepStatus AS NVARCHAR(15) = (CASE WHEN @FailCount > 0 THEN N'Failed' ELSE N'Succeeded' END)
    EXEC SMigration.MetadataExecutionLog_Add
        @RunGuid = @RunGuid,
        @StepName = N'ValidateRun',
        @StepStatus = @_StepStatus,
        @Message = N'Metadata migration validation completed.',
        @DetailsJson = N'{}';

    COMMIT TRANSACTION;

    SELECT
        @FailCount AS FailCount,
        @WarnCount AS WarnCount,
        @InfoCount AS InfoCount;
END;
GO

