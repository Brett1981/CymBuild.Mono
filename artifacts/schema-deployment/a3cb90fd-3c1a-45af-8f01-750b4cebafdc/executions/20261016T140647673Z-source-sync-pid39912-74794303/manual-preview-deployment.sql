DECLARE EntityPropertyDependants_Cursor CURSOR LOCAL FAST_FORWARD FOR
    SELECT
        sr.SourceRowGuid,
        TRY_CONVERT(TINYINT, JSON_VALUE(sr.SourcePayloadJson, N'$.RowStatus')),
        TRY_CONVERT(BIGINT, JSON_VALUE(sr.SourcePayloadJson, N'$.ParentEntityPropertyID')),
        TRY_CONVERT(BIGINT, JSON_VALUE(sr.SourcePayloadJson, N'$.DependantPropertyID')),
        ov.TargetRowGuid,
        ov.ColumnSourceSelectionJson
    FROM SMigration.Metadata_StagedRows AS sr
    INNER JOIN #MetadataRowsToApply AS applyRows
        ON applyRows.StagedRowId = sr.ID
    INNER JOIN SMigration.Metadata_TableRegistry AS tr
        ON tr.Guid = sr.RegistryGuid
       AND tr.RowStatus NOT IN (0,254)
    LEFT JOIN SMigration.Metadata_IdentityMapOverrides AS ov
        ON ov.DatabaseName = @TargetDatabaseName
       AND ov.RegistryGuid = sr.RegistryGuid
       AND ov.SourceRowGuid = sr.SourceRowGuid
       AND ov.RowStatus NOT IN (0,254)
    WHERE sr.RunGuid = @RunGuid
      AND sr.RowStatus NOT IN (0,254)
      AND sr.DifferenceType IN (N'Insert', N'Update')
      AND tr.SchemaName = N'SCore'
      AND tr.TableName = N'EntityPropertyDependants'
    ORDER BY sr.SourceRowId;

OPEN EntityPropertyDependants_Cursor;

FETCH NEXT FROM EntityPropertyDependants_Cursor
INTO
    @Guid,
    @EPD_RowStatus,
    @EPD_SourceParentEntityPropertyID,
    @EPD_SourceDependantPropertyID,
    @EPD_OverrideTargetGuid,
    @EPD_ColumnSourceSelectionJson;

WHILE @@FETCH_STATUS = 0
BEGIN
    SET @EPD_ParentEntityPropertyGuid = NULL;
    SET @EPD_DependantEntityPropertyGuid = NULL;

    SELECT
        @EPD_ParentEntityPropertyGuid = lookup.SourceRowGuid
    FROM #MetadataSourceGuidLookup AS lookup
    WHERE lookup.SchemaName = N'SCore'
      AND lookup.TableName = N'EntityProperties'
      AND lookup.SourceRowId = @EPD_SourceParentEntityPropertyID;

    SELECT
        @EPD_DependantEntityPropertyGuid = lookup.SourceRowGuid
    FROM #MetadataSourceGuidLookup AS lookup
    WHERE lookup.SchemaName = N'SCore'
      AND lookup.TableName = N'EntityProperties'
      AND lookup.SourceRowId = @EPD_SourceDependantPropertyID;

    IF @EPD_ParentEntityPropertyGuid IS NULL OR @EPD_DependantEntityPropertyGuid IS NULL
    BEGIN
        DECLARE @MissingDependantPropertyMessage NVARCHAR(4000) = CONCAT(N'EntityPropertyDependants apply could not resolve EntityProperty source ID ', COALESCE(CONVERT(NVARCHAR(30), CASE WHEN @EPD_ParentEntityPropertyGuid IS NULL THEN @EPD_SourceParentEntityPropertyID ELSE @EPD_SourceDependantPropertyID END), N'<NULL>'), N' for dependant ', CONVERT(NVARCHAR(36), @Guid), N'. Ensure SCore.EntityProperties is staged/applied before SCore.EntityPropertyDependants.');
        THROW 52030, @MissingDependantPropertyMessage, 1;
    END;

    -- A manual Identity Map override means "update the record I matched this to," not
    -- "insert my own Guid" - resolve to the override's target before upserting.
    SET @EntityPropertyDependantGuid = ISNULL(@EPD_OverrideTargetGuid, @Guid);

    IF @EPD_OverrideTargetGuid IS NOT NULL AND @EPD_ColumnSourceSelectionJson IS NOT NULL
    BEGIN
        SET @EPD_TargetRowFound = 0;
        SET @EPD_Target_RowStatus = NULL;

        SELECT
            @EPD_Target_RowStatus = targetrow.RowStatus
        FROM SCore.EntityPropertyDependants AS targetrow
        WHERE targetrow.Guid = @EPD_OverrideTargetGuid;

        IF @@ROWCOUNT > 0 SET @EPD_TargetRowFound = 1;

        -- RowStatus is this table's only scalar column; both property columns are foreign keys,
        -- which are deliberately never target-selectable.
        IF @EPD_TargetRowFound = 1 AND NOT EXISTS (SELECT 1 FROM OPENJSON(@EPD_ColumnSourceSelectionJson) WHERE [value] = N'RowStatus') SET @EPD_RowStatus = @EPD_Target_RowStatus;
    END;

    EXEC SCore.EntityPropertyDependantUpsert
        @ParentEntityPropertyGuid = @EPD_ParentEntityPropertyGuid,
        @DependantEntityPropertyGuid = @EPD_DependantEntityPropertyGuid,
        @RowStatus = @EPD_RowStatus,
        @Guid = @EntityPropertyDependantGuid OUTPUT;

    FETCH NEXT FROM EntityPropertyDependants_Cursor
    INTO
        @Guid,
        @EPD_RowStatus,
        @EPD_SourceParentEntityPropertyID,
        @EPD_SourceDependantPropertyID,
        @EPD_OverrideTargetGuid,
        @EPD_ColumnSourceSelectionJson;
