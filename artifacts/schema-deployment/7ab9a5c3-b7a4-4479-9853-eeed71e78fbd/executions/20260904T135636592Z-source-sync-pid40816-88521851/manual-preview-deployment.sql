JOIN	SFin.TransactionTypes tt ON (tt.ID = t.TransactionTypeID)
JOIN	SJob.Jobs j ON (j.Id = t.JobID)
JOIN	SCore.Identities i ON (i.ID = t.SurveyorUserId)
JOIN    SCrm.Accounts AS ac ON (ac.ID = t.AccountID)
