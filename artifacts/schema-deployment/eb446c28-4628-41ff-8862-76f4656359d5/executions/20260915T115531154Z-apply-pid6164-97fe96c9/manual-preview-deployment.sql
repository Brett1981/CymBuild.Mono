        SET @NetAmount = ABS(ISNULL(@NetAmount, 0));
        SET @TaxAmount = ABS(ISNULL(@TaxAmount, 0));

        IF ISNULL(@MatchedInvoiceTransactionID, -1) <= 0
        BEGIN
            RETURN;
        END;

        IF ISNULL(@AllocatedValue, 0) <= 0
        BEGIN
            RETURN;
        END;

