            @MaterialisedTransactionTypeGuid = tt.Guid
        FROM SFin.TransactionTypes AS tt
        WHERE tt.RowStatus NOT IN (0,254)
          AND tt.IsActive = 1
          AND UPPER(REPLACE(REPLACE(REPLACE(LTRIM(RTRIM(tt.Name)), N' ', N''), N'-', N''), N'_', N'')) =
