    SET @UserId = ISNULL(CONVERT(INT, SESSION_CONTEXT(N'user_id')), -1);
    SET @SessionUserGuid = SCore.GetCurrentUserGuid();

    BEGIN TRY
        SELECT
            @MatchedInvoiceTransactionID        = ext.MatchedTransactionID,
            @SageTransactionTypeCode             = ext.SageTransactionTypeCode,
            @AllocatedValue                     = ext.AllocatedValue,
            @NetAmount                          = ext.NetAmount,
            @TaxAmount                          = ext.TaxAmount,
            @TransactionDate                    = ext.TransactionDate,
            @SageTransactionReference           = ext.SageTransactionReference,
            @ExistingReceiptTransactionGuid     = ext.MaterialisedReceiptTransactionGuid,
            @ExistingAllocationMaterialisedGuid = ext.MaterialisedAllocationGuid
        FROM SFin.SageExternalTransactions AS ext
        WHERE ext.ID = @ExternalTransactionID
          AND ext.RowStatus NOT IN (0,254);

        /*
            Type 5 Credit Note and type 6 Receipt rows are the primary
            allocation sources created in CymBuild - Sage is the system of
            record for both and CymBuild only mirrors them inbound.

            Some Sage sources (including the DEV mock wrapper) never emit a
            distinct Credit Note/Receipt row at all: they represent a
            settled invoice purely by flipping IsPaid/AllocatedValue on the
            type 4 Invoice row itself. Without a fallback, CYB-543 invoices
            reach PaymentStateCode = Paid but never get a materialised
            Receipt/Allocation. So a type 4 row is also accepted as an
            allocation source, but only while no distinct type 5/6 row has
            ever been matched to the same invoice - once a real Credit
            Note/Receipt exists, it alone owns the receipt/allocation so the
            two sources cannot fight over (and repeatedly overwrite) the
            same materialised amount.
