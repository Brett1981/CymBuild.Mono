            @InvoiceAccountGuid            = acc.Guid,
            @InvoiceJobGuid                = j.Guid,
            @InvoiceOrganisationalUnitGuid = ou.Guid,
            @InvoiceSurveyorGuid           = idn.Guid,
            @InvoiceCreditTermsGuid        = ct.Guid
