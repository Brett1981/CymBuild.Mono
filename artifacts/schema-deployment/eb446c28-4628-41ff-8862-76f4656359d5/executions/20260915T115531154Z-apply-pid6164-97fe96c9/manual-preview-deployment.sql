            A type 4 fallback materialisation (see above) and a genuine type
            5/6 row can each reach this point for the same invoice, in
            either order, across separate poll cycles. Reuse whichever
            Receipt/Allocation is already materialised for this invoice -
            from this row or a sibling row - so the later of the two
            updates the existing pair in place instead of creating a
            duplicate.
        */
        IF ISNULL(@ExistingReceiptTransactionGuid, '00000000-0000-0000-0000-000000000000') = '00000000-0000-0000-0000-000000000000'
