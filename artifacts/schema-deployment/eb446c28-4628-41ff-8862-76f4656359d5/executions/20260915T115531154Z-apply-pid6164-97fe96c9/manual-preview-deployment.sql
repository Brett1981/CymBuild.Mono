                WHEN 5 THEN N'CreditNote'
                WHEN 6 THEN N'Receipt'
                WHEN 4 THEN CASE WHEN @InvoiceHasDistinctAllocationSource = 0 THEN N'Receipt' ELSE NULL END
                ELSE NULL
            END;

        IF @MaterialisedTransactionTypeName IS NULL
        BEGIN
            RETURN;
        END;

