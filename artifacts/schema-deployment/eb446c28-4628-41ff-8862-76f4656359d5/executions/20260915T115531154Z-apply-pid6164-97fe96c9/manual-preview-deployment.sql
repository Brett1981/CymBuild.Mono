                      AND a.RowStatus NOT IN (0,254)
              )
              AND t.JobID = (
                    SELECT TOP (1) j2.ID
                    FROM SJob.Jobs AS j2
                    WHERE j2.Guid = @InvoiceJobGuid
                      AND j2.RowStatus NOT IN (0,254)
              )
            ORDER BY t.ID DESC;

            SET @ReceiptGuid = @ExistingReceiptGuid;
        END;

