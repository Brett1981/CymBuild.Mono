/* =============================================================================
   CYB-461 - Enquiry and Quote auto-expiry
   Object: SSop.ExpireOverdueQuotesAndEnquiries

   Records a saved "Expired" workflow status for every Quote and Enquiry that
   the calculated-status views already show as expired:
   - Quotes:    SSop.Quote_CalculatedFields.QuoteStatus = 'Expired'
                (Quoting / Ready to Send / Sent / 1st Chase / 2nd Chase past
                ExpiryDate, or a legacy quote with no history past ExpiryDate).
   - Enquiries: SSop.Enquiry_CalculatedFields.EnquiryStatus IN
                ('Expired', 'Quote Expired') (no quotes and the quoting deadline
                passed more than 2 days ago, or every quote expired).

   The views stay the single definition of the expiry rules; this procedure
   only persists them. Every status is written through
   SCore.DataObjectTransitionUpsert, never directly.

   Idempotent and retry-safe: a record whose latest saved status is already
   "Expired" is skipped, and an application lock stops concurrent runs (the
   API runs this from a hosted worker on more than one replica).

   Notifications: a record that expired more than @NotifyWithinDays ago is
   expired silently (notification triggers suppressed through session
   context), so the first run clears the historic backlog without sending a
   notification per record. Recently expired records notify normally.

   Result sets:
   1) one summary row: LockAcquired, QuotesExpired, EnquiriesExpired,
      ExpiredSilently, Failed
   2) one row per failed record: RecordType, RecordGuid, ErrorMessage
