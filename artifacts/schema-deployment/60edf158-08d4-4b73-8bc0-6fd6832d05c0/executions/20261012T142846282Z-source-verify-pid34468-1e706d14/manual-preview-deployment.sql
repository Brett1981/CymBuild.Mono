-- CYB-496: inactive merge documents stay available to full Super Users (SU) and
-- System Administrators (SYSADM) only. The scoped JOBSU/QUOTESU/ENQUIRYSU groups
-- are deliberately excluded. Always returns exactly one row.
CREATE OR ALTER FUNCTION [SCore].[tvf_UserCanUseInactiveMergeDocuments]
	(
		@UserId INT
	)
RETURNS TABLE
AS
RETURN SELECT	CONVERT(BIT,
					CASE
						WHEN EXISTS
							(
								SELECT	1
								FROM	SCore.UserGroups	AS ug
								JOIN	SCore.Groups		AS g ON (g.ID = ug.GroupID)
								WHERE	(ug.IdentityID = @UserId)
									AND	(g.Code IN (N'SU', N'SYSADM'))
									AND	(ug.RowStatus NOT IN (0, 254))
									AND	(g.RowStatus NOT IN (0, 254))
							)
						THEN 1
						ELSE 0
					END) AS CanUseInactive;
