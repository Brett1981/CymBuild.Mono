		-- CYB-548: WITH (UPDLOCK, HOLDLOCK) takes an update lock on this Activity's row
		-- and holds it for the rest of the caller's transaction. A second call for the
		-- SAME Activity (double-click, or a stalled retry the user repeats) blocks here
		-- until the first call's transaction commits or rolls back, then correctly sees
		-- whatever the first call inserted below - instead of both calls' plain EXISTS
		-- checks passing concurrently under READ COMMITTED and both inserting.
		SELECT	@ActivityId = a.ID
		FROM	SJob.Activities a WITH (UPDLOCK, HOLDLOCK)
		WHERE	(a.Guid = @Guid)

		IF (
			(EXISTS
				(
					SELECT	1
					FROM	SFin.InvoiceRequestItems iri
					WHERE	(iri.ActivityId = @ActivityId)
						AND	(iri.RowStatus NOT IN (0, 254))
