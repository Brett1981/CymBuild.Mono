/*
    Permanent correction:
    - InvoiceProcessingMode: 0 = Automated, 1 = Manual, 2 = Paused.
    - ManualInvoicingEnabled is retained in the output for compatibility, but it
      is no longer used as the authoritative automation gate.
    - CannotBeInvoiced is also honoured before an automated request is created;
      downstream request views already treat this flag as non-invoiceable.
*/
CREATE OR ALTER VIEW [SFin].[vw_InvoiceAutomation_BlockingDiagnostics]
AS
WITH ScheduleJobScope AS
(
    SELECT DISTINCT
          qi.ID                AS QuoteItemId
        , qi.Guid              AS QuoteItemGuid
        , qi.InvoicingSchedule AS InvoiceScheduleId
        , sch.Guid             AS InvoiceScheduleGuid
        , qi.CreatedJobId      AS JobId
    FROM SSop.QuoteItems AS qi
    INNER JOIN SFin.InvoiceSchedules AS sch
        ON sch.ID = qi.InvoicingSchedule
    WHERE qi.RowStatus NOT IN (0, 254)
      AND sch.RowStatus NOT IN (0, 254)
      AND qi.CreatedJobId NOT IN (-1, 0)
      AND qi.InvoicingSchedule NOT IN (-1, 0)
),
BlockingResolution AS
(
    SELECT
          sjs.QuoteItemId
        , sjs.QuoteItemGuid
        , sjs.InvoiceScheduleId
        , sjs.InvoiceScheduleGuid
        , sjs.JobId
        , j.ManualInvoicingEnabled
        , a.ID AS FinanceAccountId
        , acs.IsHold AS AccountIsOnHold
        , acs.Name AS AccountStatusName
        , CAST
          (
              CASE
                  WHEN j.InvoiceProcessingMode IN (1, 2) THEN 1
                  WHEN ISNULL(j.CannotBeInvoiced, 0) = 1 THEN 1
                  WHEN ISNULL(acs.IsHold, 0) = 1 THEN 1
                  ELSE 0
              END
              AS BIT
          ) AS IsBlocked
        , CASE
              WHEN j.InvoiceProcessingMode = 1 THEN N'MANUAL_JOB'
              WHEN j.InvoiceProcessingMode = 2 THEN N'PAUSED_JOB'
              WHEN ISNULL(j.CannotBeInvoiced, 0) = 1 THEN N'JOB_CANNOT_BE_INVOICED'
              WHEN ISNULL(acs.IsHold, 0) = 1 THEN N'ACCOUNT_ON_HOLD'
              ELSE N'NONE'
          END AS BlockedReasonCode
        , CASE
              WHEN j.InvoiceProcessingMode = 1 THEN N'Job is explicitly set to Manual invoicing'
              WHEN j.InvoiceProcessingMode = 2 THEN N'Job invoicing is paused'
              WHEN ISNULL(j.CannotBeInvoiced, 0) = 1
                  THEN CONVERT
                  (
                      NVARCHAR(200),
                      COALESCE(NULLIF(j.CannotBeInvoicedReason, N''), N'Job is marked as unable to be invoiced')
                  )
              WHEN ISNULL(acs.IsHold, 0) = 1 THEN N'Finance account is on hold'
              ELSE N'Not blocked'
          END AS BlockedReason
        , CASE
              WHEN j.InvoiceProcessingMode IN (1, 2) THEN N'Job'
              WHEN ISNULL(j.CannotBeInvoiced, 0) = 1 THEN N'Job'
              WHEN ISNULL(acs.IsHold, 0) = 1 THEN N'Account'
              ELSE N'None'
          END AS BlockingSource
    FROM ScheduleJobScope AS sjs
    INNER JOIN SJob.Jobs AS j
        ON j.ID = sjs.JobId
       AND j.RowStatus NOT IN (0, 254)
    LEFT JOIN SCrm.Accounts AS a
        ON a.ID = j.FinanceAccountID
    LEFT JOIN SCrm.AccountStatus AS acs
        ON acs.ID = a.AccountStatusID
)
SELECT
      InvoiceScheduleId
    , InvoiceScheduleGuid
    , JobId
    , QuoteItemId
    , QuoteItemGuid
    , IsBlocked
    , BlockedReasonCode
    , BlockedReason
    , ManualInvoicingEnabled
    , AccountIsOnHold
    , FinanceAccountId
    , AccountStatusName
    , BlockingSource
FROM BlockingResolution;
GO
