--WITH SCHEMABINDING
AS
RETURN 
SELECT 
		i.FullName,
		i.ID,
		i.Guid,
		i.EmailAddress,
		i.JobTitle,
		i.BillableRate,
		i.Signature
	FROM SCore.Identities i 
	JOIN SCore.OrganisationalUnits org ON (org.ID = i.OriganisationalUnitId)
