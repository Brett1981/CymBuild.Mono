		CYB-321: 
		Only enable the below fields if the quote has been revised.
	 */
	 IF(@RevisionNumber < 1)
	 BEGIN
		INSERT @ValidationResult
        (
            TargetGuid,
            TargetType,
            IsReadOnly,
            IsHidden,
            IsInvalid,
            Message
