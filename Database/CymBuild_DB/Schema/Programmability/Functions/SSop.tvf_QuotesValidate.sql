          AND epfvv.Hobt IN (N'Quotes')
		  AND epfvv.Name IN (
				N'ClientAccountId', 
				N'ClientAddressId', 
				N'ClientContactId', 
				N'AgentAccountId', 
				N'AgentAddressId', 
				N'AgentContactId',
				N'PropertyId'
		  );
	 END;


	IF(EXISTS(
					SELECT 1 
					FROM SSop.QuoteItems root_hobt
					JOIN SSop.Quotes q ON (q.ID = root_hobt.QuoteId)
