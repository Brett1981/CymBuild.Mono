    SET @IsExpired  = CASE WHEN @LatestWorkflowStatusGuid = @ExpiredStatus  THEN 1 ELSE 0 END;
    SET @IsReopened = CASE WHEN @LatestWorkflowStatusGuid = @Reopened       THEN 1 ELSE 0 END;
    -------------------------------------------------------------------------
    -- Prevent changing Quote if Enquiry not ready for quote review
    -------------------------------------------------------------------------

	/*
		Additional check for reopened status. 

		=======================================================================================
		= SET @IsReopened = CASE WHEN @LatestWorkflowStatusGuid = @Reopenen THEN 1 ELSE 0 END =
		=======================================================================================

		The above is based on the last available status. Currently, if we reopen a quote,
		it first assigns "Reopened" and then immediately after that "Quoting". Aka, it would fail.


	*/
	IF(@IsReopened = 0)
	BEGIN

		IF(EXISTS
				(
					SELECT 1  
					FROM SCore.DataObjectTransition AS Dob
					JOIN SCore.WorkflowStatus AS wfs ON (Dob.StatusID = wfs.ID)
					WHERE 
								(Dob.RowStatus NOT IN (0, 254))
							AND (wfs.RowStatus NOT IN (0,254))
							AND (Dob.DataObjectGuid = @Guid)
							AND (
										wfs.Guid = '9A60F983-24BA-4733-907E-C5CCE0B691CB' --Quoting
									OR  wfs.Guid = '34EF363A-C8F7-4BA8-A2C6-067EBAEF12FD' --Reopened
								)
							AND (
										dob.Comment LIKE N'%Reopened quote returned to quoting.%'
									OR  dob.Comment LIKE N'%System Imported%'
								)
							AND NOT EXISTS
								(
									SELECT 1  
									FROM SCore.DataObjectTransition AS Dob2
									JOIN SCore.WorkflowStatus AS wfs2 ON (Dob2.StatusID = wfs2.ID)
									WHERE 
											(Dob2.RowStatus NOT IN (0, 254))
										AND (wfs2.RowStatus NOT IN (0, 254))
										AND (Dob2.DataObjectGuid = @Guid )
										AND (Dob2.ID > Dob.ID)
								)
				)
		  )

		  SET @IsReopened = 1

	 END;

    -------------------------------------------------------------------------
    -- CYB-462
    -- Quote Superusers (same QUOTESU group SSop.QuoteReopen checks) can keep
    -- editing a quote after it has been sent.
    -------------------------------------------------------------------------
    DECLARE @UserID INT = ISNULL(CONVERT(INT, SESSION_CONTEXT(N'user_id')), -1);
    DECLARE @IsQuoteSuperUser BIT = 0;

    IF EXISTS
    (
        SELECT 1
        FROM SCore.UserGroups AS ug
        JOIN SCore.Groups AS g
            ON g.ID = ug.GroupID
        WHERE ug.IdentityID = @UserID
          AND g.Code = N'QUOTESU'
          AND ug.RowStatus NOT IN (0,254)
          AND g.RowStatus NOT IN (0,254)
    )
    BEGIN
        SET @IsQuoteSuperUser = 1;
    END;

    -------------------------------------------------------------------------
    -- CYB-462
    -- A quote counts as sent once a Sent transition exists after its latest
    -- Reopened transition. The Sent status stays in force through the later
    -- statuses (1st/2nd Chase, Accepted...). QuoteReopen does not clear
    -- DateSent, so DateSent alone only counts for quotes never reopened
    -- (legacy rows without workflow history).
    -- A 1st/2nd Chase or Customer Accepted transition also counts as sent:
    -- legacy accepted quotes have an Accepted status but no Sent status and
    -- often no DateSent.
    -------------------------------------------------------------------------
    DECLARE @LastReopenedTransitionID INT = NULL;
    DECLARE @HasBeenSent BIT = 0;

    SELECT @LastReopenedTransitionID = MAX(dot.ID)
    FROM SCore.DataObjectTransition AS dot
    JOIN SCore.WorkflowStatus AS wfs
        ON wfs.ID = dot.StatusID
    WHERE dot.DataObjectGuid = @Guid
      AND dot.RowStatus NOT IN (0,254)
      AND wfs.RowStatus NOT IN (0,254)
      AND wfs.Guid = @Reopened;

    IF EXISTS
    (
        SELECT 1
        FROM SCore.DataObjectTransition AS dot
        JOIN SCore.WorkflowStatus AS wfs
            ON wfs.ID = dot.StatusID
        WHERE dot.DataObjectGuid = @Guid
          AND dot.RowStatus NOT IN (0,254)
          AND wfs.RowStatus NOT IN (0,254)
          AND wfs.Guid IN
              (
                  @SentStatus,
                  '9FF22CEA-A2A6-4907-9B2D-E62DF8150913', -- 1st Chase
                  '1F01C16B-1A73-4844-A938-FE357405FD93', -- 2nd Chase
                  @AcceptedStatus
              )
          AND dot.ID > ISNULL(@LastReopenedTransitionID, 0)
    )
    OR (@DateSent IS NOT NULL AND @LastReopenedTransitionID IS NULL)
    BEGIN
        SET @HasBeenSent = 1;
    END;

