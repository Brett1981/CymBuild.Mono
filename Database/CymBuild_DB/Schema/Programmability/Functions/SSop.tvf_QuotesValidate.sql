    -- Latest-only flags
    SET @Final      = CASE WHEN @LatestWorkflowStatusGuid = @FinalStatus    THEN 1 ELSE 0 END;
    SET @IsSent     = CASE WHEN @LatestWorkflowStatusGuid = @SentStatus     THEN 1 ELSE 0 END;
