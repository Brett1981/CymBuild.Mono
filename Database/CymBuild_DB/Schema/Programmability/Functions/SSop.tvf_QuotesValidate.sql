        INSERT @ValidationResult (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
        SELECT epfvv.Guid, N'P', 1, 0, 0, N''
        FROM SCore.EntityPropertiesForValidationV epfvv
        WHERE epfvv.[Schema] = N'SSop'
          AND epfvv.Hobt = N'Quotes'
          AND epfvv.Name NOT IN
          (
              N'ChaseDate2', N'ChaseDate1', N'RejectionReason', N'DateRejected', N'DateAccepted',
              N'IsFinal', N'DateSent', N'ExpiryDate'
          );
        INSERT @ValidationResult (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
        SELECT epfvv.Guid, N'P', 1, 0, 0, N''
        FROM SCore.EntityPropertiesForValidationV epfvv
        WHERE epfvv.[Schema] = N'SSop'
          AND epfvv.Hobt = N'Quote_ExtendedInfo';
    END;
    -------------------------------------------------------------------------
    -- CYB-462
    -- Sent lockdown: once sent, every quote field (ExpiryDate included) and
    -- Quote_ExtendedInfo locks permanently. General users can only record
    -- status changes (chase, accepted, rejected). Quote Superusers are exempt.
    -------------------------------------------------------------------------
    IF (@HasBeenSent = 1 AND @IsQuoteSuperUser = 0 AND @IsReopened = 0)
    BEGIN
        INSERT @ValidationResult (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
        SELECT epfvv.Guid, N'P', 1, 0, 0, N''
        FROM SCore.EntityPropertiesForValidationV epfvv
        WHERE epfvv.[Schema] = N'SSop'
          AND epfvv.Hobt = N'Quotes'
          AND epfvv.Name NOT IN
          (
              N'ChaseDate2', N'ChaseDate1', N'RejectionReason', N'DateRejected', N'DateAccepted'
          );
        INSERT @ValidationResult (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
        SELECT epfvv.Guid, N'P', 1, 0, 0, N''
        FROM SCore.EntityPropertiesForValidationV epfvv
        WHERE epfvv.[Schema] = N'SSop'
          AND epfvv.Hobt = N'Quote_ExtendedInfo';
    END;
    -------------------------------------------------------------------------
    -- CYB-461
    -- Expired lockdown: an expired quote is fully read-only (every Quotes
    -- and Quote_ExtendedInfo field) for general users, whatever status it
    -- expired from. Quote Superusers are exempt.
    -------------------------------------------------------------------------
    IF (@IsExpired = 1 AND @IsQuoteSuperUser = 0 AND @IsReopened = 0)
    BEGIN
        INSERT @ValidationResult (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
        SELECT epfvv.Guid, N'P', 1, 0, 0, N''
        FROM SCore.EntityPropertiesForValidationV epfvv
        WHERE epfvv.[Schema] = N'SSop'
          AND epfvv.Hobt IN (N'Quotes', N'Quote_ExtendedInfo');
    END;
    -------------------------------------------------------------------------
    -- Complete-status lock (latest-only)
    -------------------------------------------------------------------------
    IF (@LatestIsCompleteStatus = 1 AND @IsReopened = 0 )
    BEGIN
        INSERT @ValidationResult (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
        SELECT epfvv.Guid, N'P', 1, 0, 0, N''
        FROM SCore.EntityPropertiesForValidationV epfvv
        WHERE epfvv.[Schema] = N'SSop'
          AND epfvv.Hobt     = N'Quotes';
    END;
    RETURN;
END;
