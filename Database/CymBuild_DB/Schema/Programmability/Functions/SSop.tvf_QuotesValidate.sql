    DECLARE @DeadStatus     UNIQUEIDENTIFIER = '8C7F7526-559F-4CCF-8FC2-DB0DA67E793D';
    -- CYB-461: saved by SSop.ExpireOverdueQuotesAndEnquiries
    DECLARE @ExpiredStatus  UNIQUEIDENTIFIER = 'E6FAC201-F98B-4B3A-AB55-83DC9F802D00';
