    -------------------------------------------------------------------------
    -- Determine flags based on the LATEST workflow transition for this Quote (latest-only)
    -------------------------------------------------------------------------
DECLARE
      @LatestWorkflowStatusGuid UNIQUEIDENTIFIER = NULL
    , @LatestIsActiveStatus     BIT              = NULL
