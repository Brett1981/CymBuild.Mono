CREATE OR ALTER FUNCTION [SOffice].[tvf_SuggestedFilingLocations]
(
    @TargetObjectID BIGINT,
    @EntityTypeId INT,
    @WindowStart DATETIME2
)
RETURNS TABLE
    --WITH SCHEMABINDING
AS
RETURN
(
    -- This record's own filing history in the window - the primary ranking signal.
    SELECT
        oe.FilingLocationUrl,
        CAST(N'Record' AS NVARCHAR(20)) AS Scope,
        COUNT(*) AS FiledCount,
        MAX(oe.FiledDateTime) AS LastFiledDateTime
    FROM [SOffice].[OutlookEmails] oe
    WHERE
        oe.RowStatus = 1
        AND oe.IsFiled = 1
        AND oe.FilingLocationUrl <> N''
        AND oe.TargetObjectID = @TargetObjectID
        AND oe.SentDateTime >= @WindowStart
    GROUP BY
        oe.FilingLocationUrl

    UNION ALL

    -- Fallback signal for records with little/no history of their own: most-used folders among
    -- other records of the same EntityType. Bounded with TOP since the caller only ever needs
    -- a handful of candidates, not every folder ever used.
    SELECT TOP (20)
        oe.FilingLocationUrl,
        CAST(N'EntityType' AS NVARCHAR(20)) AS Scope,
        COUNT(*) AS FiledCount,
        MAX(oe.FiledDateTime) AS LastFiledDateTime
    FROM [SOffice].[OutlookEmails] oe
    JOIN [SOffice].[TargetObjects] t ON t.ID = oe.TargetObjectID
    WHERE
        oe.RowStatus = 1
        AND oe.IsFiled = 1
        AND oe.FilingLocationUrl <> N''
        AND t.EntityTypeId = @EntityTypeId
        AND oe.TargetObjectID <> @TargetObjectID
        AND oe.SentDateTime >= @WindowStart
    GROUP BY
        oe.FilingLocationUrl
    ORDER BY
        COUNT(*) DESC
);
GO
