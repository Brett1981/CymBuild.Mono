	--END

	/*
		Hide timesheet items when UseTimeSheet is false
	*/
	IF (
		SELECT	jt.UseTimeSheets
		FROM	SJob.JobTypes jt
		JOIN	SJob.Jobs j ON (j.JobTypeID = jt.ID)
		WHERE	(j.Guid = @JobGuid)
	) = 0
	BEGIN
		SELECT	@EntityPropertyGuid = SCore.GetEntityPropertyGuid(N'SJob', N'Activities', N'InvoicingQuantity')

		INSERT	@ValidationResult
			 (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
		VALUES
			 (
				 @EntityPropertyGuid,
				 N'P',
				 0,
				 1,
				 0,
				 N''
			 );

		SELECT	@EntityPropertyGuid = SCore.GetEntityPropertyGuid(N'SJob', N'Activities', N'InvoicingValue')

		INSERT @ValidationResult
				(
					TargetGuid,
					TargetType,
					IsReadOnly,
					IsHidden,
					IsInvalid,
					Message
				)
		VALUES
				(
					@EntityPropertyGuid,
					N'P',
					0,
					1,
					0,
					N''
				);

		SELECT	@EntityPropertyGuid = SCore.GetEntityPropertyGuid(N'SJob', N'Activities', N'IsAdditionalWork')

		INSERT @ValidationResult
				(
					TargetGuid,
					TargetType,
					IsReadOnly,
					IsHidden,
					IsInvalid,
					Message
				)
		VALUES
				(
					@EntityPropertyGuid,
					N'P',
					0,
					1,
					0,
					N''
				);
	END

	/*
		[CYB-333] "Is part of the agreed fee?" only applies to billable activities. Once a fee
		amendment has been raised for the activity the answer is locked.
	*/
	IF NOT EXISTS
	(
		SELECT	1
		FROM	SJob.ActivityTypes AS at
		WHERE	(at.[Guid] = @ActivityTypeGuid)
			AND	(at.IsBillable = 1)
	)
	BEGIN
		INSERT	@ValidationResult
			 (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
		SELECT	epfvv.Guid,
				N'P',
				0,
				1,
				0,
				N''
		FROM	SCore.EntityPropertiesForValidationV AS epfvv
		WHERE	(epfvv.[Schema] = N'SJob')
			AND	(epfvv.Hobt = N'Activities')
			AND	(epfvv.Name = N'IsPartOfAgreedFee');
	END
	ELSE IF EXISTS
	(
		SELECT	1
		FROM	SJob.Activities AS a
		JOIN	SJob.FeeAmendment AS fa ON (fa.ActivityID = a.ID)
		WHERE	(a.[Guid] = @Guid)
			AND	(fa.RowStatus NOT IN (0,254))
	)
	BEGIN
		INSERT	@ValidationResult
			 (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
		SELECT	epfvv.Guid,
				N'P',
				1,
				0,
				0,
				N''
		FROM	SCore.EntityPropertiesForValidationV AS epfvv
		WHERE	(epfvv.[Schema] = N'SJob')
			AND	(epfvv.Hobt = N'Activities')
			AND	(epfvv.Name = N'IsPartOfAgreedFee');
	END

	/*
		[CYB-333] A billable activity that is not part of the agreed fee raises a fee amendment on its
		job stage for its fee, so both are required. The fee (Invoicing Value or Quantity) is only
		required where the form shows it: job types that do not use timesheets hide it, and the
		amount is entered on the amendment instead.
	*/
	IF	(@IsPartOfAgreedFee = 0)
		AND	(EXISTS
				(
					SELECT	1
					FROM	SJob.ActivityTypes AS at
					WHERE	(at.[Guid] = @ActivityTypeGuid)
						AND	(at.IsBillable = 1)
				)
			)
	BEGIN
		IF NOT EXISTS
		(
			SELECT	1
			FROM	SJob.RibaStages AS rs
			WHERE	(rs.[Guid] = @RibaStageGuid)
				AND	(rs.ID > 0)
				AND	(rs.RowStatus NOT IN (0,254))
		)
		BEGIN
			INSERT	@ValidationResult
				 (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
			SELECT	epfvv.Guid,
					N'P',
					0,
					0,
					1,
					N'Select the job stage for the fee amendment.'
			FROM	SCore.EntityPropertiesForValidationV AS epfvv
			WHERE	(epfvv.[Schema] = N'SJob')
				AND	(epfvv.Hobt = N'Activities')
				AND	(epfvv.Name = N'RibaStageId');
		END

		IF	(ISNULL(
				(
					SELECT	jt.UseTimeSheets
					FROM	SJob.JobTypes jt
					JOIN	SJob.Jobs j ON (j.JobTypeID = jt.ID)
					WHERE	(j.Guid = @JobGuid)
				), 1) = 1)
			AND	(ISNULL(@InvoicingValue, 0) <= 0)
			AND	(ISNULL(@InvoicingQuantity, 0) <= 0)
		BEGIN
			INSERT	@ValidationResult
				 (TargetGuid, TargetType, IsReadOnly, IsHidden, IsInvalid, Message)
			SELECT	epfvv.Guid,
					N'P',
					0,
					0,
					1,
					N'Enter the Invoicing Value or Quantity for the fee amendment.'
			FROM	SCore.EntityPropertiesForValidationV AS epfvv
			WHERE	(epfvv.[Schema] = N'SJob')
				AND	(epfvv.Hobt = N'Activities')
				AND	(epfvv.Name IN (N'InvoicingValue'));
		END
	END




	RETURN;
END;
