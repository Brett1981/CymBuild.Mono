CREATE OR ALTER FUNCTION [SJob].[tvf_JobFeeDrawdown]
(
    @UserId INT,
    @ParentGuid UNIQUEIDENTIFIER
)
RETURNS TABLE
AS
RETURN
    SELECT
        j.RowStatus,
        j.Guid,
        j.Stage,
        j.StageLabel,
        j.Agreed,
        j.Invoiced,
        j.Paid,
        j.Remaining,
        CONVERT(INT, j.QuotedMeetings) AS QuotedMeetings,
        j.CompletedMeetings,
        CONVERT(INT, j.QuotedSiteVisits) AS QuotedSiteVisits,
        j.CompletedSiteVisits,
        ISNULL(subcontractor.SubcontractorCosts, 0) AS SubcontractorCosts,
        j.IsTotalHighlightRow,
		j.Variation
    FROM SJob.Job_FeeDrawdown AS j
    OUTER APPLY
    (
        SELECT
            CAST(SUM(sci.ValueWithoutVAT) AS DECIMAL(19, 2)) AS SubcontractorCosts
        FROM SJob.SubContractorInvoices AS sci
        LEFT JOIN SJob.Activities AS a
            ON a.ID = sci.ActivityId
           AND a.RowStatus NOT IN (0, 254)
        WHERE sci.JobId = j.JobId
          AND sci.ID > 0
          AND sci.RowStatus NOT IN (0, 254)
          AND
          (
                 j.StageId IN (-2, -3)
              OR a.RibaStageId = j.StageId
          )
    ) AS subcontractor
    WHERE j.Guid = @ParentGuid
      AND j.RowStatus NOT IN (0, 254)
      AND EXISTS
      (
          SELECT 1
          FROM SCore.ObjectSecurityForUser_CanRead(j.Guid, @UserId) AS oscr
      );
GO
