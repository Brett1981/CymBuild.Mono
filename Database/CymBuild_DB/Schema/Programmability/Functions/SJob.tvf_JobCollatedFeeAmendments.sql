/*
    CYB-336
    Fee Amendment Reporting: collated fee amendment grid for the Job page.

    One row per active SJob.FeeAmendment for the parent job, with the request,
    approval and latest chase details plus the job's Job Type, Lead Consultant,
    BU and Department for filtering/export.

    RibaStage lists every stage the amendment changes (fee, meeting or visit),
    covering the legacy fixed columns (mapped by SJob.RibaStages.Number exactly as
    SJob.Job_FeeDrawdown does), SJob.FeeAmendmentRibaStages and SJob.CustomFeeAmendment.
    TotalStageChange uses the same calculation as SJob.tvf_FeeAmendments.TotalRibaStageChange.
*/
CREATE OR ALTER FUNCTION [SJob].[tvf_JobCollatedFeeAmendments]
	(
		@UserId INT
	)
RETURNS TABLE
                   --WITH SCHEMABINDING
AS
RETURN SELECT		fa.ID,
					fa.RowStatus,
					fa.RowVersion,
					fa.Guid,
					j.Guid AS JobId,
					legacy_check.DateReceivedRequest,
					YEAR(legacy_check.DateReceivedRequest) AS YearReceived,
					requestedBy.FullName AS RequestedBy,
					j.Number AS JobNumber,
					jt.Name AS JobType,
					stages.RibaStage,
					fa.OriginalAgreedFee,
					CAST
					(
						fa.RibaStage0Change
					  + fa.RibaStage1Change
					  + fa.RibaStage2Change
					  + fa.RibaStage3Change
					  + fa.RibaStage4Change
					  + fa.RibaStage5Change
					  + fa.RibaStage6Change
					  + fa.RibaStage7Change
					  + fa.PreConstructionStageChange
					  + fa.ConstructionStageChange
					  + ISNULL(dynamic_totals.DynamicRibaStageChange, 0)
						AS DECIMAL(19,2)
					) AS TotalStageChange,
					fa.NewTotalAgreedFee AS TotalNewAgreedFee,
					fa.Comments,
					fas.Name AS Status,
					createdBy.FullName AS [User],
					CONVERT(DATE, fa.CreatedDateTime) AS CreatedDate,
					sentTo.DisplayName AS SentTo,
					CONVERT(DATE, latest_chase.DateChased) AS DateChased,
					latest_chase.ChasedBy,
					fa.DateAgreed,
					agreedBy.FullName AS AgreedStatusBy,
					ISNULL(fa.RejectionReason, N'') AS ReasonIfRejected,
					leadConsultant.FullName AS LeadConsultant,
					bu.Name AS BusinessUnit,
					dept.Name AS Department
	   FROM			SJob.FeeAmendment			AS fa
	   JOIN			SJob.Jobs					AS j ON (j.ID = fa.JobID)
	   JOIN			SJob.JobTypes				AS jt ON (jt.ID = j.JobTypeID)
	   JOIN			SJob.FeeAmendmentStatus		AS fas ON (fas.ID = fa.FeeAmendmentStatusID)
	   JOIN			SCore.Identities			AS createdBy ON (createdBy.ID = fa.CreatedByUserID)
	   JOIN			SCore.Identities			AS requestedBy ON (requestedBy.ID = fa.RequestedByUserID)
	   JOIN			SCore.Identities			AS agreedBy ON (agreedBy.ID = fa.AgreedStatusByUserID)
	   JOIN			SCore.Identities			AS leadConsultant ON (leadConsultant.ID = j.SurveyorID)
	   LEFT JOIN	SCrm.AccountContacts		AS sentToAc ON (sentToAc.ID = fa.SentToContactID)
	   LEFT JOIN	SCrm.Contacts				AS sentTo ON (sentTo.ID = sentToAc.ContactID)
	   LEFT JOIN	SCore.OrganisationalUnits	AS dept ON (dept.ID = j.OrganisationalUnitID)
	   LEFT JOIN	SCore.OrganisationalUnits	AS bu ON (bu.ID = dept.ParentID)
	   CROSS APPLY
	   (
			-- Pre-CYB-237 amendments (FeeAmendmentStatusID = -1) were backfilled with the
			-- migration date by DF_FeeAmendment_DateReceivedRequest, so use the amendment's created date instead.
			SELECT	CASE
						WHEN fa.FeeAmendmentStatusID = -1 THEN CONVERT(DATE, fa.CreatedDateTime)
						ELSE fa.DateReceivedRequest
					END AS DateReceivedRequest
	   ) AS legacy_check
	   OUTER APPLY
	   (
			SELECT	SUM(x.FeeChange) AS DynamicRibaStageChange
			FROM
			(
				SELECT	fars.FeeChange
				FROM	SJob.FeeAmendmentRibaStages AS fars
				WHERE	(fars.FeeAmendmentID = fa.ID)
					AND	(fars.RowStatus NOT IN (0, 254))

				UNION ALL

				SELECT	cfa.StageChange
				FROM	SJob.CustomFeeAmendment AS cfa
				WHERE	(cfa.FeeAmendmentId = fa.ID)
					AND	(cfa.RowStatus NOT IN (0, 254))
			) AS x
	   ) AS dynamic_totals
	   OUTER APPLY
	   (
			SELECT	STRING_AGG(CONVERT(NVARCHAR(MAX), rs.Description), N', ')
						WITHIN GROUP (ORDER BY rs.Number, rs.Description) AS RibaStage
			FROM	SJob.RibaStages AS rs
			WHERE	(rs.ID > 0)
				AND	(
						EXISTS
						(
							SELECT	1
							FROM	(VALUES
										(0,   fa.RibaStage0Change,           fa.RibaStage0MeetingChange,           fa.RibaStage0VisitChange),
										(1,   fa.RibaStage1Change,           fa.RibaStage1MeetingChange,           fa.RibaStage1VisitChange),
										(2,   fa.RibaStage2Change,           fa.RibaStage2MeetingChange,           fa.RibaStage2VisitChange),
										(3,   fa.RibaStage3Change,           fa.RibaStage3MeetingChange,           fa.RibaStage3VisitChange),
										(4,   fa.RibaStage4Change,           fa.RibaStage4MeetingChange,           fa.RibaStage4VisitChange),
										(5,   fa.RibaStage5Change,           fa.RibaStage5MeetingChange,           fa.RibaStage5VisitChange),
										(6,   fa.RibaStage6Change,           fa.RibaStage6MeetingChange,           fa.RibaStage6VisitChange),
										(7,   fa.RibaStage7Change,           fa.RibaStage7MeetingChange,           fa.RibaStage7VisitChange),
										(99,  fa.PreConstructionStageChange, fa.PreConstructionStageMeetingChange, fa.PreConstructionStageVisitChange),
										(999, fa.ConstructionStageChange,    fa.ConstructionStageMeetingChange,    fa.ConstructionStageVisitChange)
									) AS legacy (StageNumber, FeeChange, MeetingChange, VisitChange)
							WHERE	(legacy.StageNumber = rs.Number)
								AND	(rs.IsCustomStage = 0)
								AND	(rs.RowStatus NOT IN (0, 254))
								AND	((legacy.FeeChange <> 0) OR (legacy.MeetingChange <> 0) OR (legacy.VisitChange <> 0))
						)
					OR	EXISTS
						(
							SELECT	1
							FROM	SJob.FeeAmendmentRibaStages AS fars
							WHERE	(fars.FeeAmendmentID = fa.ID)
								AND	(fars.RibaStageID = rs.ID)
								AND	(fars.RowStatus NOT IN (0, 254))
								AND	((fars.FeeChange <> 0) OR (fars.MeetingChange <> 0) OR (fars.VisitChange <> 0))
						)
					OR	EXISTS
						(
							SELECT	1
							FROM	SJob.CustomFeeAmendment AS cfa
							WHERE	(cfa.FeeAmendmentId = fa.ID)
								AND	(cfa.StageId = rs.ID)
								AND	(cfa.RowStatus NOT IN (0, 254))
								AND	((cfa.StageChange <> 0) OR (cfa.StageMeetingChange <> 0) OR (cfa.StageVisitChange <> 0))
						)
					)
	   ) AS stages
	   OUTER APPLY
	   (
			SELECT	TOP (1)
					fac.DateChased,
					chasedBy.FullName AS ChasedBy
			FROM	SJob.FeeAmendmentChase	AS fac
			JOIN	SCore.Identities		AS chasedBy ON (chasedBy.ID = fac.ChasedByUserID)
			WHERE	(fac.FeeAmendmentID = fa.ID)
				AND	(fac.RowStatus NOT IN (0, 254))
			ORDER BY fac.DateChased DESC, fac.ID DESC
	   ) AS latest_chase
	   WHERE		(fa.RowStatus NOT IN (0, 254))
				AND	(EXISTS
			(
				SELECT	1
				FROM	SCore.ObjectSecurityForUser_CanRead (fa.Guid, @UserId) oscr
			)
		)
GO
