CREATE OR ALTER FUNCTION [SOffice].[tvf_FrequentFilingRecords]
    (
        @Mailbox NVARCHAR(250),
        @WindowStart DATETIME2
    )
RETURNS TABLE
AS
RETURN
    (
        SELECT TOP (20)
                    t.ID,
                    t.Guid,
                    et.Name                 AS EntityTypeName,
                    t.Name,
                    COUNT(*)                AS FiledCount,
                    MAX(oe.FiledDateTime)   AS LastFiledDateTime
        FROM        SOffice.OutlookEmails AS oe
        JOIN        SOffice.OutlookEmailMailboxes AS mb ON (mb.ID = oe.OutlookEmailMailboxID)
        JOIN        SOffice.TargetObjects AS t ON (t.ID = oe.TargetObjectID)
        JOIN        SOffice.EntityTypes AS et ON (et.ID = t.EntityTypeId)
        WHERE       (oe.RowStatus NOT IN (0, 254))
                AND (t.RowStatus NOT IN (0, 254))
                AND (et.RowStatus NOT IN (0, 254))
                AND (oe.IsFiled = 1)
                AND (oe.FiledDateTime >= @WindowStart)
                AND (mb.Name = @Mailbox)
                AND (@Mailbox <> N'')
        GROUP BY    t.ID,
                    t.Guid,
                    et.Name,
                    t.Name
        ORDER BY    COUNT(*) DESC,
                    MAX(oe.FiledDateTime) DESC
    );
GO
