/*
    CYB-553: SSop.Quote_JobsSummary's RibaStages join previously had no fallback for
    QuoteItems.ProvideAtStageID = -1 ("no stage set"), so those quote items were
    silently excluded from the fixed fee columns SSop.QuoteCreateJobs writes onto a
    new Job at creation time. This leaves the affected Job's own fee data at zero
    even though the originating quote item carries a real value (e.g. Job 9433).

    This procedure finds Jobs safely eligible for correction - Jobs whose fixed fee
    columns AND SJob.JobRibaStageFees are both entirely empty/zero, created from a
    Quote with at least one QuoteItem where ProvideAtStageID = -1 and a non-zero
    LineNet - and, when @PreviewOnly = 0, corrects them by calling the existing,
    already-correct SJob.JobRibaStageFees_UpsertFromCreatedQuoteItems for each one
    (the same procedure that already applies the -1 -> 2 sentinel remap).

    Jobs whose fixed fee columns are only PARTIALLY populated are deliberately
    excluded and reported separately, never auto-corrected: forcing dynamic-stage
    mode (SJob.JobRibaStageFees having any row) on a Job that already has legitimate
    legacy per-stage fee data makes SJob.Job_FeeDrawdown ignore those other legacy
    stage columns entirely, which would blank out real fee data instead of fixing it.
    Those require manual review.

    Run with @PreviewOnly = 1 (default) first and review the report before running
    with @PreviewOnly = 0 to apply the fix.
*/
CREATE OR ALTER PROCEDURE [SJob].[Jobs_BackfillMissingQuoteStageFees_CYB553]
(
    @PreviewOnly BIT = 1
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @Candidates TABLE
    (
        JobID INT NOT NULL PRIMARY KEY,
        HasPartialLegacyFees BIT NOT NULL
    );

    INSERT INTO @Candidates
    (
        JobID,
        HasPartialLegacyFees
    )
    SELECT
        j.ID,
        CASE
            WHEN
                  ISNULL(j.AgreedFee, 0) + ISNULL(j.RibaStage1Fee, 0) + ISNULL(j.RibaStage2Fee, 0)
                + ISNULL(j.RibaStage3Fee, 0) + ISNULL(j.RibaStage4Fee, 0) + ISNULL(j.RibaStage5Fee, 0)
                + ISNULL(j.RibaStage6Fee, 0) + ISNULL(j.RibaStage7Fee, 0)
                + ISNULL(j.PreConstructionStageFee, 0) + ISNULL(j.ConstructionStageFee, 0) <> 0
                THEN 1
            ELSE 0
        END AS HasPartialLegacyFees
    FROM SJob.Jobs AS j
    WHERE j.RowStatus NOT IN (0, 254)
      AND NOT EXISTS
      (
          SELECT 1
          FROM SJob.JobRibaStageFees AS jrsf
          WHERE jrsf.JobID = j.ID
            AND jrsf.RowStatus NOT IN (0, 254)
      )
      AND EXISTS
      (
          SELECT 1
          FROM SSop.QuoteItems AS qi
          JOIN SSop.QuoteItemTotals AS qit
              ON qit.ID = qi.ID
          WHERE qi.CreatedJobId = j.ID
            AND qi.RowStatus NOT IN (0, 254)
            AND qi.ProvideAtStageID = -1
            AND ISNULL(qit.LineNet, 0) <> 0
      );

    IF @PreviewOnly = 1
    BEGIN
        SELECT
            c.JobID,
            j.Number AS JobNumber,
            c.HasPartialLegacyFees,
            CASE
                WHEN c.HasPartialLegacyFees = 1 THEN N'SKIP - manual review required'
                ELSE N'FIX - safe to backfill'
            END AS ProposedAction
        FROM @Candidates AS c
        JOIN SJob.Jobs AS j
            ON j.ID = c.JobID
        ORDER BY
            c.HasPartialLegacyFees,
            c.JobID;

        RETURN;
    END;

    DECLARE @JobID INT;

    DECLARE candidate_cursor CURSOR LOCAL FAST_FORWARD FOR
        SELECT JobID
        FROM @Candidates
        WHERE HasPartialLegacyFees = 0;

    OPEN candidate_cursor;
    FETCH NEXT FROM candidate_cursor INTO @JobID;

    WHILE @@FETCH_STATUS = 0
    BEGIN
        EXEC SJob.JobRibaStageFees_UpsertFromCreatedQuoteItems @JobID = @JobID;
        FETCH NEXT FROM candidate_cursor INTO @JobID;
    END;

    CLOSE candidate_cursor;
    DEALLOCATE candidate_cursor;

    SELECT
        c.JobID,
        j.Number AS JobNumber,
        N'FIXED' AS Action
    FROM @Candidates AS c
    JOIN SJob.Jobs AS j
        ON j.ID = c.JobID
    WHERE c.HasPartialLegacyFees = 0
    ORDER BY
        c.JobID;

    SELECT
        c.JobID,
        j.Number AS JobNumber,
        N'SKIPPED - manual review required' AS Action
    FROM @Candidates AS c
    JOIN SJob.Jobs AS j
        ON j.ID = c.JobID
    WHERE c.HasPartialLegacyFees = 1
    ORDER BY
        c.JobID;
END;
GO
