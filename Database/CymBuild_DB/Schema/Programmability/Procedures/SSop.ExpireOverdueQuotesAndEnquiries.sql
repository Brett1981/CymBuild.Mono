/* =============================================================================
   CYB-461 - Enquiry and Quote auto-expiry
   Object: SSop.ExpireOverdueQuotesAndEnquiries

   Records a saved "Expired" workflow status for every Quote and Enquiry that
   the calculated-status views already show as expired:
   - Quotes:    SSop.Quote_CalculatedFields.QuoteStatus = 'Expired'
                (Quoting / Ready to Send / Sent / 1st Chase / 2nd Chase past
                ExpiryDate, or a legacy quote with no history past ExpiryDate).
   - Enquiries: SSop.Enquiry_CalculatedFields.EnquiryStatus IN
                ('Expired', 'Quote Expired') (no quotes and the quoting deadline
                passed more than 2 days ago, or every quote expired).

   The views stay the single definition of the expiry rules; this procedure
   only persists them. Every status is written through
   SCore.DataObjectTransitionUpsert, never directly.

   Idempotent and retry-safe: a record whose latest saved status is already
   "Expired" is skipped, and an application lock stops concurrent runs (the
   API runs this from a hosted worker on more than one replica).

   Notifications: a record that expired more than @NotifyWithinDays ago is
   expired silently (notification triggers suppressed through session
   context), so the first run clears the historic backlog without sending a
   notification per record. Recently expired records notify normally.

   Result sets:
   1) one summary row: LockAcquired, QuotesExpired, EnquiriesExpired,
      ExpiredSilently, Failed
   2) one row per failed record: RecordType, RecordGuid, ErrorMessage
============================================================================= */
CREATE OR ALTER PROCEDURE [SSop].[ExpireOverdueQuotesAndEnquiries]
(
    @ServiceUserGuid UNIQUEIDENTIFIER,
    @MaxRecords INT = 500,
    @NotifyWithinDays INT = 7
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ExpiredStatusGuid UNIQUEIDENTIFIER = 'E6FAC201-F98B-4B3A-AB55-83DC9F802D00';
    DECLARE @EmptyGuid UNIQUEIDENTIFIER = '00000000-0000-0000-0000-000000000000';
    DECLARE @LockName NVARCHAR(255) = N'SSop.ExpireOverdueQuotesAndEnquiries';

    IF NOT EXISTS
    (
        SELECT 1
        FROM SCore.WorkflowStatus ws
        WHERE ws.Guid = @ExpiredStatusGuid
          AND ws.RowStatus NOT IN (0,254)
          AND ws.ShowInQuotes = 1
          AND ws.ShowInEnquiries = 1
    )
        THROW 62001, N'ExpireOverdueQuotesAndEnquiries: the "Expired" WorkflowStatus (E6FAC201-F98B-4B3A-AB55-83DC9F802D00) is missing, inactive, or not enabled for Quotes and Enquiries.', 1;

    IF NOT EXISTS
    (
        SELECT 1
        FROM SCore.Identities i
        WHERE i.Guid = @ServiceUserGuid
          AND i.RowStatus NOT IN (0,254)
    )
        THROW 62002, N'ExpireOverdueQuotesAndEnquiries: @ServiceUserGuid does not match an active SCore.Identities row.', 1;

    IF (@MaxRecords IS NULL OR @MaxRecords <= 0)
        SET @MaxRecords = 500;

    IF (@NotifyWithinDays IS NULL OR @NotifyWithinDays < 0)
        SET @NotifyWithinDays = 0;

    DECLARE @LockResult INT;

    EXEC @LockResult = sys.sp_getapplock
        @Resource    = @LockName,
        @LockMode    = N'Exclusive',
        @LockOwner   = N'Session',
        @LockTimeout = 0;

    IF (@LockResult < 0)
    BEGIN
        SELECT
            LockAcquired     = CONVERT(bit, 0),
            QuotesExpired    = 0,
            EnquiriesExpired = 0,
            ExpiredSilently  = 0,
            Failed           = 0;

        SELECT
            RecordType   = CONVERT(nvarchar(10), NULL),
            RecordGuid   = CONVERT(uniqueidentifier, NULL),
            ErrorMessage = CONVERT(nvarchar(4000), NULL)
        WHERE 1 = 0;

        RETURN;
    END

    DECLARE @TodayUtc DATE = CONVERT(date, SYSUTCDATETIME());
    DECLARE @NotifyFrom DATE = DATEADD(DAY, -@NotifyWithinDays, @TodayUtc);

    DECLARE @PreviousDisableTriggers SQL_VARIANT = SESSION_CONTEXT(N'S_disable_triggers');
    DECLARE @PreviousDisableNotificationTriggers SQL_VARIANT = SESSION_CONTEXT(N'S_disable_notification_triggers');

    DECLARE @QuotesExpired INT = 0;
    DECLARE @EnquiriesExpired INT = 0;
    DECLARE @ExpiredSilently INT = 0;

    DECLARE @Work TABLE
    (
        Seq           INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        RecordType    NVARCHAR(10)      NOT NULL,
        RecordGuid    UNIQUEIDENTIFIER  NOT NULL,
        OldStatusGuid UNIQUEIDENTIFIER  NULL,
        ExpiredOn     DATE              NULL
    );

    DECLARE @Failures TABLE
    (
        RecordType   NVARCHAR(10)     NOT NULL,
        RecordGuid   UNIQUEIDENTIFIER NOT NULL,
        ErrorMessage NVARCHAR(4000)   NOT NULL
    );

    BEGIN TRY
        DECLARE @Phase INT = 1;

        WHILE (@Phase <= 2)
        BEGIN
            DELETE FROM @Work;

            DECLARE @Remaining INT = @MaxRecords - @QuotesExpired - @EnquiriesExpired
                                     - (SELECT COUNT(1) FROM @Failures);

            IF (@Remaining <= 0)
                BREAK;

            IF (@Phase = 1)
            BEGIN
                -- Quotes. Latest status uses ORDER BY ID DESC, matching
                -- SSop.Quote_CalculatedFields. Both expiry branches of the
                -- view need ExpiryDate < today, so that pre-filters the view.
                INSERT INTO @Work (RecordType, RecordGuid, OldStatusGuid, ExpiredOn)
                SELECT TOP (@Remaining)
                    N'Quote',
                    q.Guid,
                    LatestStatus.Guid,
                    q.ExpiryDate
                FROM SSop.Quotes AS q
                JOIN SSop.Quote_CalculatedFields AS qcf ON qcf.ID = q.ID
                OUTER APPLY
                (
                    SELECT TOP (1) wfs.Guid
                    FROM SCore.DataObjectTransition AS dot
                    JOIN SCore.WorkflowStatus AS wfs ON wfs.ID = dot.StatusID
                    WHERE dot.DataObjectGuid = q.Guid
                      AND dot.RowStatus NOT IN (0,254)
                      AND wfs.RowStatus NOT IN (0,254)
                    ORDER BY dot.ID DESC
                ) AS LatestStatus
                WHERE q.RowStatus NOT IN (0,254)
                  AND q.ID > 0
                  AND q.ExpiryDate < @TodayUtc
                  AND qcf.QuoteStatus = N'Expired'
                  AND ISNULL(LatestStatus.Guid, @EmptyGuid) <> @ExpiredStatusGuid
                ORDER BY q.ExpiryDate, q.ID;
            END
            ELSE
            BEGIN
                -- Enquiries, selected after the quotes so quote expiry that
                -- already synced to the enquiry is not written twice. Latest
                -- status matches SSop.Enquiry_CalculatedFields.
                INSERT INTO @Work (RecordType, RecordGuid, OldStatusGuid, ExpiredOn)
                SELECT TOP (@Remaining)
                    N'Enquiry',
                    e.Guid,
                    LatestStatus.Guid,
                    ISNULL(QuoteAgg.LatestExpiryDate, DATEADD(DAY, 2, e.QuotingDeadlineDate))
                FROM SSop.Enquiries AS e
                OUTER APPLY
                (
                    SELECT LatestExpiryDate = MAX(q.ExpiryDate)
                    FROM SSop.EnquiryServices AS es
                    JOIN SSop.Quotes AS q ON q.EnquiryServiceID = es.ID
                    WHERE es.EnquiryId = e.ID
                      AND es.RowStatus NOT IN (0,254)
                      AND q.RowStatus NOT IN (0,254)
                ) AS QuoteAgg
                JOIN SSop.Enquiry_CalculatedFields AS ecf ON ecf.ID = e.ID
                OUTER APPLY
                (
                    SELECT TOP (1) wfs.Guid
                    FROM SCore.DataObjectTransition AS dot
                    JOIN SCore.WorkflowStatus AS wfs ON wfs.ID = dot.StatusID
                    WHERE dot.DataObjectGuid = e.Guid
                      AND dot.RowStatus NOT IN (0,254)
                      AND wfs.RowStatus NOT IN (0,254)
                      AND ISNULL(wfs.ShowInEnquiries, 0) = 1
                    ORDER BY dot.DateTimeUTC DESC, dot.ID DESC
                ) AS LatestStatus
                WHERE e.RowStatus NOT IN (0,254)
                  AND e.ID > 0
                  AND
                  (
                      QuoteAgg.LatestExpiryDate < @TodayUtc
                      OR (QuoteAgg.LatestExpiryDate IS NULL AND e.QuotingDeadlineDate < DATEADD(DAY, -2, @TodayUtc))
                  )
                  AND ecf.EnquiryStatus IN (N'Expired', N'Quote Expired')
                  AND ISNULL(LatestStatus.Guid, @EmptyGuid) <> @ExpiredStatusGuid
                ORDER BY ISNULL(QuoteAgg.LatestExpiryDate, DATEADD(DAY, 2, e.QuotingDeadlineDate)), e.ID;
            END

            DECLARE @Seq INT = 0;

            WHILE (1 = 1)
            BEGIN
                DECLARE @RecordType NVARCHAR(10) = NULL;
                DECLARE @RecordGuid UNIQUEIDENTIFIER = NULL;
                DECLARE @OldStatusGuid UNIQUEIDENTIFIER = NULL;
                DECLARE @ExpiredOn DATE = NULL;

                SELECT TOP (1)
                    @Seq           = w.Seq,
                    @RecordType    = w.RecordType,
                    @RecordGuid    = w.RecordGuid,
                    @OldStatusGuid = w.OldStatusGuid,
                    @ExpiredOn     = w.ExpiredOn
                FROM @Work AS w
                WHERE w.Seq > @Seq
                ORDER BY w.Seq;

                IF (@RecordGuid IS NULL)
                    BREAK;

                DECLARE @Silent BIT = CASE WHEN @ExpiredOn < @NotifyFrom THEN 1 ELSE 0 END;
                DECLARE @TransitionGuid UNIQUEIDENTIFIER = NEWID();
                DECLARE @Comment NVARCHAR(MAX) =
                    CASE @RecordType
                        WHEN N'Quote' THEN N'Automatically expired: the quote expiry date has passed.'
                        ELSE N'Automatically expired: all quotes have expired or the quoting deadline has passed.'
                    END;

                IF (@Silent = 1)
                BEGIN
                    EXEC sys.sp_set_session_context @key = N'S_disable_triggers', @value = 1, @read_only = 0;
                    EXEC sys.sp_set_session_context @key = N'S_disable_notification_triggers', @value = 1, @read_only = 0;
                END

                BEGIN TRY
                    EXEC SCore.DataObjectTransitionUpsert
                        @Guid              = @TransitionGuid,
                        @OldStatusGuid     = @OldStatusGuid,
                        @StatusGuid        = @ExpiredStatusGuid,
                        @Comment           = @Comment,
                        @CreatedByUserGuid = @ServiceUserGuid,
                        @SurveyorUserGuid  = NULL,
                        @DataObjectGuid    = @RecordGuid,
                        @IsImported        = 0;

                    IF (@RecordType = N'Quote')
                        SET @QuotesExpired += 1;
                    ELSE
                        SET @EnquiriesExpired += 1;

                    IF (@Silent = 1)
                        SET @ExpiredSilently += 1;
                END TRY
                BEGIN CATCH
                    -- A caller-owned transaction that is now doomed cannot
                    -- continue; stop and surface the error.
                    IF (XACT_STATE() = -1)
                        THROW;

                    INSERT INTO @Failures (RecordType, RecordGuid, ErrorMessage)
                    VALUES (@RecordType, @RecordGuid, LEFT(ERROR_MESSAGE(), 4000));
                END CATCH

                IF (@Silent = 1)
                BEGIN
                    EXEC sys.sp_set_session_context @key = N'S_disable_triggers', @value = @PreviousDisableTriggers, @read_only = 0;
                    EXEC sys.sp_set_session_context @key = N'S_disable_notification_triggers', @value = @PreviousDisableNotificationTriggers, @read_only = 0;
                END
            END

            SET @Phase += 1;
        END
    END TRY
    BEGIN CATCH
        EXEC sys.sp_set_session_context @key = N'S_disable_triggers', @value = @PreviousDisableTriggers, @read_only = 0;
        EXEC sys.sp_set_session_context @key = N'S_disable_notification_triggers', @value = @PreviousDisableNotificationTriggers, @read_only = 0;
        EXEC sys.sp_releaseapplock @Resource = @LockName, @LockOwner = N'Session';
        THROW;
    END CATCH

    EXEC sys.sp_releaseapplock @Resource = @LockName, @LockOwner = N'Session';

    SELECT
        LockAcquired     = CONVERT(bit, 1),
        QuotesExpired    = @QuotesExpired,
        EnquiriesExpired = @EnquiriesExpired,
        ExpiredSilently  = @ExpiredSilently,
        Failed           = (SELECT COUNT(1) FROM @Failures);

    SELECT f.RecordType, f.RecordGuid, f.ErrorMessage
    FROM @Failures AS f
    ORDER BY f.RecordType, f.RecordGuid;
END
GO
