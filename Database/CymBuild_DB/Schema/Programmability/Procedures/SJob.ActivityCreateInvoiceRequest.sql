	(
		@Guid UNIQUEIDENTIFIER
	)
AS
	BEGIN
		SET NOCOUNT ON

		DECLARE	@MilestoneGuid UNIQUEIDENTIFIER,
				@JobGuid UNIQUEIDENTIFIER,
				@CreatedByUserGuid UNIQUEIDENTIFIER,
				@InvoiceRequestGuid UNIQUEIDENTIFIER = NEWID(),
				@InvoiceRequestItemGuid UNIQUEIDENTIFIER = NEWID(),
				@Net DECIMAL(19,2),
				@FinanceAccountGuid UNIQUEIDENTIFIER,
				@ActivityId INT

		-- CYB-548: WITH (UPDLOCK, HOLDLOCK) takes an update lock on this Activity's row
		-- and holds it for the rest of the caller's transaction. A second call for the
		-- SAME Activity (double-click, or a stalled retry the user repeats) blocks here
		-- until the first call's transaction commits or rolls back, then correctly sees
		-- whatever the first call inserted below - instead of both calls' plain EXISTS
		-- checks passing concurrently under READ COMMITTED and both inserting.
		SELECT	@ActivityId = a.ID
		FROM	SJob.Activities a WITH (UPDLOCK, HOLDLOCK)
		WHERE	(a.Guid = @Guid)

		IF (
			(EXISTS
				(
					SELECT	1
					FROM	SFin.InvoiceRequestItems iri
					WHERE	(iri.ActivityId = @ActivityId)
						AND	(iri.RowStatus NOT IN (0, 254))
				)
			)
			OR (EXISTS
				(
					SELECT	1
					FROM	SFin.TransactionDetails td
					WHERE	(td.ActivityId = @ActivityId)
						AND	(td.RowStatus NOT IN (0, 254))
				)
			)
		)
		BEGIN
			;THROW 60000, N'This Activity has previously been invoiced or an invoice request has already been made.', 1
		END

		IF (
				(NOT EXISTS
					(
						SELECT	1
						FROM	SJob.Activities a
						JOIN	SJob.ActivityStatus ast ON (ast.ID = a.ActivityStatusID)
						WHERE	(ast.IsCompleteStatus = 1)
							AND	(a.Guid = @Guid)
					)
				)
			)
		BEGIN
			;THROW 60000, N'The Activity must be complete before it can be invoiced.', 1
		END

		-- Get the current user.
		SELECT	@CreatedByUserGuid = SCore.GetCurrentUserGuid()

		-- Get the details to create the invoice.
		SELECT	@JobGuid = j.Guid,
