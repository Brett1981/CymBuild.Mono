    TargetPayloadHash = HASHBYTES(''SHA2_256'', CONVERT(VARBINARY(MAX), tgt.TargetPayloadJson)),
    DifferenceType = CASE
        WHEN HASHBYTES(''SHA2_256'', CONVERT(VARBINARY(MAX), sr.SourcePayloadJson))
