       AND targetIcon.RowStatus NOT IN (0,254)
    WHERE sr.RunGuid = @RunGuid
      AND sr.RowStatus NOT IN (0,254)
      AND sr.DifferenceType = N''Insert''
      AND tr.SchemaName = N''SUserInterface''
      AND tr.TableName = N''Icons''
      AND targetIcon.ID IS NOT NULL
)
UPDATE sr
SET
    TargetPayloadJson = tgt.TargetPayloadJson,
    TargetPayloadHash = HASHBYTES(''SHA2_256'', CONVERT(VARBINARY(MAX), tgt.TargetPayloadJson)),
    DifferenceType = CASE
        WHEN HASHBYTES(''SHA2_256'', CONVERT(VARBINARY(MAX), sr.SourcePayloadJson))
           = HASHBYTES(''SHA2_256'', CONVERT(VARBINARY(MAX), tgt.TargetPayloadJson)) THEN N''NoChange''
        ELSE N''Update''
    END
FROM SMigration.Metadata_StagedRows AS sr
INNER JOIN IconsToNaturalise AS n
    ON n.StagedRowID = sr.ID
OUTER APPLY
(
    SELECT
        (
            SELECT ' + @IconsColumnList + N'
            FROM SUserInterface.Icons AS ij
            WHERE ij.ID = n.TargetIconID
            FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
        ) AS TargetPayloadJson
) AS tgt
WHERE tgt.TargetPayloadJson IS NOT NULL;';

        EXEC sys.sp_executesql
            @Sql,
            N'@RunGuid UNIQUEIDENTIFIER',
            @RunGuid = @RunGuid;
    END;

    /* =========================================================
       2. Normalise false updates caused by environment-specific IDs.
          CYB-564: a foreign key column is no longer simply dropped from the comparison -
          that hid every genuine re-point (e.g. an EntityQueryParameters row re-mapped to a
          different EntityProperty staged as NoChange and was never applied). A declared,
          single-column FK to another enabled registered table is compared by the Guid each
          side's ID resolves to: on the source side the same Guid Apply will write (manual
          Identity Map override, then natural-key match, then the source row's own Guid - the
          #MetadataSourceGuidLookup order in MetadataApply_Run), on the target side the
          referenced target row's own Guid. When either side cannot be resolved the column
          falls back to the previous behaviour (ignored if it is in the legacy ID list, else
          compared as-is); two identical sentinel values (<= 0, e.g. -1) always compare equal.
          This also absorbs the per-table rules MetadataStage_NormaliseEnvironmentOnlyUpdates
          used to apply (Guid on naturalised rows, EntityQueries.Statement whitespace), which
          compared raw FK IDs and would otherwise undo the resolution above.
          Raw payloads remain available for audit.
       ========================================================= */

    DECLARE
        @NormaliseTargetDatabaseName SYSNAME,
        @RefRegistryGuid UNIQUEIDENTIFIER,
        @RefSchemaName SYSNAME,
        @RefTableName SYSNAME,
        @RefGuidColumnName SYSNAME,
        @RefPrimaryKeyColumnName SYSNAME;

    SELECT
        @NormaliseTargetDatabaseName = r.TargetDatabaseName
    FROM SMigration.Metadata_Run AS r
    WHERE r.Guid = @RunGuid
      AND r.RowStatus NOT IN (0,254);

    -- The ID columns the previous version ignored outright, spelled exactly as before. They are
    -- now only the fallback for a column that cannot be resolved by Guid (see header).
    DECLARE @LegacyIgnoredKeys TABLE
    (
        KeyName NVARCHAR(128) COLLATE DATABASE_DEFAULT NOT NULL
    );

    INSERT INTO @LegacyIgnoredKeys (KeyName)
    VALUES
        (N'EntityTypeID'), (N'EntityTypeId'),
        (N'EntityHoBTID'), (N'EntityHoBTId'), (N'EntityHobtID'), (N'EntityHobtId'),
        (N'LanguageLabelID'), (N'LanguageLabelId'),
        (N'LanguageID'), (N'LanguageId'),
        (N'EntityDataTypeID'), (N'EntityDataTypeId'),
        (N'EntityPropertyGroupID'), (N'EntityPropertyGroupId'),
        (N'DropDownListDefinitionID'), (N'DropDownListDefinitionId'),
        (N'EntityQueryID'), (N'EntityQueryId'),
        (N'MappedEntityPropertyID'), (N'MappedEntityPropertyId'),
        (N'GridDefinitionID'), (N'GridDefinitionId'),
        (N'GridViewDefinitionID'), (N'GridViewDefinitionId'),
        (N'MetricTypeID'), (N'MetricTypeId'),
        (N'DrawerIconID'), (N'DrawerIconId'),
        (N'GridViewTypeID'), (N'GridViewTypeId'),
        (N'IconID'), (N'IconId'),
        (N'PropertyGroupLayoutID'), (N'PropertyGroupLayoutId');

    IF OBJECT_ID(N'tempdb..#MetadataFkColumns') IS NOT NULL
        DROP TABLE #MetadataFkColumns;

    CREATE TABLE #MetadataFkColumns
    (
        ChildRegistryGuid UNIQUEIDENTIFIER NOT NULL,
        ColumnName NVARCHAR(128) COLLATE DATABASE_DEFAULT NOT NULL,
        RefRegistryGuid UNIQUEIDENTIFIER NOT NULL,
        RefGuidColumnName SYSNAME NOT NULL,
        CONSTRAINT PK_MetadataFkColumns PRIMARY KEY CLUSTERED (ChildRegistryGuid, ColumnName)
    );

    ;WITH DeclaredForeignKeys AS
    (
        SELECT
            childTr.Guid AS ChildRegistryGuid,
            pc.name AS ColumnName,
            refTr.Guid AS RefRegistryGuid,
            refTr.GuidColumnName AS RefGuidColumnName,
            COUNT(1) OVER (PARTITION BY childTr.Guid, pc.name) AS ForeignKeysOnColumn
        FROM SMigration.Metadata_TableRegistry AS childTr
        INNER JOIN sys.foreign_key_columns AS fkc
            ON fkc.parent_object_id = OBJECT_ID(QUOTENAME(childTr.SchemaName) + N'.' + QUOTENAME(childTr.TableName))
        INNER JOIN sys.columns AS pc
            ON pc.object_id = fkc.parent_object_id
           AND pc.column_id = fkc.parent_column_id
        INNER JOIN sys.tables AS rt
            ON rt.object_id = fkc.referenced_object_id
        INNER JOIN sys.schemas AS rs
            ON rs.schema_id = rt.schema_id
        INNER JOIN sys.columns AS rc
            ON rc.object_id = fkc.referenced_object_id
           AND rc.column_id = fkc.referenced_column_id
        INNER JOIN SMigration.Metadata_TableRegistry AS refTr
            ON refTr.SchemaName = rs.name
           AND refTr.TableName = rt.name
           AND refTr.RowStatus NOT IN (0,254)
           AND refTr.IsEnabled = 1
        WHERE childTr.RowStatus NOT IN (0,254)
          AND childTr.IsEnabled = 1
          AND pc.name <> N'RowStatus'
          AND rc.name = refTr.PrimaryKeyColumnName
          AND NOT EXISTS
          (
              SELECT 1
              FROM sys.foreign_key_columns AS otherColumn
              WHERE otherColumn.constraint_object_id = fkc.constraint_object_id
                AND otherColumn.constraint_column_id <> fkc.constraint_column_id
          )
    )
    INSERT INTO #MetadataFkColumns
    (
        ChildRegistryGuid,
        ColumnName,
        RefRegistryGuid,
        RefGuidColumnName
    )
    SELECT
        dfk.ChildRegistryGuid,
        dfk.ColumnName,
        dfk.RefRegistryGuid,
        dfk.RefGuidColumnName
    FROM DeclaredForeignKeys AS dfk
    WHERE dfk.ForeignKeysOnColumn = 1;

    IF OBJECT_ID(N'tempdb..#MetadataTargetIdGuid') IS NOT NULL
        DROP TABLE #MetadataTargetIdGuid;

    CREATE TABLE #MetadataTargetIdGuid
    (
        RefRegistryGuid UNIQUEIDENTIFIER NOT NULL,
        ID BIGINT NOT NULL,
        RowGuid UNIQUEIDENTIFIER NOT NULL,
        CONSTRAINT PK_MetadataTargetIdGuid PRIMARY KEY CLUSTERED (RefRegistryGuid, ID)
    );

    -- This procedure runs in the target database (both staging paths call it there), so the
    -- referenced tables are read directly.
    DECLARE referenced_table_cursor CURSOR LOCAL FAST_FORWARD FOR
        SELECT DISTINCT
            refTr.Guid,
            refTr.SchemaName,
            refTr.TableName,
            refTr.GuidColumnName,
            refTr.PrimaryKeyColumnName
        FROM #MetadataFkColumns AS fk
        INNER JOIN SMigration.Metadata_TableRegistry AS refTr
            ON refTr.Guid = fk.RefRegistryGuid
        WHERE OBJECT_ID(QUOTENAME(refTr.SchemaName) + N'.' + QUOTENAME(refTr.TableName)) IS NOT NULL;

    OPEN referenced_table_cursor;

    FETCH NEXT FROM referenced_table_cursor
    INTO @RefRegistryGuid, @RefSchemaName, @RefTableName, @RefGuidColumnName, @RefPrimaryKeyColumnName;

    WHILE @@FETCH_STATUS = 0
    BEGIN
        SET @Sql = N'
INSERT INTO #MetadataTargetIdGuid
(
    RefRegistryGuid,
    ID,
    RowGuid
)
SELECT
    @RefRegistryGuid,
    TRY_CONVERT(BIGINT, t.' + QUOTENAME(@RefPrimaryKeyColumnName) + N'),
    CONVERT(UNIQUEIDENTIFIER, t.' + QUOTENAME(@RefGuidColumnName) + N')
FROM ' + QUOTENAME(@RefSchemaName) + N'.' + QUOTENAME(@RefTableName) + N' AS t
WHERE TRY_CONVERT(BIGINT, t.' + QUOTENAME(@RefPrimaryKeyColumnName) + N') IS NOT NULL
  AND t.' + QUOTENAME(@RefGuidColumnName) + N' IS NOT NULL;';

        EXEC sys.sp_executesql
            @Sql,
            N'@RefRegistryGuid UNIQUEIDENTIFIER',
            @RefRegistryGuid = @RefRegistryGuid;

        FETCH NEXT FROM referenced_table_cursor
        INTO @RefRegistryGuid, @RefSchemaName, @RefTableName, @RefGuidColumnName, @RefPrimaryKeyColumnName;
    END;

    CLOSE referenced_table_cursor;
    DEALLOCATE referenced_table_cursor;

    IF OBJECT_ID(N'tempdb..#MetadataSourceIdGuid') IS NOT NULL
        DROP TABLE #MetadataSourceIdGuid;

    CREATE TABLE #MetadataSourceIdGuid
    (
        RefRegistryGuid UNIQUEIDENTIFIER NOT NULL,
        SourceRowId BIGINT NOT NULL,
        ResolvedGuid UNIQUEIDENTIFIER NOT NULL,
        CONSTRAINT PK_MetadataSourceIdGuid PRIMARY KEY CLUSTERED (RefRegistryGuid, SourceRowId)
    );

    INSERT INTO #MetadataSourceIdGuid
    (
        RefRegistryGuid,
        SourceRowId,
        ResolvedGuid
    )
    SELECT
        sr.RegistryGuid,
        sr.SourceRowId,
        COALESCE
        (
            ov.TargetRowGuid,
            TRY_CONVERT(UNIQUEIDENTIFIER, JSON_VALUE(sr.TargetPayloadJson, N'$.' + tr.GuidColumnName)),
            sr.SourceRowGuid
        )
    FROM SMigration.Metadata_StagedRows AS sr
    INNER JOIN SMigration.Metadata_TableRegistry AS tr
        ON tr.Guid = sr.RegistryGuid
       AND tr.RowStatus NOT IN (0,254)
    LEFT JOIN SMigration.Metadata_IdentityMapOverrides AS ov
        ON ov.DatabaseName = @NormaliseTargetDatabaseName
       AND ov.RegistryGuid = sr.RegistryGuid
       AND ov.SourceRowGuid = sr.SourceRowGuid
       AND ov.RowStatus NOT IN (0,254)
    WHERE sr.RunGuid = @RunGuid
      AND sr.RowStatus NOT IN (0,254)
      AND sr.SourceRowId IS NOT NULL
      AND sr.SourceRowGuid IS NOT NULL
      AND EXISTS
      (
          SELECT 1
          FROM #MetadataFkColumns AS fk
          WHERE fk.RefRegistryGuid = sr.RegistryGuid
      );

    IF OBJECT_ID(N'tempdb..#MetadataRowsWithRealDifference') IS NOT NULL
        DROP TABLE #MetadataRowsWithRealDifference;

    CREATE TABLE #MetadataRowsWithRealDifference
    (
        StagedRowID BIGINT NOT NULL PRIMARY KEY
    );

    ;WITH Pairs AS
    (
        SELECT
            sr.ID AS StagedRowID,
            sr.RegistryGuid,
            tr.SchemaName,
            tr.TableName,
            kv.KeyName,
            kv.SourceValue,
            kv.TargetValue,
            -- TRY_CONVERT(BIGINT, ...) on an nvarchar(max) value over 8000 bytes (e.g. a long
            -- EntityQueries.Statement) raises 8152 instead of returning NULL. No ID is longer
            -- than 20 characters, so only short values are converted; CONVERT to NVARCHAR(20)
            -- truncates silently, which keeps this safe even if evaluated before the LEN guard.
            TRY_CONVERT(BIGINT, CASE WHEN LEN(kv.SourceValue) <= 20 THEN CONVERT(NVARCHAR(20), kv.SourceValue) END) AS SourceIdValue,
            TRY_CONVERT(BIGINT, CASE WHEN LEN(kv.TargetValue) <= 20 THEN CONVERT(NVARCHAR(20), kv.TargetValue) END) AS TargetIdValue
        FROM SMigration.Metadata_StagedRows AS sr
        INNER JOIN SMigration.Metadata_TableRegistry AS tr
            ON tr.Guid = sr.RegistryGuid
           AND tr.RowStatus NOT IN (0,254)
        CROSS APPLY
        (
            SELECT
                COALESCE(src.[key], tgt.[key]) COLLATE DATABASE_DEFAULT AS KeyName,
                src.[value] AS SourceValue,
                tgt.[value] AS TargetValue
            FROM OPENJSON(sr.SourcePayloadJson) AS src
            FULL OUTER JOIN OPENJSON(sr.TargetPayloadJson) AS tgt
                ON tgt.[key] COLLATE DATABASE_DEFAULT = src.[key] COLLATE DATABASE_DEFAULT
        ) AS kv
        WHERE sr.RunGuid = @RunGuid
          AND sr.RowStatus NOT IN (0,254)
          AND sr.DifferenceType = N'Update'
          AND sr.TargetPayloadJson IS NOT NULL
    ),
    Classified AS
    (
        SELECT
            p.StagedRowID,
            CASE
                WHEN p.KeyName = N'ID' THEN 0
                -- A row naturalised onto a different-Guid target row (step 1) legitimately
                -- differs by Guid on these tables.
                WHEN p.KeyName = N'Guid'
                     AND
                     (
                         (p.SchemaName = N'SCore' AND p.TableName IN (N'EntityProperties', N'EntityQueries'))
                         OR (p.SchemaName = N'SUserInterface' AND p.TableName = N'GridViewColumnDefinitions')
                     ) THEN 0
                WHEN p.KeyName = N'Statement' AND p.SchemaName = N'SCore' AND p.TableName = N'EntityProperties' THEN 0
                WHEN p.KeyName = N'Statement' AND p.SchemaName = N'SCore' AND p.TableName = N'EntityQueries' THEN
                    CASE
                        WHEN LOWER(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(ISNULL(p.SourceValue, N''), CHAR(13), N''), CHAR(10), N''), CHAR(9), N''), NCHAR(160), N''), N' ', N''), N'"', N''))
                           = LOWER(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(ISNULL(p.TargetValue, N''), CHAR(13), N''), CHAR(10), N''), CHAR(9), N''), NCHAR(160), N''), N' ', N''), N'"', N'')) THEN 0
                        ELSE 1
                    END
                WHEN fk.ColumnName IS NOT NULL
                     AND CONVERT(VARBINARY(MAX), p.SourceValue) = CONVERT(VARBINARY(MAX), p.TargetValue)
                     AND p.SourceIdValue <= 0 THEN 0
                WHEN fk.ColumnName IS NOT NULL
                     AND srcRef.ResolvedGuid IS NOT NULL
                     AND tgtRef.RowGuid IS NOT NULL THEN
                    CASE WHEN srcRef.ResolvedGuid = tgtRef.RowGuid THEN 0 ELSE 1 END
                WHEN legacy.KeyName IS NOT NULL THEN 0
                WHEN p.SourceValue IS NULL AND p.TargetValue IS NULL THEN 0
                WHEN CONVERT(VARBINARY(MAX), p.SourceValue) = CONVERT(VARBINARY(MAX), p.TargetValue) THEN 0
                ELSE 1
            END AS IsDifferent
        FROM Pairs AS p
        LEFT JOIN #MetadataFkColumns AS fk
            ON fk.ChildRegistryGuid = p.RegistryGuid
           AND fk.ColumnName = p.KeyName
        LEFT JOIN #MetadataSourceIdGuid AS srcRef
            ON srcRef.RefRegistryGuid = fk.RefRegistryGuid
           AND srcRef.SourceRowId = p.SourceIdValue
        LEFT JOIN #MetadataTargetIdGuid AS tgtRef
            ON tgtRef.RefRegistryGuid = fk.RefRegistryGuid
           AND tgtRef.ID = p.TargetIdValue
        OUTER APPLY
        (
            SELECT TOP (1) lk.KeyName
            FROM @LegacyIgnoredKeys AS lk
            WHERE lk.KeyName = p.KeyName
        ) AS legacy
    )
    INSERT INTO #MetadataRowsWithRealDifference
    (
        StagedRowID
    )
    SELECT DISTINCT
        c.StagedRowID
    FROM Classified AS c
    WHERE c.IsDifferent = 1;

    UPDATE sr
    SET DifferenceType = N'NoChange'
    FROM SMigration.Metadata_StagedRows AS sr
    WHERE sr.RunGuid = @RunGuid
      AND sr.RowStatus NOT IN (0,254)
      AND sr.DifferenceType = N'Update'
      AND sr.TargetPayloadJson IS NOT NULL
      AND NOT EXISTS
      (
          SELECT 1
          FROM #MetadataRowsWithRealDifference AS diff
          WHERE diff.StagedRowID = sr.ID
      );

    /* =========================================================
       3. Refresh run summary after normalisation.
       ========================================================= */

    UPDATE SMigration.Metadata_Run
    SET SummaryJson =
    (
        SELECT
            CONCAT
            (
                N'{"insertCount":',
                CONVERT(NVARCHAR(30), ISNULL(SUM(CASE WHEN sr.DifferenceType = N'Insert' THEN 1 ELSE 0 END), 0)),
                N',"updateCount":',
                CONVERT(NVARCHAR(30), ISNULL(SUM(CASE WHEN sr.DifferenceType = N'Update' THEN 1 ELSE 0 END), 0)),
                N',"noChangeCount":',
                CONVERT(NVARCHAR(30), ISNULL(SUM(CASE WHEN sr.DifferenceType = N'NoChange' THEN 1 ELSE 0 END), 0)),
                N',"totalCount":',
                CONVERT(NVARCHAR(30), COUNT_BIG(1)),
                N'}'
            )
        FROM SMigration.Metadata_StagedRows AS sr
        WHERE sr.RunGuid = @RunGuid
          AND sr.RowStatus NOT IN (0,254)
    )
    WHERE Guid = @RunGuid
      AND RowStatus NOT IN (0,254);
END;
