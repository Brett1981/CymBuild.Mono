        ON targetHobt.Guid = srcHobt.SourceRowGuid
       AND targetHobt.RowStatus NOT IN (0,254)
    LEFT JOIN SCore.EntityProperties AS targetEp
        ON targetEp.EntityHoBTID = targetHobt.ID
