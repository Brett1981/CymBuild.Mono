/*
    CYB-576: create a Quote for an Enquiry Service from a Quote Template.

    The Enquiry Service supplies who/where, exactly as SSop.EnquiryCreateQuotes does: org unit
    (from the service's job type), job type, stages, client/agent/project/property, contracts,
    external reference and NDA flag. The template supplies the content: overview, fee cap and
    quote items. The template's contract is used only when the enquiry has none.

    Quote sections are no longer created (the Enquiry -> Quote path has never created them and
    current quote items carry their own stage). Each template item becomes a quote item
    provided at its template section's RIBA stage, with the section's invoicing schedule; the
    section's meetings and site visits go on the section's first item so totals are kept.

    All rows are created through the normal upserts (SCore.DataObjects included) in one
    transaction: an invalid template item (for example a product not valid for the quote's job
    type) creates nothing.
*/
CREATE OR ALTER PROCEDURE [SSop].[QuoteTemplatesCreateQuote]
	(
		@TemplateGuid UNIQUEIDENTIFIER,
		@EnquiryServiceGuid UNIQUEIDENTIFIER,
		@QuoteGuid UNIQUEIDENTIFIER,
		@UserGuid UNIQUEIDENTIFIER
	)
AS
BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT ON;

	DECLARE @EmptyGuid UNIQUEIDENTIFIER = '00000000-0000-0000-0000-000000000000';

	IF (ISNULL(@QuoteGuid, @EmptyGuid) = @EmptyGuid)
		THROW 60000, N'QuoteTemplatesCreateQuote: a Quote Guid is required.', 1;

	IF (EXISTS (SELECT 1 FROM SSop.Quotes WHERE Guid = @QuoteGuid))
		THROW 60000, N'QuoteTemplatesCreateQuote: a Quote with this Guid already exists.', 1;

	DECLARE @TemplateId INT,
			@TemplateOverview NVARCHAR(MAX),
			@TemplateFeeCap DECIMAL(19, 2),
			@TemplateContractGuid UNIQUEIDENTIFIER;

	SELECT	@TemplateId = qt.ID,
			@TemplateOverview = qt.Overview,
			@TemplateFeeCap = qt.FeeCap,
			@TemplateContractGuid = c.Guid
	FROM	SSop.QuoteTemplates AS qt
	LEFT JOIN SSop.Contracts AS c ON (c.ID = qt.ContractId)
	WHERE	(qt.Guid = @TemplateGuid)
		AND	(qt.ID > 0)
		AND	(qt.RowStatus NOT IN (0, 254));

	IF (@TemplateId IS NULL)
		THROW 60000, N'QuoteTemplatesCreateQuote: the Quote Template could not be found.', 1;

	IF (NOT EXISTS (SELECT 1 FROM SCore.Identities WHERE Guid = @UserGuid AND ID > 0 AND RowStatus NOT IN (0, 254)))
		THROW 60000, N'QuoteTemplatesCreateQuote: the quoting user could not be found.', 1;

	DECLARE @EnquiryServiceId INT,
			@OrganisationalUnitGuid UNIQUEIDENTIFIER,
			@JobTypeGuid UNIQUEIDENTIFIER,
			@DescriptionOfWorks NVARCHAR(4000),
			@ExternalReference NVARCHAR(50),
			@CurrentStageGuid UNIQUEIDENTIFIER,
			@AppointmentStageGuid UNIQUEIDENTIFIER,
			@IsSubjectToNDA BIT,
			@PropertyGuid UNIQUEIDENTIFIER,
			@ClientAccountGuid UNIQUEIDENTIFIER,
			@ClientAddressGuid UNIQUEIDENTIFIER,
			@ClientContactGuid UNIQUEIDENTIFIER,
			@AgentAccountGuid UNIQUEIDENTIFIER,
			@AgentAddressGuid UNIQUEIDENTIFIER,
			@AgentContactGuid UNIQUEIDENTIFIER,
			@ProjectGuid UNIQUEIDENTIFIER,
			@ContractGuid UNIQUEIDENTIFIER,
			@AgentContractGuid UNIQUEIDENTIFIER;

	SELECT	@EnquiryServiceId = es.ID,
			@OrganisationalUnitGuid = ou.Guid,
			@JobTypeGuid = jt.Guid,
			@DescriptionOfWorks = LEFT(jt.Name + N' -- ' + e.DescriptionOfWorks, 4000),
			@ExternalReference = e.ExternalReference,
			@CurrentStageGuid = ISNULL(cs.Guid, @EmptyGuid),
			@AppointmentStageGuid = ISNULL(aps.Guid, @EmptyGuid),
			@IsSubjectToNDA = e.IsSubjectToNDA,
			@PropertyGuid = ISNULL(uprn.Guid, @EmptyGuid),
			@ClientAccountGuid = ISNULL(ca.Guid, @EmptyGuid),
			@ClientAddressGuid = ISNULL(cadd.Guid, @EmptyGuid),
			@ClientContactGuid = ISNULL(ccon.Guid, @EmptyGuid),
			@AgentAccountGuid = ISNULL(aa.Guid, @EmptyGuid),
			@AgentAddressGuid = ISNULL(aadd.Guid, @EmptyGuid),
			@AgentContactGuid = ISNULL(acon.Guid, @EmptyGuid),
			@ProjectGuid = ISNULL(p.Guid, @EmptyGuid),
			@ContractGuid = ISNULL(NULLIF(ec.Guid, @EmptyGuid), ISNULL(@TemplateContractGuid, @EmptyGuid)),
			@AgentContractGuid = ISNULL(eac.Guid, @EmptyGuid)
	FROM	SSop.EnquiryServices AS es
	JOIN	SSop.Enquiries AS e ON (e.ID = es.EnquiryId)
	JOIN	SJob.JobTypes AS jt ON (jt.ID = es.JobTypeId)
	JOIN	SCore.OrganisationalUnits AS ou ON (ou.ID = jt.OrganisationalUnitID)
	LEFT JOIN SJob.RibaStages AS cs ON (cs.ID = e.CurrentProjectRibaStageID)
	LEFT JOIN SJob.RibaStages AS aps ON (aps.ID = es.StartRibaStageId)
	LEFT JOIN SJob.Assets AS uprn ON (uprn.ID = e.PropertyId)
	LEFT JOIN SCrm.Accounts AS ca ON (ca.ID = e.ClientAccountId)
	LEFT JOIN SCrm.AccountAddresses AS cadd ON (cadd.ID = e.ClientAddressId)
	LEFT JOIN SCrm.AccountContacts AS ccon ON (ccon.ID = e.ClientAccountContactId)
	LEFT JOIN SCrm.Accounts AS aa ON (aa.ID = e.AgentAccountId)
	LEFT JOIN SCrm.AccountAddresses AS aadd ON (aadd.ID = e.AgentAddressId)
	LEFT JOIN SCrm.AccountContacts AS acon ON (acon.ID = e.AgentAccountContactId)
	LEFT JOIN SSop.Projects AS p ON (p.ID = e.ProjectId)
	LEFT JOIN SSop.Contracts AS ec ON (ec.ID = e.ContractID)
	LEFT JOIN SSop.Contracts AS eac ON (eac.ID = e.AgentContractID)
	WHERE	(es.Guid = @EnquiryServiceGuid)
		AND	(es.ID > 0)
		AND	(es.RowStatus NOT IN (0, 254))
		AND	(e.RowStatus NOT IN (0, 254))
		AND	(jt.ID > 0);

	IF (@EnquiryServiceId IS NULL)
		THROW 60000, N'QuoteTemplatesCreateQuote: the Enquiry Service could not be found, or has no Job Type.', 1;

	-- Same rule as SSop.EnquiryCreateQuotes: one live quote per Enquiry Service.
	IF (EXISTS (SELECT 1 FROM SSop.Quotes WHERE EnquiryServiceID = @EnquiryServiceId AND RowStatus NOT IN (0, 254)))
		THROW 60000, N'QuoteTemplatesCreateQuote: the Enquiry Service already has a quote.', 1;

	DECLARE @MarketGuid UNIQUEIDENTIFIER = @EmptyGuid,
			@DataClassificationGuid UNIQUEIDENTIFIER = '31E24091-52B4-480E-9A85-7052F614567A',
			@SecurityClassificationGuid UNIQUEIDENTIFIER = 'B4EF7A4D-454B-4C4B-AF3D-5996312FD038',
			@QuoteDate DATE = GETUTCDATE(),
			@ExpiryDate DATE = DATEADD(MONTH, 6, GETUTCDATE());

	SELECT @MarketGuid = Guid FROM SCore.Markets WHERE Name LIKE N'%UK%';

	-- Template items in a stable order, with the values each quote item needs.
	DECLARE @Items TABLE
	(
		RowNumber INT NOT NULL PRIMARY KEY,
		ItemGuid UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
		ProductGuid UNIQUEIDENTIFIER NOT NULL,
		Details NVARCHAR(2000) NOT NULL,
		Net DECIMAL(19, 2) NOT NULL,
		VatRate DECIMAL(9, 2) NOT NULL,
		DoNotConsolidateJob BIT NOT NULL,
		Quantity DECIMAL(9, 2) NOT NULL,
		ProvidedAtStageGuid UNIQUEIDENTIFIER NOT NULL,
		InvoicingScheduleGuid UNIQUEIDENTIFIER NOT NULL,
		NumberOfMeetings INT NOT NULL,
		NumberOfSiteVisits INT NOT NULL
	);

	INSERT	@Items
		(RowNumber, ProductGuid, Details, Net, VatRate, DoNotConsolidateJob, Quantity,
		 ProvidedAtStageGuid, InvoicingScheduleGuid, NumberOfMeetings, NumberOfSiteVisits)
	SELECT	ROW_NUMBER() OVER (ORDER BY qts.SortOrder, qts.ID, qti.SortOrder, qti.ID),
			pr.Guid,
			qti.Details,
			qti.Net,
			qti.VatRate,
			qti.DoNotConsolidateJob,
			qti.Quantity,
			ISNULL(rs.Guid, @EmptyGuid),
			ISNULL(sch.Guid, @EmptyGuid),
			IIF(ROW_NUMBER() OVER (PARTITION BY qts.ID ORDER BY qti.SortOrder, qti.ID) = 1, qts.NumberOfMeetings, 0),
			IIF(ROW_NUMBER() OVER (PARTITION BY qts.ID ORDER BY qti.SortOrder, qti.ID) = 1, qts.NumberOfSiteVisits, 0)
	FROM	SSop.QuoteTemplateSections AS qts
	JOIN	SSop.QuoteTemplateItems AS qti ON (qti.QuoteTemplateSectionId = qts.ID)
	JOIN	SProd.Products AS pr ON (pr.ID = qti.ProductId)
	LEFT JOIN SJob.RibaStages AS rs ON (rs.ID = qts.RibaStageId)
	LEFT JOIN SFin.InvoiceSchedules AS sch ON (sch.ID = qts.InvoiceScheduleId)
	WHERE	(qts.QuoteTemplateId = @TemplateId)
		AND	(qts.ID > 0)
		AND	(qts.RowStatus NOT IN (0, 254))
		AND	(qti.ID > 0)
		AND	(qti.RowStatus NOT IN (0, 254));

	IF (NOT EXISTS (SELECT 1 FROM @Items))
		THROW 60000, N'QuoteTemplatesCreateQuote: the Quote Template has no items.', 1;

	DECLARE @OwnTransaction BIT = 0;

	BEGIN TRY
		IF (@@TRANCOUNT = 0)
		BEGIN
			BEGIN TRANSACTION;
			SET @OwnTransaction = 1;
		END;

		EXEC SSop.QuotesUpsert @OrganisationalUnitGuid = @OrganisationalUnitGuid,
							   @QuotingUserGuid = @UserGuid,
							   @ContractGuid = @ContractGuid,
							   @Date = @QuoteDate,
							   @Overview = @TemplateOverview,
							   @ExpiryDate = @ExpiryDate,
							   @DateSent = NULL,
							   @DateAccepted = NULL,
							   @DateRejected = NULL,
							   @RejectionReason = N'',
							   @FeeCap = @TemplateFeeCap,
							   @IsFinal = 0,
							   @ExternalReference = @ExternalReference,
							   @QuotingConsultantGuid = @UserGuid,
							   @AppointmentFromRibaStageGuid = @AppointmentStageGuid,
							   @CurrentStageGuid = @CurrentStageGuid,
							   @DeadDate = NULL,
							   @EnquiryServiceGuid = @EnquiryServiceGuid,
							   @ProjectGuid = @ProjectGuid,
							   @Guid = @QuoteGuid,
							   @JobType = @JobTypeGuid,
							   @DeclinedToQuoteReason = N'',
							   @DescriptionOfWorks = @DescriptionOfWorks,
							   @ExclusionsAndLimitations = N'',
							   @AgentContractGuid = @AgentContractGuid,
							   @IsSubjectToNDA = @IsSubjectToNDA,
							   @SectorGuid = @EmptyGuid,
							   @MarketGuid = @MarketGuid,
							   @DataClassificationGuid = @DataClassificationGuid,
							   @SecurityClassificationGuid = @SecurityClassificationGuid,
							   @JobTypeGuid = @JobTypeGuid,
							   @PropertyGuid = @PropertyGuid,
							   @ClientAccountGuid = @ClientAccountGuid,
							   @ClientAddressGuid = @ClientAddressGuid,
							   @ClientContactGuid = @ClientContactGuid,
							   @AgentAccountGuid = @AgentAccountGuid,
							   @AgentAddressGuid = @AgentAddressGuid,
							   @AgentContactGuid = @AgentContactGuid;

		DECLARE @RowNumber INT = 1,
				@ItemCount INT = (SELECT COUNT(*) FROM @Items),
				@ItemGuid UNIQUEIDENTIFIER,
				@ProductGuid UNIQUEIDENTIFIER,
				@Details NVARCHAR(2000),
				@Net DECIMAL(19, 2),
				@VatRate DECIMAL(9, 2),
				@DoNotConsolidateJob BIT,
				@Quantity DECIMAL(9, 2),
				@ProvidedAtStageGuid UNIQUEIDENTIFIER,
				@InvoicingScheduleGuid UNIQUEIDENTIFIER,
				@NumberOfMeetings INT,
				@NumberOfSiteVisits INT;

		WHILE (@RowNumber <= @ItemCount)
		BEGIN
			SELECT	@ItemGuid = i.ItemGuid,
					@ProductGuid = i.ProductGuid,
					@Details = i.Details,
					@Net = i.Net,
					@VatRate = i.VatRate,
					@DoNotConsolidateJob = i.DoNotConsolidateJob,
					@Quantity = i.Quantity,
					@ProvidedAtStageGuid = i.ProvidedAtStageGuid,
					@InvoicingScheduleGuid = i.InvoicingScheduleGuid,
					@NumberOfMeetings = i.NumberOfMeetings,
					@NumberOfSiteVisits = i.NumberOfSiteVisits
			FROM	@Items AS i
			WHERE	(i.RowNumber = @RowNumber);

			EXEC SSop.QuoteItemsUpsert @QuoteGuid = @QuoteGuid,
									   @ProductGuid = @ProductGuid,
									   @Details = @Details,
									   @Net = @Net,
									   @VatRate = @VatRate,
									   @DoNotConsolidateJob = @DoNotConsolidateJob,
									   @SortOrder = @RowNumber,
									   @Quantity = @Quantity,
									   @ProvidedAtStageGuid = @ProvidedAtStageGuid,
									   @Guid = @ItemGuid,
									   @NumberOfSiteVisits = @NumberOfSiteVisits,
									   @NumberOfMeetings = @NumberOfMeetings,
									   @InvoicingScheduleGuid = @InvoicingScheduleGuid;

			SET @RowNumber += 1;
		END;

		IF (@OwnTransaction = 1)
			COMMIT TRANSACTION;
	END TRY
	BEGIN CATCH
		IF (@OwnTransaction = 1 AND XACT_STATE() <> 0)
			ROLLBACK TRANSACTION;

		THROW;
	END CATCH;
END;
