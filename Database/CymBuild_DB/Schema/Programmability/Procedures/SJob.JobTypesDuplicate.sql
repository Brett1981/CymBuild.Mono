CREATE OR ALTER PROCEDURE [SJob].[JobTypesDuplicate] 
								@SourceGuid UNIQUEIDENTIFIER,
								@TargetGuid UNIQUEIDENTIFIER
AS
BEGIN

	DECLARE @Name NVARCHAR(100),
			@SourceID INT,
			@ID INT,
			@UseTimeSheets BIT,
			@OrganisationalUnitGuid UNIQUEIDENTIFIER


	-- CYB-572 follow-up: the copy keeps the source's timesheet and org unit settings.
	SELECT	@Name = jt.Name + N' - Copy',
			@SourceID = jt.ID,
			@UseTimeSheets = jt.UseTimeSheets,
			@OrganisationalUnitGuid = ou.Guid
	FROM	SJob.JobTypes jt
	JOIN	SCore.OrganisationalUnits ou ON (ou.ID = jt.OrganisationalUnitID)
	WHERE	(jt.Guid = @SourceGuid)

	EXEC SJob.JobTypesUpsert @Name = @Name,			-- nvarchar(100)
							 @IsActive = 0,		-- bit
							 @UseTimeSheets = @UseTimeSheets,
							 @OrganisationalUnitGuid = @OrganisationalUnitGuid,
							 @Guid = @TargetGuid OUTPUT	-- uniqueidentifier
	
	SELECT	@ID = id 
	FROM	SJob.JobTypes
	WHERE	(Guid = @TargetGuid)

	INSERT	SJob.JobTypeMilestoneTemplates
		 (RowStatus, Guid, JobTypeID, MilestoneTypeID, Description, SortOrder)
	SELECT	1, NEWID(), @ID, MilestoneTypeID, Description, SortOrder 
	FROM	SJob.JobTypeMilestoneTemplates 
	WHERE	(JobTypeID = @SourceID)
		AND	(RowStatus NOT IN (0, 254))

	INSERT	SJob.JobTypeProjectDirectoryRoles
