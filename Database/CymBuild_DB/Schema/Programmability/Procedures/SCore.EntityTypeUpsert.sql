CREATE OR ALTER PROCEDURE [SCore].[EntityTypeUpsert]
  (
    @Name                 NVARCHAR(250),
    @RowStatus            TINYINT,
    @IsReadOnlyOffline    BIT,
    @IsRequiredSystemData BIT,
    @HasDocuments         BIT,
    @LanguageLabelGuid    UNIQUEIDENTIFIER,
    @DoNotTrackChanges    BIT,
    @IconGuid             UNIQUEIDENTIFIER,
    @IsRootEntity         BIT,
    @DetailPageUrl        NVARCHAR(250),
	@IsMetaData			  BIT,
    @Guid                 UNIQUEIDENTIFIER OUT,
	@IsDeletable		  BIT
  )
AS
  BEGIN
    SET NOCOUNT ON

    DECLARE @ProcessMessages SCore.ProcessMessages,
            @LanguageLabelID INT,
            @IconId          INT

    -- If the name isn't set, then create a validation message. 
    IF (ISNULL(@Name,
      N''
      ) = N''
      )
      BEGIN
        INSERT @ProcessMessages
              (
                Type,
                Message
              )
        VALUES
                (
                  'V',
                  N'The name for the entity type cannot be blank.'
                );
      END;

    -- The sentinel Guid must never be reused as a real LanguageLabels identity - it already
    -- exists (ID -1) - and an unresolved (NULL) Guid can't be looked up at all, so both cases
    -- need a fresh Guid before resolving/creating a dedicated label.
    IF (@LanguageLabelGuid IS NULL OR @LanguageLabelGuid = '00000000-0000-0000-0000-000000000000')
      BEGIN
        SET @LanguageLabelGuid = NEWID();
      END;

    -- If the language label isn't set, create one based on the name.
    SELECT
            @LanguageLabelID = ID
    FROM
            SCore.LanguageLabels
    WHERE
            (Guid = @LanguageLabelGuid);

    IF (@LanguageLabelID IS NULL OR @LanguageLabelID = -1)
      BEGIN
        EXECUTE SCore.LanguageLabelUpsert
          @Name = @Name,
          @Guid = @LanguageLabelGuid OUT;

        SELECT
                @LanguageLabelID = ID
        FROM
                SCore.LanguageLabels
        WHERE
                (Guid = @LanguageLabelGuid);
      END;

    -- Icons is no longer a migrated metadata table, so @IconGuid is often unresolved;
    -- fall back to the sentinel row on insert and leave the existing value alone on update.
    SELECT
            @IconId = ID
    FROM
            SUserInterface.Icons i
    WHERE
            (Guid = @IconGuid)

    DECLARE @IsInsert BIT = 0;
    EXEC SCore.UpsertDataObject
      @Guid       = @Guid,					-- uniqueidentifier
      @SchemeName = N'SCore',				-- nvarchar(255)
      @ObjectName = N'EntityTypes',				-- nvarchar(255)
      @IsInsert   = @IsInsert OUTPUT	-- bit

    IF (@IsInsert = 1)
      BEGIN
        INSERT SCore.EntityTypes
              (
                Guid,
                Name,
                RowStatus,
                IsReadOnlyOffline,
                IsRequiredSystemData,
                HasDocuments,
                LanguageLabelID,
                DoNotTrackChanges,
                IconId,
                IsRootEntity,
                DetailPageUrl,
				IsMetaData,
				IsDeletable
              )
        VALUES
                (
                  @Guid,
                  @Name,
                  @RowStatus,
                  @IsReadOnlyOffline,
                  @IsRequiredSystemData,
                  @HasDocuments,
                  @LanguageLabelID,
                  @DoNotTrackChanges,
                  ISNULL(@IconId, -1),
                  @IsRootEntity,
                  @DetailPageUrl,
				  @IsMetaData,
				  @IsDeletable
                );
      END;
    ELSE
      BEGIN
        UPDATE  SCore.EntityTypes
        SET     Name = @Name,
                RowStatus = @RowStatus,
                IsReadOnlyOffline = @IsReadOnlyOffline,
                IsRequiredSystemData = @IsRequiredSystemData,
                HasDocuments = @HasDocuments,
                LanguageLabelID = @LanguageLabelID,
                DoNotTrackChanges = @DoNotTrackChanges,
                IconId = ISNULL(@IconId, IconId),
                IsRootEntity = @IsRootEntity,
                DetailPageUrl = @DetailPageUrl,
				IsMetaData = @IsMetaData,
				IsDeletable = @IsDeletable
        WHERE
          (Guid = @Guid);
      END;


  END;
