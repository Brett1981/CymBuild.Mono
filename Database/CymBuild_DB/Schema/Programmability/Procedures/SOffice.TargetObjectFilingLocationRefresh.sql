CREATE OR ALTER PROCEDURE [SOffice].[TargetObjectFilingLocationRefresh]
	(	@RecordGuid UNIQUEIDENTIFIER	)
AS
BEGIN
	-- Recomputes FilingLocation from the current SCore.ObjectSharePointFolder row for this record.
	-- Mirrors the same subquery each entity's own Upsert proc (SJob.JobsUpsert etc.) uses, so this can
	-- be called after any write to ObjectSharePointFolder that does not go through a full entity Upsert
	-- (e.g. lazy/first-time SharePoint folder provisioning) without producing a different FilingLocation shape.
	DECLARE @FilingLocation NVARCHAR(MAX)

	SELECT	@FilingLocation =
	(
		SELECT	ss.SiteIdentifier,
				spf.FolderPath
		FROM	SCore.ObjectSharePointFolder AS spf
		JOIN	SCore.SharepointSites AS ss
			ON	ss.ID = spf.SharepointSiteId
		WHERE	spf.ObjectGuid = @RecordGuid
		FOR JSON PATH
	)

	UPDATE	SOffice.TargetObjects
	SET		FilingLocation = ISNULL(@FilingLocation, N'')
	WHERE	(Guid = @RecordGuid)
END
GO
