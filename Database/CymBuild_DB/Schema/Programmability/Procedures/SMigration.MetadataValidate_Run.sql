    SELECT
        NEWID(),
        1,
        @RunGuid,
        unselected.RegistryGuid,
        NULL,
        N'Warn',
        N'UnselectedActionableRows',
        CONCAT
        (
            unselected.SchemaName, N'.', unselected.TableName, N' has ',
            unselected.InsertCount, N' Insert and ', unselected.UpdateCount,
            N' Update row(s) staged but not selected. They will not be applied. Select or ignore them.'
