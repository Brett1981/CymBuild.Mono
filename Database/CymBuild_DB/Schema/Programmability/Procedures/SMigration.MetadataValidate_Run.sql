        Warn once per table for staged Insert/Update rows that are neither selected nor ignored.
    */
    INSERT INTO SMigration.Metadata_ValidationIssues
    (
        Guid,
        RowStatus,
        RunGuid,
        RegistryGuid,
        SourceRowGuid,
        Severity,
        IssueCode,
        IssueMessage,
        DetailsJson,
        CreatedOnUtc
