BEGIN
    SET NOCOUNT ON;

    /*
        CYB-564: superseded - intentionally does nothing.

        This procedure used to turn staged Update rows into NoChange when the only differing
        JSON properties were ID/Guid or numeric FK columns. It compared those FK columns as raw
        IDs and simply ignored them, which hid genuine re-points (for example an
        EntityQueryParameters row re-mapped to a different EntityProperty was never applied).

        Its three per-table rules (Guid on naturalised rows for EntityProperties, EntityQueries
        and GridViewColumnDefinitions; EntityProperties.Statement; whitespace-insensitive
        EntityQueries.Statement) now live in SMigration.MetadataStage_NormaliseDifferences,
        which compares FK columns by the Guid they resolve to. Running the old rules after it
        would undo that resolution.

        Both staging paths no longer call this procedure. It is kept, as a no-op, so an API
        build deployed before this schema change cannot reintroduce the old behaviour.
    */
    DECLARE @UnusedRunGuid UNIQUEIDENTIFIER = @RunGuid;
END;
