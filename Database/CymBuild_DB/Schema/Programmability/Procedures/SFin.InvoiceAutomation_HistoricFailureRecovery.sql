/*
    Historic recovery for invoice automation runs that failed with
    FK_InvoiceBatches_DataObjects.

    Safety model
    ------------
    1. @Apply defaults to 0 and returns a plan only.
    2. An apply requires an explicit date, job-number, or run-guid scope.
    3. Requests linked to TransactionDetails are never changed.
    4. A request is automatically suppressed only where mode history proves
       the job was Manual or Paused when the request was created.
    5. A request is batched only when it was eligible at creation and the job is
       still Automated and unblocked at apply time.
    6. Existing failed run details are retained. Recovery adds new audit detail
       rows and leaves the original ErrorCount unchanged.
    7. Deleted parents with active child items are repaired through the normal
       soft-delete procedures; no financial transaction rows are changed.
*/
