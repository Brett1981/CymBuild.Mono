                UPDATE ir
                SET ir.InvoiceBatchGuid = @BatchGuid
                FROM SFin.InvoiceRequests AS ir
                INNER JOIN #RequestPlan AS rp
                    ON rp.RequestId = ir.ID
                INNER JOIN SJob.Jobs AS j
                    ON j.ID = ir.JobId
                   AND j.RowStatus NOT IN (0, 254)
                LEFT JOIN SCrm.Accounts AS a
                    ON a.ID = j.FinanceAccountID
                   AND a.RowStatus NOT IN (0, 254)
                LEFT JOIN SCrm.AccountStatus AS acs
                    ON acs.ID = a.AccountStatusID
                   AND acs.RowStatus NOT IN (0, 254)
                WHERE rp.AutomationRunGuid = @RunGuid
                  AND rp.RecoveryAction = N'BATCH'
                  AND ir.RowStatus NOT IN (0, 254)
                  AND ir.InvoiceBatchGuid IS NULL
                  AND ISNULL(ir.IsAutomated, 0) = 1
                  AND j.InvoiceProcessingMode = 0
                  AND ISNULL(j.CannotBeInvoiced, 0) = 0
                  AND ISNULL(acs.IsHold, 0) = 0
                  AND NOT EXISTS
                  (
                      SELECT 1
                      FROM SFin.InvoiceRequestItems AS iri
                      INNER JOIN SFin.TransactionDetails AS td
                          ON td.InvoiceRequestItemId = iri.ID
                      WHERE iri.InvoiceRequestId = ir.ID
                  );

                DECLARE @AssignedCount INT = @@ROWCOUNT;

                UPDATE b
                SET b.CreatedCount =
                (
                    SELECT COUNT(1)
                    FROM SFin.InvoiceRequests AS ir
                    WHERE ir.RowStatus NOT IN (0, 254)
                      AND ir.InvoiceBatchGuid = @BatchGuid
                )
                FROM SFin.InvoiceBatches AS b
                WHERE b.Guid = @BatchGuid;

                IF @AssignedCount > 0
                BEGIN
                    UPDATE ar
                    SET ar.CreatedCount =
                        (
                            SELECT COUNT(1)
                            FROM SFin.InvoiceRequests AS ir
                            WHERE ir.RowStatus NOT IN (0, 254)
                              AND ir.AutomationRunGuid = @RunGuid
                              AND ISNULL(ir.IsAutomated, 0) = 1
                        )
                      , ar.InvoiceBatchGuid = @BatchGuid
                      , ar.WasBatchCreated = 1
                    FROM SFin.InvoiceAutomationRuns AS ar
                    WHERE ar.Guid = @RunGuid;

                    INSERT INTO #Applied
                    (
                          ActionType
                        , RequestGuid
                        , AutomationRunGuid
                        , InvoiceBatchGuid
                        , AppliedDateTimeUTC
                        , Message
                    )
                    SELECT
                          N'BATCHED'
                        , rp.RequestGuid
                        , rp.AutomationRunGuid
                        , @BatchGuid
                        , @NowUtc
                        , N'Request assigned to a valid historic-recovery batch; the original run error remains in the audit trail.'
                    FROM #RequestPlan AS rp
                    INNER JOIN SFin.InvoiceRequests AS ir
                        ON ir.ID = rp.RequestId
                    WHERE rp.AutomationRunGuid = @RunGuid
                      AND rp.RecoveryAction = N'BATCH'
                      AND ir.InvoiceBatchGuid = @BatchGuid
                      AND NOT EXISTS
                      (
                          SELECT 1
                          FROM #Applied AS already_applied
                          WHERE already_applied.ActionType = N'BATCHED'
                            AND already_applied.RequestGuid = rp.RequestGuid
                      );

                    DECLARE @AuditRequestGuid UNIQUEIDENTIFIER;
                    DECLARE @AuditSourceType NVARCHAR(50);
                    DECLARE @AuditSourceGuid UNIQUEIDENTIFIER;
                    DECLARE @AuditSourceIntId INT;

                    WHILE EXISTS
                    (
                        SELECT 1
                        FROM #Applied AS applied
                        WHERE applied.ActionType = N'BATCHED'
                          AND applied.AutomationRunGuid = @RunGuid
                          AND applied.AuditLogged = 0
                    )
                    BEGIN
                        SELECT TOP (1)
                              @AuditRequestGuid = applied.RequestGuid
                        FROM #Applied AS applied
                        WHERE applied.ActionType = N'BATCHED'
                          AND applied.AutomationRunGuid = @RunGuid
                          AND applied.AuditLogged = 0
                        ORDER BY applied.ActionOrder;

                        SELECT
                              @AuditSourceType = rp.SourceType
                            , @AuditSourceGuid = rp.SourceGuid
                            , @AuditSourceIntId = rp.SourceIntId
                        FROM #RequestPlan AS rp
                        WHERE rp.RequestGuid = @AuditRequestGuid;

                        IF NOT EXISTS
                        (
                            SELECT 1
                            FROM SFin.InvoiceAutomationRunDetails AS d
                            WHERE d.RowStatus NOT IN (0, 254)
                              AND d.AutomationRunGuid = @RunGuid
                              AND d.InstanceKey = CONCAT(N'HISTORIC_BATCH_RECOVERY|', CONVERT(NVARCHAR(36), @AuditRequestGuid))
                        )
                        BEGIN
                            DECLARE @DetailGuid UNIQUEIDENTIFIER = NEWID();
                            DECLARE @DetailDataObjectWasInserted BIT = 0;

                            EXEC SCore.UpsertDataObject
                                  @Guid = @DetailGuid
                                , @SchemeName = N'SFin'
                                , @ObjectName = N'InvoiceAutomationRunDetails'
                                , @IncludeDefaultSecurity = 0
                                , @IsInsert = @DetailDataObjectWasInserted OUTPUT;

                            INSERT INTO SFin.InvoiceAutomationRunDetails
                            (
                                  RowStatus
                                , Guid
                                , AutomationRunGuid
                                , InvoiceScheduleId
                                , SourceType
                                , SourceGuid
                                , SourceIntId
                                , InstanceType
                                , InstanceKey
                                , Outcome
                                , Message
                                , InvoiceRequestGuid
                                , CreatedDateTimeUTC
                                , LegacyId
                                , LegacySystemID
                            )
                            VALUES
                            (
                                  1
                                , @DetailGuid
                                , @RunGuid
                                , -1
                                , ISNULL(@AuditSourceType, N'')
                                , @AuditSourceGuid
                                , @AuditSourceIntId
                                , N'InvoiceRequest'
                                , CONCAT(N'HISTORIC_BATCH_RECOVERY|', CONVERT(NVARCHAR(36), @AuditRequestGuid))
                                , N'Recovered'
                                , CONCAT(N'Historic batch recovery assigned request to batch ', CONVERT(NVARCHAR(36), @BatchGuid), N'. Original failed-run detail retained.')
                                , @AuditRequestGuid
                                , @NowUtc
                                , NULL
                                , -1
                            );
                        END;

                        UPDATE applied
                        SET applied.AuditLogged = 1
                        FROM #Applied AS applied
                        WHERE applied.ActionType = N'BATCHED'
                          AND applied.RequestGuid = @AuditRequestGuid;
                    END;
                END;
            END;

            UPDATE rp
            SET rp.Processed = 1
            FROM #RequestPlan AS rp
            WHERE rp.AutomationRunGuid = @RunGuid
              AND rp.RecoveryAction = N'BATCH';

            COMMIT TRANSACTION;

            FETCH NEXT FROM cur_recovery_run INTO @RunGuid;
        END;

        CLOSE cur_recovery_run;
        DEALLOCATE cur_recovery_run;

        /* --------------------------------------------------------------
           B. Suppress requests proven to have been created while Manual or
              Paused. This uses the corrected soft-delete procedure.
           -------------------------------------------------------------- */
        IF @SuppressProvenManualOrPaused = 1
        BEGIN
            DECLARE @SuppressRequestId INT;
            DECLARE @SuppressRequestGuid UNIQUEIDENTIFIER;
            DECLARE @SuppressRunGuid UNIQUEIDENTIFIER;
            DECLARE @SuppressSourceType NVARCHAR(50);
            DECLARE @SuppressSourceGuid UNIQUEIDENTIFIER;
            DECLARE @SuppressSourceIntId INT;
            DECLARE @SuppressReason NVARCHAR(500);

            WHILE EXISTS
            (
                SELECT 1
                FROM #RequestPlan AS rp
                WHERE rp.RecoveryAction = N'SUPPRESS'
                  AND rp.Processed = 0
            )
            BEGIN
                SELECT TOP (1)
                      @SuppressRequestId = rp.RequestId
                    , @SuppressRequestGuid = rp.RequestGuid
                    , @SuppressRunGuid = rp.AutomationRunGuid
                    , @SuppressSourceType = rp.SourceType
                    , @SuppressSourceGuid = rp.SourceGuid
                    , @SuppressSourceIntId = rp.SourceIntId
                    , @SuppressReason = rp.RecoveryReason
                FROM #RequestPlan AS rp
                WHERE rp.RecoveryAction = N'SUPPRESS'
                  AND rp.Processed = 0
                ORDER BY rp.CreatedDateTimeUTC, rp.RequestId;

                BEGIN TRANSACTION;

                IF EXISTS
                (
                    SELECT 1
                    FROM SFin.InvoiceRequests AS ir WITH (UPDLOCK, HOLDLOCK)
                    WHERE ir.ID = @SuppressRequestId
                      AND ir.Guid = @SuppressRequestGuid
                      AND ir.RowStatus NOT IN (0, 254)
                      AND ir.InvoiceBatchGuid IS NULL
                      AND NOT EXISTS
                      (
                          SELECT 1
                          FROM SFin.InvoiceRequestItems AS iri
                          INNER JOIN SFin.TransactionDetails AS td
                              ON td.InvoiceRequestItemId = iri.ID
                          WHERE iri.InvoiceRequestId = ir.ID
                      )
                )
                BEGIN
                    EXEC SFin.InvoiceRequestsDelete
                        @Guid = @SuppressRequestGuid;

                    IF NOT EXISTS
                    (
                        SELECT 1
                        FROM SFin.InvoiceAutomationRunDetails AS d
                        WHERE d.RowStatus NOT IN (0, 254)
                          AND d.AutomationRunGuid = @SuppressRunGuid
                          AND d.InstanceKey = CONCAT(N'HISTORIC_REQUEST_SUPPRESSION|', CONVERT(NVARCHAR(36), @SuppressRequestGuid))
                    )
                    BEGIN
                        DECLARE @SuppressDetailGuid UNIQUEIDENTIFIER = NEWID();
                        DECLARE @SuppressDetailWasInserted BIT = 0;

                        EXEC SCore.UpsertDataObject
                              @Guid = @SuppressDetailGuid
                            , @SchemeName = N'SFin'
                            , @ObjectName = N'InvoiceAutomationRunDetails'
                            , @IncludeDefaultSecurity = 0
                            , @IsInsert = @SuppressDetailWasInserted OUTPUT;

                        INSERT INTO SFin.InvoiceAutomationRunDetails
                        (
                              RowStatus
                            , Guid
                            , AutomationRunGuid
                            , InvoiceScheduleId
                            , SourceType
                            , SourceGuid
                            , SourceIntId
                            , InstanceType
                            , InstanceKey
                            , Outcome
                            , Message
                            , InvoiceRequestGuid
                            , CreatedDateTimeUTC
                            , LegacyId
                            , LegacySystemID
                        )
                        VALUES
                        (
                              1
                            , @SuppressDetailGuid
                            , @SuppressRunGuid
                            , -1
                            , ISNULL(@SuppressSourceType, N'')
                            , @SuppressSourceGuid
                            , @SuppressSourceIntId
                            , N'InvoiceRequest'
                            , CONCAT(N'HISTORIC_REQUEST_SUPPRESSION|', CONVERT(NVARCHAR(36), @SuppressRequestGuid))
                            , N'Suppressed'
                            , CONCAT(N'Historic invalid request soft-deleted. ', @SuppressReason)
                            , @SuppressRequestGuid
                            , @NowUtc
                            , NULL
                            , -1
                        );
                    END;

                    UPDATE ar
                    SET ar.CreatedCount =
                        (
                            SELECT COUNT(1)
                            FROM SFin.InvoiceRequests AS ir
                            WHERE ir.RowStatus NOT IN (0, 254)
                              AND ir.AutomationRunGuid = @SuppressRunGuid
                              AND ISNULL(ir.IsAutomated, 0) = 1
                        )
                    FROM SFin.InvoiceAutomationRuns AS ar
                    WHERE ar.Guid = @SuppressRunGuid;

                    INSERT INTO #Applied
                    (
                          ActionType
                        , RequestGuid
                        , AutomationRunGuid
                        , InvoiceBatchGuid
                        , AppliedDateTimeUTC
                        , Message
                        , AuditLogged
                    )
                    VALUES
                    (
                          N'SUPPRESSED'
                        , @SuppressRequestGuid
                        , @SuppressRunGuid
                        , NULL
                        , @NowUtc
                        , @SuppressReason
                        , 1
                    );
                END
                ELSE
                BEGIN
                    INSERT INTO #Applied
                    (
                          ActionType
                        , RequestGuid
                        , AutomationRunGuid
                        , InvoiceBatchGuid
                        , AppliedDateTimeUTC
                        , Message
                        , AuditLogged
                    )
                    VALUES
                    (
                          N'SKIPPED_STATE_CHANGED'
                        , @SuppressRequestGuid
                        , @SuppressRunGuid
                        , NULL
                        , @NowUtc
                        , N'Request was not suppressed because its state changed or it became transaction-linked after planning.'
                        , 1
                    );
                END;

                UPDATE rp
                SET rp.Processed = 1
                FROM #RequestPlan AS rp
                WHERE rp.RequestId = @SuppressRequestId;

                COMMIT TRANSACTION;
            END;
        END;

        /* --------------------------------------------------------------
           C. Repair active child items beneath already-deleted parents.
           -------------------------------------------------------------- */
        IF @RepairDeletedParentItems = 1
        BEGIN
            DECLARE @OrphanRequestId INT;
            DECLARE @OrphanRequestGuid UNIQUEIDENTIFIER;
            DECLARE @OrphanRunGuid UNIQUEIDENTIFIER;
            DECLARE @OrphanItemCount INT;

            WHILE EXISTS
            (
                SELECT 1
                FROM #OrphanItemPlan AS op
                WHERE op.RecoveryAction = N'CLEAN_ORPHAN_ITEMS'
                  AND op.Processed = 0
            )
            BEGIN
                SELECT TOP (1)
                      @OrphanRequestId = op.RequestId
                    , @OrphanRequestGuid = op.RequestGuid
                    , @OrphanRunGuid = op.AutomationRunGuid
                FROM #OrphanItemPlan AS op
                WHERE op.RecoveryAction = N'CLEAN_ORPHAN_ITEMS'
                  AND op.Processed = 0
                ORDER BY op.RequestCreatedDateTimeUTC, op.RequestId;

                SELECT @OrphanItemCount = COUNT(1)
                FROM #OrphanItemPlan AS op
                WHERE op.RequestId = @OrphanRequestId
                  AND op.RecoveryAction = N'CLEAN_ORPHAN_ITEMS';

                BEGIN TRANSACTION;

                IF EXISTS
                (
                    SELECT 1
                    FROM SFin.InvoiceRequests AS ir WITH (UPDLOCK, HOLDLOCK)
                    WHERE ir.ID = @OrphanRequestId
                      AND ir.Guid = @OrphanRequestGuid
                      AND ir.RowStatus IN (0, 254)
                      AND NOT EXISTS
                      (
                          SELECT 1
                          FROM SFin.InvoiceRequestItems AS iri
                          INNER JOIN SFin.TransactionDetails AS td
                              ON td.InvoiceRequestItemId = iri.ID
                          WHERE iri.InvoiceRequestId = ir.ID
                      )
                )
                BEGIN
                    EXEC SFin.InvoiceRequestsDelete
                        @Guid = @OrphanRequestGuid;

                    IF NOT EXISTS
                    (
                        SELECT 1
                        FROM SFin.InvoiceAutomationRunDetails AS d
                        WHERE d.RowStatus NOT IN (0, 254)
                          AND d.AutomationRunGuid = @OrphanRunGuid
                          AND d.InstanceKey = CONCAT(N'HISTORIC_ORPHAN_CLEANUP|', CONVERT(NVARCHAR(36), @OrphanRequestGuid))
                    )
                    BEGIN
                        DECLARE @OrphanDetailGuid UNIQUEIDENTIFIER = NEWID();
                        DECLARE @OrphanDetailWasInserted BIT = 0;

                        EXEC SCore.UpsertDataObject
                              @Guid = @OrphanDetailGuid
                            , @SchemeName = N'SFin'
                            , @ObjectName = N'InvoiceAutomationRunDetails'
                            , @IncludeDefaultSecurity = 0
                            , @IsInsert = @OrphanDetailWasInserted OUTPUT;

                        INSERT INTO SFin.InvoiceAutomationRunDetails
                        (
                              RowStatus
                            , Guid
                            , AutomationRunGuid
                            , InvoiceScheduleId
                            , SourceType
                            , SourceGuid
                            , SourceIntId
                            , InstanceType
                            , InstanceKey
                            , Outcome
                            , Message
                            , InvoiceRequestGuid
                            , CreatedDateTimeUTC
                            , LegacyId
                            , LegacySystemID
                        )
                        VALUES
                        (
                              1
                            , @OrphanDetailGuid
                            , @OrphanRunGuid
                            , -1
                            , N''
                            , NULL
                            , NULL
                            , N'InvoiceRequest'
                            , CONCAT(N'HISTORIC_ORPHAN_CLEANUP|', CONVERT(NVARCHAR(36), @OrphanRequestGuid))
                            , N'Cleaned'
                            , CONCAT(N'Soft-deleted ', CONVERT(NVARCHAR(20), @OrphanItemCount), N' active child item(s) beneath an already-deleted invoice request.')
                            , @OrphanRequestGuid
                            , @NowUtc
                            , NULL
                            , -1
                        );
                    END;

                    INSERT INTO #Applied
                    (
                          ActionType
                        , RequestGuid
                        , AutomationRunGuid
                        , InvoiceBatchGuid
                        , AppliedDateTimeUTC
                        , Message
                        , AuditLogged
                    )
                    VALUES
                    (
                          N'ORPHAN_ITEMS_CLEANED'
                        , @OrphanRequestGuid
                        , @OrphanRunGuid
                        , NULL
                        , @NowUtc
                        , CONCAT(N'Soft-deleted ', CONVERT(NVARCHAR(20), @OrphanItemCount), N' orphan child item(s).')
                        , 1
                    );
                END
                ELSE
                BEGIN
                    INSERT INTO #Applied
                    (
                          ActionType
                        , RequestGuid
                        , AutomationRunGuid
                        , InvoiceBatchGuid
                        , AppliedDateTimeUTC
                        , Message
                        , AuditLogged
                    )
                    VALUES
                    (
                          N'SKIPPED_STATE_CHANGED'
                        , @OrphanRequestGuid
                        , @OrphanRunGuid
                        , NULL
                        , @NowUtc
                        , N'Orphan cleanup was skipped because the parent state changed or became transaction-linked after planning.'
                        , 1
                    );
                END;

                UPDATE op
                SET op.Processed = 1
                FROM #OrphanItemPlan AS op
                WHERE op.RequestId = @OrphanRequestId;

                COMMIT TRANSACTION;
            END;
        END;

        IF @LockAcquired = 1
        BEGIN
            EXEC sys.sp_releaseapplock
                  @Resource = @AppLockName
                , @LockOwner = N'Session';

            SET @LockAcquired = 0;
        END;

        /* Final apply result. */
        SELECT
              applied.ActionOrder
            , applied.ActionType
            , applied.RequestGuid
            , applied.AutomationRunGuid
            , applied.InvoiceBatchGuid
            , applied.AppliedDateTimeUTC
            , applied.Message
        FROM #Applied AS applied
        ORDER BY applied.ActionOrder;
    END TRY
    BEGIN CATCH
        IF CURSOR_STATUS('local', 'cur_recovery_run') >= 0
            CLOSE cur_recovery_run;

        IF CURSOR_STATUS('local', 'cur_recovery_run') > -3
            DEALLOCATE cur_recovery_run;

        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        IF @LockAcquired = 1
        BEGIN
            EXEC sys.sp_releaseapplock
                  @Resource = @AppLockName
                , @LockOwner = N'Session';
        END;

        ;THROW;
    END CATCH;
END;
GO
