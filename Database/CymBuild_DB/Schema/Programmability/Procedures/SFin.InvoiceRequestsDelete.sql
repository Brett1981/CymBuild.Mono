/*
    Permanent correction:
    soft-delete active child InvoiceRequestItems, including their DataObjects,
    before soft-deleting the parent InvoiceRequest. This prevents active orphan
    items when a failed automated request is removed.
*/
CREATE OR ALTER PROCEDURE [SFin].[InvoiceRequestsDelete]
    @Guid UNIQUEIDENTIFIER
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @Guid IS NULL
        THROW 60000, N'Invoice request Guid is required.', 1;

    IF NOT EXISTS
    (
        SELECT 1
        FROM SFin.InvoiceRequests AS ir
        WHERE ir.Guid = @Guid
    )
        RETURN;

    /*
        Completed = an active line on an active transaction, the same test SFin.tvf_InvoiceRequests
        uses to hide the request from the Finance grid. A request whose transaction was
        soft-deleted (RowStatus 0/254) or has RowStatus 200 shows in that grid again, so it must
        be deletable too.
    */
    IF EXISTS
    (
        SELECT 1
        FROM SFin.TransactionDetails AS td
        INNER JOIN SFin.InvoiceRequestItems AS iri
            ON iri.ID = td.InvoiceRequestItemId
        INNER JOIN SFin.InvoiceRequests AS ir
            ON ir.ID = iri.InvoiceRequestId
        INNER JOIN SFin.Transactions AS tr
            ON tr.ID = td.TransactionID
        WHERE ir.Guid = @Guid
          AND td.RowStatus NOT IN (0, 254)
          AND iri.RowStatus NOT IN (0, 254)
          AND tr.RowStatus NOT IN (0, 254, 200)
    )
        THROW 60000, N'Cannot delete a completed invoice request.', 1;

    BEGIN TRY
        BEGIN TRANSACTION;

        /* Lock the parent while its children are being soft-deleted. */
        DECLARE @LockedRequestId INT;

        SELECT @LockedRequestId = ir.ID
        FROM SFin.InvoiceRequests AS ir WITH (UPDLOCK, HOLDLOCK)
        WHERE ir.Guid = @Guid;

        /* Re-check after taking the parent lock to close the planning race. */
        IF EXISTS
        (
            SELECT 1
            FROM SFin.TransactionDetails AS td
            INNER JOIN SFin.InvoiceRequestItems AS iri
                ON iri.ID = td.InvoiceRequestItemId
            INNER JOIN SFin.Transactions AS tr
                ON tr.ID = td.TransactionID
            WHERE iri.InvoiceRequestId = @LockedRequestId
              AND td.RowStatus NOT IN (0, 254)
              AND iri.RowStatus NOT IN (0, 254)
              AND tr.RowStatus NOT IN (0, 254, 200)
        )
            THROW 60000, N'Cannot delete a completed invoice request.', 1;

        DECLARE @ItemGuid UNIQUEIDENTIFIER;

        DECLARE cur_child CURSOR LOCAL FAST_FORWARD FOR
        SELECT iri.Guid
        FROM SFin.InvoiceRequestItems AS iri
        INNER JOIN SFin.InvoiceRequests AS ir
            ON ir.ID = iri.InvoiceRequestId
        WHERE ir.Guid = @Guid
          AND iri.RowStatus NOT IN (0, 254)
        ORDER BY iri.ID;

        OPEN cur_child;

        FETCH NEXT FROM cur_child INTO @ItemGuid;

        WHILE @@FETCH_STATUS = 0
        BEGIN
            EXEC SFin.InvoiceRequestItemsDelete
                @Guid = @ItemGuid;

            FETCH NEXT FROM cur_child INTO @ItemGuid;
        END;

        CLOSE cur_child;
        DEALLOCATE cur_child;

        EXEC SCore.DeleteDataObject
            @Guid = @Guid;

        UPDATE ir
        SET ir.RowStatus = 254
        FROM SFin.InvoiceRequests AS ir
        WHERE ir.Guid = @Guid
          AND ir.RowStatus <> 254;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF CURSOR_STATUS('local', 'cur_child') >= 0
            CLOSE cur_child;

        IF CURSOR_STATUS('local', 'cur_child') > -3
            DEALLOCATE cur_child;

        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        ;THROW;
    END CATCH;
END;
GO
