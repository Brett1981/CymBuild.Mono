/* =============================================================================
   CYB-569 - Merge duplicate seeded workflow statuses
   Object: SCore.WorkflowStatusMergeDuplicates

   Problem:
   - Seed data carries two active rows each for "New", "Quoting" and "Declined".
     Workflows built in the app mix both IDs, so a record moved to one copy
     finds no onward transitions (empty Record Status dropdown), and the
     name-based lookups in the upsert procedures pick either copy.

   What this does (mapping from CymBuild_Workflow_Cleanup
   03_Evidence/Workflow_Duplicate_Mapping.csv, keyed by stable Guid):
   - Repoints every reference from the duplicate to the retained status:
     WorkflowTransition From/To, DataObjectTransition Status/OldStatus,
     WorkflowNotificationQueue, WorkflowNotificationQueueErrorLog and
     WorkflowStatusNotificationGroups (sentinel ID = -1 excluded).
   - Widens the retained status visibility to cover the duplicate's.
   - Retires transitions / notification groups made identical by the merge,
     keeping an enabled transition and carrying CanAction over.
   - Retires the duplicate status (RowStatus = 254 + DataObject soft delete).

   Guardrails:
   - Idempotent: safe to re-run; a fully merged duplicate is a no-op.
   - @WhatIf = 1 (default) only reports reference counts.
   - DataObjectTransition rows are preserved; only the status ID they point at
     changes to an identically named status. S_disable_notification_triggers
     is set so tr_DataObjectTransition_QueueWorkflowNotifications (the only
     UPDATE-time notification trigger) never queues emails for the repoint.
     Record-history triggers stay on, so every change is audited.
   - Run once per environment as a release step (QA, UAT, LIVE).
============================================================================= */
CREATE OR ALTER PROCEDURE [SCore].[WorkflowStatusMergeDuplicates]
(
    @WhatIf BIT = 1
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @Map TABLE
    (
        Name           NVARCHAR(100)    NOT NULL,
        DuplicateGuid  UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
        RetainedGuid   UNIQUEIDENTIFIER NOT NULL,
        DuplicateID    INT              NULL,
        RetainedID     INT              NULL
    );

    INSERT INTO @Map (Name, DuplicateGuid, RetainedGuid)
    VALUES
        (N'New',      '9e0a10c7-94a0-4e25-afb1-14240d906c12', '3dab4339-a1c0-4abe-860a-4915a6cf94b6'),
        (N'Quoting',  'b88f95c2-41c9-4cc6-ad9f-d9223c4e852a', '9a60f983-24ba-4733-907e-c5cce0b691cb'),
        (N'Declined', 'b9ba4510-6358-4c0a-bba1-5feb33c54f84', '708c00e6-f45f-4cb2-8e91-a80b8b8e802e');

    UPDATE m
    SET DuplicateID = dup.ID,
        RetainedID  = kept.ID
    FROM @Map AS m
    LEFT JOIN SCore.WorkflowStatus AS dup  ON dup.Guid  = m.DuplicateGuid
    LEFT JOIN SCore.WorkflowStatus AS kept ON kept.Guid = m.RetainedGuid;

    -- Nothing to merge where the duplicate does not exist in this environment.
    DELETE FROM @Map WHERE DuplicateID IS NULL;

    IF EXISTS (SELECT 1 FROM @Map WHERE RetainedID IS NULL)
        THROW 62569, N'A duplicate workflow status exists but its retained status Guid is missing. Nothing was changed.', 1;

    IF EXISTS
    (
        SELECT 1
        FROM @Map AS m
        JOIN SCore.WorkflowStatus AS dup  ON dup.ID  = m.DuplicateID
        JOIN SCore.WorkflowStatus AS kept ON kept.ID = m.RetainedID
        WHERE dup.Name <> m.Name
           OR kept.Name <> m.Name
    )
        THROW 62570, N'A mapped workflow status no longer has the expected name. Nothing was changed.', 1;

    IF EXISTS
    (
        SELECT 1
        FROM @Map AS m
        JOIN SCore.WorkflowStatus AS kept ON kept.ID = m.RetainedID
        WHERE kept.RowStatus IN (0,254)
    )
        THROW 62571, N'A retained workflow status is inactive. Nothing was changed.', 1;

    -- Reference report (before).
    SELECT
        m.Name,
        m.DuplicateID,
        m.RetainedID,
        dup.RowStatus AS DuplicateRowStatus,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowTransition AS wt WHERE wt.FromStatusID = m.DuplicateID OR wt.ToStatusID = m.DuplicateID) AS WorkflowTransitionRefs,
        (SELECT COUNT_BIG(1) FROM SCore.DataObjectTransition AS dot WHERE dot.StatusID = m.DuplicateID OR dot.OldStatusID = m.DuplicateID) AS DataObjectTransitionRefs,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowNotificationQueue AS q WHERE q.StatusId = m.DuplicateID) AS NotificationQueueRefs,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowNotificationQueueErrorLog AS el WHERE el.StatusId = m.DuplicateID) AS NotificationErrorLogRefs,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowStatusNotificationGroups AS ng WHERE ng.WorkflowStatusGuid = m.DuplicateGuid AND ng.ID <> -1) AS NotificationGroupRefs
    FROM @Map AS m
    JOIN SCore.WorkflowStatus AS dup ON dup.ID = m.DuplicateID
    ORDER BY m.Name;

    IF (@WhatIf = 1)
    BEGIN
        PRINT N'[SCore.WorkflowStatusMergeDuplicates] WhatIf only. Re-run with @WhatIf = 0 to apply.';
        RETURN;
    END;

    DECLARE @PreviousDisableNotificationTriggers SQL_VARIANT = SESSION_CONTEXT(N'S_disable_notification_triggers');
    DECLARE @TouchedTransitions TABLE (ID INT NOT NULL PRIMARY KEY);
    DECLARE @RetireTransitions TABLE (ID INT NOT NULL PRIMARY KEY);
    DECLARE @RetiredDataObjects TABLE (Guid UNIQUEIDENTIFIER NULL);
    DECLARE @BatchSize INT = 1000;
    DECLARE @Rows INT;

    BEGIN TRY
        EXEC sys.sp_set_session_context @key = N'S_disable_notification_triggers', @value = 1, @read_only = 0;

        BEGIN TRANSACTION;

        UPDATE kept
        SET ShowInEnquiries = CASE WHEN dup.ShowInEnquiries = 1 THEN CONVERT(BIT, 1) ELSE kept.ShowInEnquiries END,
            ShowInQuotes    = CASE WHEN dup.ShowInQuotes    = 1 THEN CONVERT(BIT, 1) ELSE kept.ShowInQuotes END,
            ShowInJobs      = CASE WHEN dup.ShowInJobs      = 1 THEN CONVERT(BIT, 1) ELSE kept.ShowInJobs END
        FROM SCore.WorkflowStatus AS kept
        JOIN @Map AS m ON m.RetainedID = kept.ID
        JOIN SCore.WorkflowStatus AS dup ON dup.ID = m.DuplicateID
        WHERE (dup.ShowInEnquiries = 1 AND kept.ShowInEnquiries = 0)
           OR (dup.ShowInQuotes    = 1 AND kept.ShowInQuotes    = 0)
           OR (dup.ShowInJobs      = 1 AND kept.ShowInJobs      = 0);

        -- History is repointed in batches: tg_DataObjectTransition_RecordHistory walks
        -- Inserted one row at a time, so a single large UPDATE is quadratic.
        SET @Rows = 1;
        WHILE (@Rows > 0)
        BEGIN
            UPDATE TOP (@BatchSize) dot
            SET StatusID = m.RetainedID
            FROM SCore.DataObjectTransition AS dot
            JOIN @Map AS m ON m.DuplicateID = dot.StatusID;

            SET @Rows = @@ROWCOUNT;
        END;

        SET @Rows = 1;
        WHILE (@Rows > 0)
        BEGIN
            UPDATE TOP (@BatchSize) dot
            SET OldStatusID = m.RetainedID
            FROM SCore.DataObjectTransition AS dot
            JOIN @Map AS m ON m.DuplicateID = dot.OldStatusID;

            SET @Rows = @@ROWCOUNT;
        END;

        INSERT INTO @TouchedTransitions (ID)
        SELECT DISTINCT wt.ID
        FROM SCore.WorkflowTransition AS wt
        JOIN @Map AS m ON m.DuplicateID IN (wt.FromStatusID, wt.ToStatusID);

        UPDATE wt
        SET FromStatusID = m.RetainedID
        FROM SCore.WorkflowTransition AS wt
        JOIN @Map AS m ON m.DuplicateID = wt.FromStatusID;

        UPDATE wt
        SET ToStatusID = m.RetainedID
        FROM SCore.WorkflowTransition AS wt
        JOIN @Map AS m ON m.DuplicateID = wt.ToStatusID;

        -- Retire transitions the merge made redundant: repointed self-loops, and all
        -- but one active row per (Workflow, From, To) where the merge created the clash.
        -- The survivor is an enabled row if there is one, preferring rows the merge did
        -- not touch, so no onward path is lost.
        INSERT INTO @RetireTransitions (ID)
        SELECT wt.ID
        FROM SCore.WorkflowTransition AS wt
        JOIN @TouchedTransitions AS tt ON tt.ID = wt.ID
        WHERE wt.RowStatus NOT IN (0,254)
          AND wt.FromStatusID = wt.ToStatusID;

        INSERT INTO @RetireTransitions (ID)
        SELECT ranked.ID
        FROM
        (
            SELECT
                wt.ID,
                ROW_NUMBER() OVER
                (
                    PARTITION BY wt.WorkflowID, wt.FromStatusID, wt.ToStatusID
                    ORDER BY wt.Enabled DESC, CASE WHEN tt.ID IS NULL THEN 0 ELSE 1 END, wt.ID
                ) AS RowNumber,
                MAX(CASE WHEN tt.ID IS NULL THEN 0 ELSE 1 END) OVER
                (
                    PARTITION BY wt.WorkflowID, wt.FromStatusID, wt.ToStatusID
                ) AS ClashTouched
            FROM SCore.WorkflowTransition AS wt
            LEFT JOIN @TouchedTransitions AS tt ON tt.ID = wt.ID
            WHERE wt.RowStatus NOT IN (0,254)
              AND wt.ID <> -1
              AND NOT EXISTS (SELECT 1 FROM @RetireTransitions AS rt WHERE rt.ID = wt.ID)
        ) AS ranked
        WHERE ranked.ClashTouched = 1
          AND ranked.RowNumber > 1;

        UPDATE wt
        SET RowStatus = 254
        OUTPUT inserted.Guid INTO @RetiredDataObjects (Guid)
        FROM SCore.WorkflowTransition AS wt
        JOIN @RetireTransitions AS rt ON rt.ID = wt.ID;

        UPDATE q
        SET StatusId = m.RetainedID
        FROM SCore.WorkflowNotificationQueue AS q
        JOIN @Map AS m ON m.DuplicateID = q.StatusId;

        UPDATE el
        SET StatusId = m.RetainedID
        FROM SCore.WorkflowNotificationQueueErrorLog AS el
        JOIN @Map AS m ON m.DuplicateID = el.StatusId;

        -- Where a workflow already notifies the same group on the retained status, keep
        -- that row (carrying CanAction over) and retire the duplicate-side row first:
        -- UX_WorkflowStatusNotificationGroups_Workflow_Status_Group would reject the repoint.
        UPDATE kept
        SET CanAction = 1
        FROM SCore.WorkflowStatusNotificationGroups AS kept
        JOIN @Map AS m ON m.RetainedGuid = kept.WorkflowStatusGuid
        WHERE kept.ID <> -1
          AND kept.RowStatus NOT IN (0,254)
          AND kept.CanAction = 0
          AND EXISTS
          (
              SELECT 1
              FROM SCore.WorkflowStatusNotificationGroups AS dup
              WHERE dup.WorkflowStatusGuid = m.DuplicateGuid
                AND dup.WorkflowID = kept.WorkflowID
                AND dup.GroupID = kept.GroupID
                AND dup.ID <> -1
                AND dup.RowStatus NOT IN (0,254)
                AND dup.CanAction = 1
          );

        UPDATE dup
        SET RowStatus = 254
        OUTPUT inserted.Guid INTO @RetiredDataObjects (Guid)
        FROM SCore.WorkflowStatusNotificationGroups AS dup
        JOIN @Map AS m ON m.DuplicateGuid = dup.WorkflowStatusGuid
        WHERE dup.ID <> -1
          AND dup.RowStatus NOT IN (0,254)
          AND EXISTS
          (
              SELECT 1
              FROM SCore.WorkflowStatusNotificationGroups AS kept
              WHERE kept.WorkflowStatusGuid = m.RetainedGuid
                AND kept.WorkflowID = dup.WorkflowID
                AND kept.GroupID = dup.GroupID
                AND kept.ID <> -1
                AND kept.RowStatus NOT IN (0,254)
          );

        UPDATE ng
        SET WorkflowStatusGuid = m.RetainedGuid
        FROM SCore.WorkflowStatusNotificationGroups AS ng
        JOIN @Map AS m ON m.DuplicateGuid = ng.WorkflowStatusGuid
        WHERE ng.ID <> -1;

        UPDATE dup
        SET RowStatus = 254
        OUTPUT inserted.Guid INTO @RetiredDataObjects (Guid)
        FROM SCore.WorkflowStatus AS dup
        JOIN @Map AS m ON m.DuplicateID = dup.ID
        WHERE dup.RowStatus NOT IN (0,254);

        UPDATE d
        SET RowStatus = 254
        FROM SCore.DataObjects AS d
        JOIN @RetiredDataObjects AS r ON r.Guid = d.Guid
        WHERE d.RowStatus NOT IN (0,254);

        COMMIT TRANSACTION;

        EXEC sys.sp_set_session_context @key = N'S_disable_notification_triggers', @value = @PreviousDisableNotificationTriggers, @read_only = 0;
    END TRY
    BEGIN CATCH
        IF (@@TRANCOUNT > 0)
            ROLLBACK TRANSACTION;

        EXEC sys.sp_set_session_context @key = N'S_disable_notification_triggers', @value = @PreviousDisableNotificationTriggers, @read_only = 0;
        THROW;
    END CATCH;

    -- Result report (after).
    SELECT
        m.Name,
        m.DuplicateID,
        m.RetainedID,
        dup.RowStatus AS DuplicateRowStatus,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowTransition AS wt WHERE wt.FromStatusID = m.DuplicateID OR wt.ToStatusID = m.DuplicateID) AS WorkflowTransitionRefs,
        (SELECT COUNT_BIG(1) FROM SCore.DataObjectTransition AS dot WHERE dot.StatusID = m.DuplicateID OR dot.OldStatusID = m.DuplicateID) AS DataObjectTransitionRefs,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowNotificationQueue AS q WHERE q.StatusId = m.DuplicateID) AS NotificationQueueRefs,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowNotificationQueueErrorLog AS el WHERE el.StatusId = m.DuplicateID) AS NotificationErrorLogRefs,
        (SELECT COUNT_BIG(1) FROM SCore.WorkflowStatusNotificationGroups AS ng WHERE ng.WorkflowStatusGuid = m.DuplicateGuid AND ng.ID <> -1) AS NotificationGroupRefs
    FROM @Map AS m
    JOIN SCore.WorkflowStatus AS dup ON dup.ID = m.DuplicateID
    ORDER BY m.Name;
END;
GO
