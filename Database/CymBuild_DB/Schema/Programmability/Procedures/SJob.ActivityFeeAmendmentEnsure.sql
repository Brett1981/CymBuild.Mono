/*
	[CYB-333] Activity-Based Fee Amendments.

	A billable activity answered "No" to "Is part of the agreed fee?" needs a fee amendment so the
	extra fee is added to the job's agreed fee instead of drawing down from it. This procedure
	raises that amendment, linked to the activity, the first time it is called for the activity and
	returns the existing one on every later call.

	The amendment is created Pending, so it does not change the Job Fees table until a user sets
	it to Agreed (SJob.Job_FeeDrawdown only counts Agreed and legacy amendments). The activity's
	fee, as it is invoiced (Invoicing Value, otherwise the surveyor's Billable Rate x Invoicing
	Quantity), is pre-filled as the change for its RIBA stage: the fixed stage columns for the
	standard stages, a SJob.CustomFeeAmendment row for a custom stage. SJob.ActivitiesUpsert
	requires the stage; the fee is zero on job types that do not use timesheets, where the user
	enters it on the amendment.

	Returns one row: FeeAmendmentGuid (zero Guid when no amendment is needed), JobGuid,
	JobEntityTypeGuid and WasCreated.
*/
CREATE OR ALTER PROCEDURE [SJob].[ActivityFeeAmendmentEnsure]
	(
		@ActivityGuid UNIQUEIDENTIFIER
	)
AS
	BEGIN
		SET NOCOUNT ON
		SET XACT_ABORT ON

		DECLARE	@PendingFeeAmendmentStatusGuid UNIQUEIDENTIFIER = '68C95270-1BB9-4E8B-BE4C-38746C4661BB',
				@EmptyGuid UNIQUEIDENTIFIER = '00000000-0000-0000-0000-000000000000',
				@ActivityId BIGINT,
				@JobId INT,
				@JobGuid UNIQUEIDENTIFIER,
				@Title NVARCHAR(250),
				@ActivityFee DECIMAL(19,2),
				@StageId INT,
				@StageGuid UNIQUEIDENTIFIER,
				@StageNumber INT,
				@IsCustomStage BIT,
				@IsRequired BIT = 0,
				@FeeAmendmentGuid UNIQUEIDENTIFIER,
				@WasCreated BIT = 0,
				@UserId INT = CONVERT(INT, SESSION_CONTEXT(N'user_id')),
				@UserGuid UNIQUEIDENTIFIER

		BEGIN TRANSACTION

		-- Lock the activity row so a double save cannot raise two amendments for it.
		SELECT	@ActivityId = a.ID,
				@JobId = a.JobID,
				@Title = a.Title,
				-- The activity's fee as SJob.ActivityCreateInvoiceRequest invoices it.
				@ActivityFee = CASE WHEN a.InvoicingValue > 0 THEN a.InvoicingValue ELSE (ISNULL(i.BillableRate, 0) * a.InvoicingQuantity) END,
				@StageId = a.RibaStageId,
				@IsRequired = CASE WHEN at.IsBillable = 1 AND a.IsPartOfAgreedFee = 0 THEN 1 ELSE 0 END
		FROM	SJob.Activities AS a WITH (UPDLOCK, HOLDLOCK)
		JOIN	SJob.ActivityTypes AS at ON (at.ID = a.ActivityTypeID)
		LEFT JOIN SJob.Jobs AS fj ON (fj.ID = a.JobID)
		LEFT JOIN SCore.Identities AS i ON (i.ID = fj.SurveyorID)
		WHERE	(a.[Guid] = @ActivityGuid)
			AND	(a.RowStatus NOT IN (0,254))

		SELECT	@JobGuid = j.[Guid]
		FROM	SJob.Jobs AS j
		WHERE	(j.ID = @JobId)
			AND	(j.ID > 0)

		SELECT	@FeeAmendmentGuid = fa.[Guid]
		FROM	SJob.FeeAmendment AS fa
		WHERE	(fa.ActivityID = @ActivityId)
			AND	(fa.RowStatus NOT IN (0,254))

		IF (@FeeAmendmentGuid IS NULL AND @IsRequired = 1 AND @JobGuid IS NOT NULL)
		BEGIN
			IF NOT EXISTS (SELECT 1 FROM SJob.FeeAmendmentStatus AS fas WHERE (fas.[Guid] = @PendingFeeAmendmentStatusGuid))
			BEGIN
				;THROW 60000, N'The Pending fee amendment status does not exist.', 1;
			END

			SELECT	@UserGuid = i.[Guid]
			FROM	SCore.Identities AS i
			WHERE	(i.ID = @UserId)

			SET @UserGuid = ISNULL(@UserGuid, @EmptyGuid)

			SELECT	@StageGuid = rs.[Guid],
					@StageNumber = rs.Number,
					@IsCustomStage = rs.IsCustomStage
			FROM	SJob.RibaStages AS rs
			WHERE	(rs.ID = @StageId)
				AND	(rs.ID > 0)

			DECLARE	@Change DECIMAL(9,2) = ISNULL(@ActivityFee, 0),
					@Reason NVARCHAR(MAX) = N'Activity not part of the agreed fee: ' + ISNULL(@Title, N''),
					@Today DATE = CONVERT(DATE, GETUTCDATE()),
					@IsFixedStage BIT = CASE WHEN @IsCustomStage = 0 AND @StageNumber IN (0, 1, 2, 3, 4, 5, 6, 7, 99, 999) THEN 1 ELSE 0 END

			DECLARE	@S0 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 0 THEN @Change ELSE 0 END,
					@S1 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 1 THEN @Change ELSE 0 END,
					@S2 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 2 THEN @Change ELSE 0 END,
					@S3 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 3 THEN @Change ELSE 0 END,
					@S4 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 4 THEN @Change ELSE 0 END,
					@S5 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 5 THEN @Change ELSE 0 END,
					@S6 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 6 THEN @Change ELSE 0 END,
					@S7 DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 7 THEN @Change ELSE 0 END,
					@PreCon DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 99 THEN @Change ELSE 0 END,
					@Con DECIMAL(9,2) = CASE WHEN @IsFixedStage = 1 AND @StageNumber = 999 THEN @Change ELSE 0 END,
					@UpsertPass INT = 1

			SET @FeeAmendmentGuid = NEWID()

			-- A custom-stage change lives in a child row, so the amendment is saved a second time
			-- to include it in New Total Agreed Fee.
			WHILE (@UpsertPass <= CASE WHEN @IsCustomStage = 1 THEN 2 ELSE 1 END)
			BEGIN
				EXEC SJob.FeeAmendmentsUpsert
					@JobGuid = @JobGuid,
					@RibaStage0Change = @S0, @RibaStage1Change = @S1, @RibaStage2Change = @S2, @RibaStage3Change = @S3,
					@RibaStage4Change = @S4, @RibaStage5Change = @S5, @RibaStage6Change = @S6, @RibaStage7Change = @S7,
					@RibaStage0VisitChange = 0, @RibaStage1VisitChange = 0, @RibaStage2VisitChange = 0, @RibaStage3VisitChange = 0,
					@RibaStage4VisitChange = 0, @RibaStage5VisitChange = 0, @RibaStage6VisitChange = 0, @RibaStage7VisitChange = 0,
					@RibaStage0MeetingChange = 0, @RibaStage1MeetingChange = 0, @RibaStage2MeetingChange = 0, @RibaStage3MeetingChange = 0,
					@RibaStage4MeetingChange = 0, @RibaStage5MeetingChange = 0, @RibaStage6MeetingChange = 0, @RibaStage7MeetingChange = 0,
					@PreConstructionStageChange = @PreCon,
					@ConstructionStageChange = @Con,
					@PreConstructionStageMeetingChange = 0,
					@PreConstructionStageVisitChange = 0,
					@ConstructionStageMeetingChange = 0,
					@ConstructionStageVisitChange = 0,
					@FeeCapChange = 0,
					@Guid = @FeeAmendmentGuid,
					@Reason = @Reason,
					@DateReceivedRequest = @Today,
					@DateAgreed = NULL,
					@OriginalAgreedFee = 0,
					@NewTotalAgreedFee = 0,
					@Comments = N'',
					@RejectionReason = NULL,
					@FeeAmendmentStatusGuid = @PendingFeeAmendmentStatusGuid,
					@SendToContactGuid = @EmptyGuid,
					@RequestedByUserGuid = @UserGuid,
					@AgreedStatusByUserGuid = @EmptyGuid

				IF (@UpsertPass = 1)
				BEGIN
					UPDATE	SJob.FeeAmendment
					SET		ActivityID = @ActivityId
					WHERE	([Guid] = @FeeAmendmentGuid)

					IF (@IsCustomStage = 1)
					BEGIN
						DECLARE @CustomFeeAmendmentGuid UNIQUEIDENTIFIER = NEWID()

						EXEC SJob.CustomFeeAmendmentUpsert
							@Guid = @CustomFeeAmendmentGuid,
							@StageChange = @Change,
							@StageMeetingChange = 0,
							@StageVisitChange = 0,
							@Reason = @Reason,
							@StageGuid = @StageGuid,
							@FeeAmendmentGuid = @FeeAmendmentGuid,
							@CreatedByUserGuid = @UserGuid
					END
				END

				SET @UpsertPass += 1
			END

			SET @WasCreated = 1
		END

		COMMIT TRANSACTION

		SELECT	ISNULL(@FeeAmendmentGuid, @EmptyGuid) AS FeeAmendmentGuid,
				ISNULL(@JobGuid, @EmptyGuid) AS JobGuid,
				ISNULL(et.[Guid], @EmptyGuid) AS JobEntityTypeGuid,
				@WasCreated AS WasCreated
		FROM	(SELECT 1 AS One) AS x
		LEFT JOIN SCore.DataObjects AS dob ON (dob.[Guid] = @JobGuid)
		LEFT JOIN SCore.EntityTypes AS et ON (et.ID = dob.EntityTypeId)
	END
GO
